"""gen_menu_padlayout.py - ui/coop_padlayout.urc, the CONTROLLER LAYOUT page (v1.10.46).

user: "we need a place for players to rebind their controller controls (and it should use a controller image like modern games do)".
A picture of the connected pad (Xbox / PlayStation / generic, chosen by ui_padPic, which the engine's ui_padbinds sets from the
Auto-detected in_padType) above two columns of rows. Each row: the button's own icon (coop_pg_x_NN / coop_pg_p_NN), its name, and
what it does now (ui_padb_<BUTTON>, filled by ui_padbinds). Pressing A on a row (or clicking it) steps it to the next action
(padbind_cycle <BUTTON>); the small "<" before it steps back. Reached from Options > Controls > AIM / SENSITIVITY > CONTROLLER LAYOUT,
which runs "ui_padbinds" first so the labels are current.
    python docs/tools/gen_menu_padlayout.py [mod dir]
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MOD = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "hzm-mohaa-coop-mod")
out = []


def w(s):
    out.append(s)


def label(name, title, x, y, wd, h=14, fg="0.84 0.82 0.76 1.00", extra=""):
    w('resource\nLabel\n{\n\tname "%s"\n\ttitle "%s"\n\trect %d %d %d %d\n\tfgcolor %s\n\tbgcolor 0.00 0.00 0.00 0.00\n\tborderstyle "NONE"\n\tfont "verdana-12"\n%s}'
      % (name, title, x, y, wd, h, fg, extra))


def pic(name, shader, x, y, wd, h, cvar):
    w('resource\nLabel\n{\n\tname "%s"\n\trect %d %d %d %d\n\tfgcolor 1.00 1.00 1.00 1.00\n\tbgcolor 0.00 0.00 0.00 0.00\n\tborderstyle "NONE"\n\tshader "%s"\n\tenabledcvar "%s"\n}'
      % (name, x, y, wd, h, shader, cvar))


def button(name, title, x, y, wd, cmd, snd="apply", h=18, border="3D_BORDER", bg="0.09 0.10 0.13 0.90", fg="0.84 0.82 0.76 1.00"):
    w('resource\nButton\n{\n\tname "%s"\n\ttitle "%s"\n\trect %d %d %d %d\n\tfgcolor %s\n\tbgcolor %s\n\tborderstyle "%s"\n\tfont "verdana-12"\n\tclicksound "sound/menu/%s.wav"\n\tstuffcommand "%s"\n}'
      % (name, title, x, y, wd, h, fg, bg, border, snd, cmd))


# (engine button, glyph cell (-1 = no icon), Xbox name, PlayStation name)
LEFT = [("LEFTTRIGGER", 6, "LT", "L2"), ("LEFTSHOULDER", 4, "LB", "L1"), ("LEFTSTICK_CLICK", 12, "L3", "L3"),
        ("DPAD_UP", 8, "D-pad up", "D-pad up"), ("DPAD_DOWN", 9, "D-pad down", "D-pad down"), ("DPAD_LEFT", 10, "D-pad left", "D-pad left"),
        ("DPAD_RIGHT", 11, "D-pad right", "D-pad right"), ("BACK", 14, "View", "Create"), ("MISC1", -1, "Share", "Mic")]
RIGHT = [("RIGHTTRIGGER", 7, "RT", "R2"), ("RIGHTSHOULDER", 5, "RB", "R1"), ("RIGHTSTICK_CLICK", 13, "R3", "R3"),
         ("Y", 3, "Y", "Triangle"), ("B", 1, "B", "Circle"), ("A", 0, "A", "Cross"), ("X", 2, "X", "Square"),
         ("START", 15, "Menu", "Options"), ("TOUCHPAD", -1, "Touchpad", "Touchpad")]

w('// HZM coop - CONTROLLER LAYOUT. GENERATED by docs/tools/gen_menu_padlayout.py - do not hand-edit.')
w('// Pad art: CC0 "8th gen console vector gamepad collection" (OpenGameArt); icons: docs/tools/gen_pad_glyphs.py; layout + binds: engine ui_padbinds / padbind_cycle.')
w('menu "coop_padlayout" 640 480 NONE 1\nborderstyle NONE\nbgcolor 0 0 0 0\nalign centerx centery\nvirtualres 1\nfullscreen 0\n\ndirection from_top 0\n')
w('resource\nLabel\n{\n\tordernumber 50\n\tname "bg"\n\trect 0 0 640 480\n\tfgcolor 0.84 0.82 0.76 1.00\n\tbgcolor 0.05 0.06 0.08 1.00\n\tborderstyle "NONE"\n}')
label("title", "CONTROLLER LAYOUT", 220, 10, 200, fg="0.88 0.83 0.66 1.00")
label("hint", "Select a button and press A (or click) to change what it does. < steps back.", 40, 26, 560, fg="0.60 0.58 0.52 1.00")
# the pad picture, 2:1, one per family
for fam in ("xbox", "ps", "generic"):
    pic("pad_" + fam, "textures/hud/coop_pad_%s" % fam, 180, 42, 280, 140, "ui_padPic==%s" % fam)


def rows(lst, x0, col):
    y = 194
    for i, (btn, cell, xn, pn) in enumerate(lst):
        if cell >= 0:
            pic("ic%s_x" % btn, "textures/hud/coop_pg_x_%02d" % cell, x0, y - 1, 16, 16, "ui_padPic!=ps")
            pic("ic%s_p" % btn, "textures/hud/coop_pg_p_%02d" % cell, x0, y - 1, 16, 16, "ui_padPic==ps")
        label("nm%s_x" % btn, xn, x0 + 20, y, 70, extra='\tenabledcvar "ui_padPic!=ps"\n')
        label("nm%s_p" % btn, pn, x0 + 20, y, 70, extra='\tenabledcvar "ui_padPic==ps"\n')
        button("bk%s" % btn, "<", x0 + 94, y - 2, 16, "padbind_cycle %s -1" % btn)
        # the action: a Label showing the current bind under a transparent Button that steps it forward
        label("act%s" % btn, "", x0 + 114, y, 170, fg="0.45 0.80 0.45 1.00", extra='\tlinkcvar "ui_padb_%s"\n' % btn)
        button("cy%s" % btn, "", x0 + 112, y - 2, 176, "padbind_cycle %s" % btn, border="NONE", bg="0.20 0.22 0.26 0.35", fg="0.00 0.00 0.00 0.00")
        y += 26


rows(LEFT, 24, 0)
rows(RIGHT, 330, 1)
DEF = "exec coop_mod/cfg/coop_padbinds_default.cfg ; ui_padbinds"
button("btnDefaults", "RESET TO DEFAULTS", 40, 458, 200, DEF)
button("btnBack", "BACK", 470, 458, 120, "popmenu 0", "back")
w("end.")

p = os.path.join(MOD, "ui", "coop_padlayout.urc")
open(p, "w", newline="\r\n").write("\n".join(out) + "\n")
print("wrote", p)
