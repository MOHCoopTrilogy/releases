def _journal(disc, level, files, lines, jn, log):
    """[flfix2 round 22] the mission journal Frontline shows before the level (DATA/SHELL/<level>_BLOG.VIV: one SHPX
    image per page, j<level>_pg<n>.xsh, 1024 x 512 DXT1 with the 640 x 448 screen in its top-left corner and the text
    baked into the art). Each page is cut to jn["crop"] (the book, above the console's button prompts, which mean
    nothing on a PC), stretched to jn["size"] (a power of two) and written as textures/fl/<level>/journal<n>.tga in the
    converted pak; level.fl_journal[n] names it for the mission script's HUD pages, fl_journal_aspect = the crop's
    height / width so the page is drawn undistorted. Local only, like every other disc-derived file."""
    import shpx
    try:
        from PIL import Image
    except ImportError:
        log("journal: PIL missing, pages not written")
        return
    try:
        mem = disc.viv_members(jn["viv"].format(L=level.upper()))
    except KeyError:
        log("journal: no", jn["viv"].format(L=level.upper()))
        return
    x0, y0, x1, y1 = jn["crop"]
    W, H = jn["size"]
    n = 0
    for k in range(1, int(jn.get("pages", 9)) + 1):   # [anvil] "pages" caps it (1_3: page 4 is an orphan page)
        name = next((m for m in mem if m.lower() == f"j{level}_pg{k}.xsh"), None)
        if name is None:
            break
        img = list(shpx.decode(mem[name]))
        if not img:
            break
        t = img[0]
        if t.get("rgba") is None and len(mem[name]) >= t["w"] * t["h"] * 2:
            # [anvil 1_3] the last 1_3 page is a 640 x 448 linear 16-bit RGB565 image (SHPX type 120), not DXT1:
            # pixels are the file's last w*h*2 bytes (checked by eye against the page layout)
            import numpy as np
            raw_ = np.frombuffer(mem[name][-t["w"] * t["h"] * 2:], dtype="<u2").reshape(t["h"], t["w"]).astype(np.uint32)
            rgb_ = np.dstack([((raw_ >> 11) & 31) * 255 // 31, ((raw_ >> 5) & 63) * 255 // 63, (raw_ & 31) * 255 // 31,
                              np.full_like(raw_, 255)]).astype(np.uint8)
            t = dict(t, rgba=rgb_.tobytes())
        im = Image.frombytes("RGBA", (t["w"], t["h"]), bytes(t["rgba"])).crop((x0, y0, x1, y1)).resize((W, H), Image.LANCZOS)
        im.putalpha(255)
        n += 1
        rel = f"textures/fl/{level}/journal{n}.tga"
        # uncompressed 32-bit TGA, origin lower-left (flconvert.tga_bytes' layout)
        files[rel] = (struct.pack("<BBBHHBHHHHBB", 0, 0, 2, 0, 0, 0, 0, 0, W, H, 32, 8)
                      + im.transpose(Image.FLIP_TOP_BOTTOM).tobytes("raw", "BGRA"))
        lines.append(f'\tlevel.fl_journal[{n}] = "{rel}"')
    lines.append(f"\tlevel.fl_journal_n = {n}")
    lines.append(f"\tlevel.fl_journal_aspect = {(y1 - y0) / float(x1 - x0):.4f}")
    log("journal pages", n)


def _pitch_parms(row):
    """[decodeaudit r100, aems] a SOMI / SOMA row's pitch range (0x1000 = 1.0; the PLAYSOUND player draws a uniform value
    in lo..hi, 0x55810) -> MOHAA soundparms 'pitch pitchRandom' (snd_dma_new.cpp: pitch = base + random() * mod)"""
    lo, hi = row.get("pitch", (4096, 4096))
    if lo == hi == 4096 or not lo:
        return "1.0 0.0"
    return "%.3f %.3f" % (lo / 4096.0, (hi - lo) / 4096.0)


def _prop_sounds(disc, L, level, files, lines, ali, tmp, d, vgm, psp, log):
    """[anvil] fl_levels "prop_sounds": [{name, rec, sound, som, bank, min, max}] - the record's own PLAYSOUND(sound)
    through its sound set (link category 11) and <l>propSnd.som, decoded from the player's bank like the fire loop.
    [decodeaudit r100] "set" instead of "rec": a sound set no placed record links (a class's own: 454 = the jeep
    gunner's grunt). Every entry first..last of the row is taken, as the PLAYSOUND player picks one uniformly
    (0x55810): a row of several becomes the numbered set <alias>1..N (MOHAA plays one at random when the base name is
    played), each with the row's pitch range. A single-entry row keeps its one alias as before"""
    pre = f"fl{level.replace('_', '')}_ps"
    sdir = f"sound/fl/{level}/"
    recs = {e.get("i"): e for e in L.entities()}
    for ps in psp:
        som = L.files.get(ps["som"], b"")
        if "set" in ps:
            sets_, subs_ = [ps["set"]], []
        else:
            e = recs.get(ps["rec"])
            if e is None:
                log("prop sound", ps["name"], "record missing")
                continue
            sets_ = [x & 0xFFFF for x in flscene.words(e)[13:] if x >> 16 == 11]
            subs_ = [x & 0xFFFF for x in flscene.words(e)[13:] if x >> 16 == 12] if ps.get("sub_link") else []
        row = flaudio.som_sound(som, sets_[0], ps["sound"], subs_[0] if subs_ else None) if sets_ else None
        if not row:
            log("prop sound", ps["name"], "no row for set", sets_, "sound", ps["sound"])
            continue
        abk = disc.read(d + ps["bank"])
        bnk_path = os.path.join(tmp, "ps_%s.bnk" % ps["name"])
        with open(bnk_path, "wb") as f:
            f.write(abk[abk.find(b"BNKl"):])
        ents_ = list(range(row["first"], row["last"] + 1)) or [row["first"]]
        multi = len(ents_) > 1
        alias = f"{pre}_{ps['name']}"
        got, first_len = 0, None
        for k, ent in enumerate(ents_, 1):
            stream = flaudio.bank_stream(abk, row["code"], ent)
            sfx = str(k) if multi else ""
            dst = os.path.join(tmp, "ps_%s%s.wav" % (ps["name"], sfx))
            if not (stream and flaudio.vgm_decode(vgm, bnk_path, dst, stream)):
                log("prop sound", ps["name"], "entry", ent, "decode failed", row, stream)
                continue
            got += 1
            rel = f"{sdir}ps_{ps['name']}{sfx}.wav"
            files[rel] = flaudio.wav_mono(dst)
            ali.append(f'aliascache {alias}{sfx} {rel} soundparms {row["volume"]:.2f} 0.0 {_pitch_parms(row)} {ps.get("min", 384)} {ps.get("max", 4000)} auto loaded maps "coop_fl"')
            if first_len is None:
                first_len = flaudio.wav_seconds(dst)
            log("prop sound", ps["name"] + sfx, "set", sets_[0], "row", row, "entry", ent, "stream", stream, f"{flaudio.wav_seconds(dst):.2f} s")
        if not got:
            continue
        lines.append(f'	level.fl_psnd["{ps["name"]}"] = "{alias}"')
        lines.append(f'	level.fl_psnd_len["{ps["name"]}"] = {first_len:.2f}')


def _vehicle_engines(disc, level, files, lines, ali, tmp, d, vgm, vep, log):
    """[decodeaudit 2026-11-23, gap 11] fl_levels "vehicle_engines": [{name, type, bank, min, max}] - the engine loops
    the vehicle bank's graph gives that vehicle type (flaudio.vehicle_loops: idle = on at a low running level, drive =
    on from a higher one). -> level.fl_veh_snd["<name>_idle" / "<name>_drive"] = alias; a type whose slot is empty
    gets nothing (the original plays nothing for it)."""
    pre = f"fl{level.replace('_', '')}_veh"
    sdir = f"sound/fl/{level}/"
    for ve in vep:
        abk = disc.read(d + ve["bank"])
        loops = flaudio.vehicle_loops(abk, ve["type"])
        # [decodeaudit r100, aems] "level" / "begin_dist_m": the module's arguments as the vehicle sends them, once at
        # begin and never updated (bp_tank.log: running level 8, 49.1 m) -> each loop's pitch and the frozen volume
        # from the bank's own tables (flaudio.vehicle_params); both loops on at that level play together for the
        # vehicle's life. Without "level": the old full-volume, pitch 1.0 aliases
        parms = flaudio.vehicle_params(abk, ve["type"], ve["level"], ve.get("begin_dist_m", 0.0)) if "level" in ve else {}
        live = flaudio.bnk_live_streams(abk)
        bnk_path = os.path.join(tmp, "veh.bnk")
