def _projgens(L, X, lines, log, grid=None):
    """[flfix2 round 22] Frontline's projectile generators (.bpd kind 10, flscene.projgen): where each fires from, the
    named path it spreads its burst along (shot s of N aims at (s + 0.5) / N of the path's length, grounded like
    level.fl_npath), its rate, burst, bursts per switch-on and pause, whether its round is a bullet or a rocket
    (weapbul_medium.dat, read only for that label), whether it plays the MG42 sound, and the trigger that switches it
    on (message 357 over a shared category-6 link) with the slot that sends it. A record without a behaviour class is
    never created by the original (1_1 rec 212): listed with fl_pg_on 0 so nothing builds it."""
    wb = flscene.weapbul(L.files.get("weapbul_medium.dat", b""))
    npaths = L.named_paths()
    ents = L.entities()
    n = 0
    for e in ents:
        p = flscene.projgen(e)
        if p is None:
            continue
        n += 1
        k = n
        name = wb.get(p["proj"], "") if p["proj"] else ""
        kind = "rocket" if re.search(r"PANZER|SCHRECK|FAUST|BAZOOKA", name) else ("bullet" if name else "none")
        lines.append(f"\tlevel.fl_pg[{k}] = {_vec(X(e['pos']))}")
        lines.append(f"\tlevel.fl_pg_rec[{k}] = {e['i']}")
        lines.append(f"\tlevel.fl_pg_on[{k}] = {1 if p['cls'] else 0}")
        lines.append(f'\tlevel.fl_pg_kind[{k}] = "{kind}"')
        lines.append(f"\tlevel.fl_pg_sound[{k}] = {1 if p['sound'] else 0}")
        lines.append(f"\tlevel.fl_pg_rate[{k}] = {p['rate']:.2f}")
        lines.append(f"\tlevel.fl_pg_burst[{k}] = {p['burst'][1]}")
        lines.append(f"\tlevel.fl_pg_burst0[{k}] = {p['burst'][0]}")
        lines.append(f"\tlevel.fl_pg_cycles[{k}] = {p['cycles']}")
        lines.append(f"\tlevel.fl_pg_pause0[{k}] = {p['pause'][0]:.1f}")
        lines.append(f"\tlevel.fl_pg_pause1[{k}] = {p['pause'][1]:.1f}")
        lines.append(f"\tlevel.fl_pg_path[{k}] = {p['path']}")
        # the burst's aim points along the named path, by length
        pts = []
        for q in npaths.get(p["path"], []):
            g = X(q)
            if grid is not None:
                gz = grid.ground(g[0], g[1], g[2] + 64, g[2] - 128)
                if gz is not None:
                    g = (g[0], g[1], gz + 2.0)
            pts.append(g)
        nb = max(1, p["burst"][1])
        if len(pts) >= 2:
            seg = [math.dist(pts[i], pts[i + 1]) for i in range(len(pts) - 1)]
            tot = sum(seg) or 1.0
            for s_ in range(nb):
                t, i = (s_ + 0.5) / nb * tot, 0
                while i < len(seg) - 1 and t > seg[i]:
                    t -= seg[i]
                    i += 1
                a = min(1.0, t / (seg[i] or 1.0))
                q = tuple(pts[i][j] + (pts[i + 1][j] - pts[i][j]) * a for j in range(3))
                lines.append(f"\tlevel.fl_pg_aim[{k}][{s_ + 1}] = {_vec(q)}")
        lines.append(f"\tlevel.fl_pg_aim_n[{k}] = {nb if len(pts) >= 2 else 0}")
        # the switch: a record sharing a category-6 link whose slot sends 357 (0 enter, 1 leave, 2 object enters ...)
        l6 = {i for c, i in flscene.links(e) if c == 6}
        nt = 0
        for t_ in ents:
            if t_ is e or not l6 & {i for c, i in flscene.links(t_) if c == 6}:
                continue
            for sl in range(5):
                if 357 in flscene.slots(t_, sl):
                    nt += 1
                    w = flscene.words(t_)
                    lines.append(f"\tlevel.fl_pg_trig[{k}][{nt}] = {_vec(X(t_['pos']))}")
                    lines.append(f"\tlevel.fl_pg_trig_r[{k}][{nt}] = {flscene.radius_m(t_) * X.s:.0f}")
                    lines.append(f"\tlevel.fl_pg_trig_rec[{k}][{nt}] = {t_['i']}")
                    lines.append(f"\tlevel.fl_pg_trig_slot[{k}][{nt}] = {sl}")
        lines.append(f"\tlevel.fl_pg_trig_n[{k}] = {nt}")
        log("projgen", e["i"], "on" if p["cls"] else "never created", kind, "path", p["path"], "rate", p["rate"],
            "burst", p["burst"], "cycles", p["cycles"], "pause", p["pause"], "switch", nt)
    lines.append(f"\tlevel.fl_pg_n = {n}")


