#!/usr/bin/env python3
"""Level pack: everything a converted level needs besides its BSP - generated
on the player's PC from their own disc, written only into the generated pk3.

  maps/fl_<l>_data.scr   level vars our committed mission script reads:
                         objective/hint text (chars.bum), dialogue cue aliases
                         + subtitles + lengths, entity placements, music paths
  ubersound/fl_<l>.scr   aliases for the dialogue cues
  sound/fl/<l>/*.wav     dialogue cues (vgmstream decode of the ScrBnk bank)
  sound/music/fl_<l>_*.wav  the level's music segments (22050 Hz stereo PCM -
                         the tmstart streamer's native rate)
Our own code. Decoding: vgmstream (ISC), built locally from source.
"""
import json
import math
import os
import re
import subprocess
import tempfile

import flaudio

HERE = os.path.dirname(os.path.abspath(__file__))

AXIS_RX = re.compile(r"^(Soldier[ABC]_|TransHangout_|Soldier_Say|InterrogationOfficer|SoldierA_MachineGunNest)")
ALLY_RX = re.compile(r"^(AlliedSoldier_A$|InterrogationVictim$)")
HEALTH = {"Health10": 10, "Health25": 25, "Health50": 50}


MAP_TOKEN_RX = re.compile(r'^(\s*(?:alias|aliascache)\s+(\S+)\s.*?maps\s+")([^"]*)(".*)$', re.I)


def alias_bridge(mohaa_base, mapname):
    """Sound aliases are filtered per map by name prefix ("maps "m1 m2 ... train""). A converted map named
    mfl_* matches only lists holding a plain "m" token, so the generic AA/coop sounds tied to m1..m6 (AI
    grunts, rain loops, doors...) would be silent. Re-declare every alias whose list holds an AA campaign
    token (m, m1..m6) with maps "mfl", read from the player's own install. Last definition wins, pak order."""
    import glob
    import zipfile
    defs = {}
    paks = []
    for game in ("main", "mainta", "maintt"):
        paks += sorted(glob.glob(os.path.join(mohaa_base, game, "*.pk3")), key=str.lower)
    for pk in paks:
        try:
            z = zipfile.ZipFile(pk)
        except Exception:
            continue
        for n in sorted(z.namelist()):
            if not (n.lower().startswith("ubersound/") and n.lower().endswith(".scr")):
                continue
            for line in z.read(n).decode("latin-1").splitlines():
                m = MAP_TOKEN_RX.match(line)
                if not m:
                    continue
                toks = [t.lower() for t in m.group(3).split()]
                if any(mapname.lower().startswith(t) for t in toks):
                    continue
                if any(t == "m" or (len(t) == 2 and t[0] == "m" and t[1] in "123456") for t in toks):
                    defs[m.group(2).lower()] = m.group(1) + "mfl" + m.group(4)
    return "// GENERATED by the Frontline converter from this PC's own MOHAA install: alias map-filter bridge\n" + \
        "\n".join(defs[k] for k in sorted(defs)) + "\n"


def spec(level):
    with open(os.path.join(HERE, "fl_levels.json")) as f:
        return json.load(f)[level]


def scr_str(s):
    return '"' + s.replace("\\", "/").replace('"', "'") + '"'


def chars_table(disc):
    return disc.read("DATA/chars.bum").split(b"\0")


# TODO(frontline): English speech has no English subtitle on the disc (SMUL carries EN only for foreign-language
# lines). Decision 2026-11-08: keep Frontline's own behaviour - subtitles only where the disc has them. A local
# speech-to-text pass was prototyped and removed; revisit only with the user's OK (bundled model, licence, size).


def build(disc, L, level, X, vgm, files, log=print, mohaa_base=None):
    sp = spec(level)
    d = f"DATA/{level.split('_')[0]}/{level}/"
    lines = ["// GENERATED on this PC by docs/tools/frontline/flpack.py from the player's own disc.",
             "// Not part of the mod source; regenerated by the converter.", "init:{"]

    # ---- text ----
    ct = chars_table(disc)
    for k, ordn in sorted(sp["chars_bum"].items()):
        lines.append(f'\tlevel.fl_text["{k}"] = {scr_str(ct[ordn].decode("latin-1"))}')

    # ---- dialogue ----
    tmp = tempfile.mkdtemp(prefix="flpack_")
    abk = disc.read(d + sp["dialogue_bank"])
    bnk, entries = flaudio.bnk_entries(abk)
    bnk_path = os.path.join(tmp, "scr.bnk")
    with open(bnk_path, "wb") as f:
        f.write(bnk)
    by_stream = {e["stream"]: e for e in entries}
    wavs, ali = {}, []
    for key, stream in sorted(sp["cues"].items(), key=lambda kv: kv[1]):
        out = os.path.join(tmp, f"{key}.wav")
        if not flaudio.vgm_decode(vgm, bnk_path, out, stream):
            log("cue decode failed", key)
            continue
        wavs[key] = out
    for key, path in sorted(wavs.items()):
        alias = f"fl{level.replace('_', '')}_{key}"
        rel = f"sound/fl/{level}/{key}.wav"
        with open(path, "rb") as f:
            files[rel] = f.read()
        ali.append(f'aliascache {alias} {rel} soundparms 1.0 0.0 1.0 0.0 600 4000 dialog streamed maps "mfl"')
        sub = by_stream[sp["cues"][key]]["subs"].get("en", "")
        spk = next((v for k, v in sp["speakers"].items() if key.startswith(k)), "")
        lines.append(f'\tlevel.fl_cue["{key}"] = "{alias}"')
        lines.append(f'\tlevel.fl_cue_sub["{key}"] = {scr_str(sub)}')
        lines.append(f'\tlevel.fl_cue_who["{key}"] = {scr_str(spk)}')
        lines.append(f'\tlevel.fl_cue_len["{key}"] = {flaudio.wav_seconds(path):.2f}')
    files[f"ubersound/fl_{level}.scr"] = ("// GENERATED on this PC by the Frontline converter\n" + "\n".join(ali) + "\n").encode()

    if mohaa_base:
        files["ubersound/fl_aliasbridge.scr"] = alias_bridge(mohaa_base, "mfl_" + level).encode("latin-1")

    # ---- music ----
    segs = flaudio.split_schl(disc.read(d + sp["music"]["bank"]))
    for name, idx in sorted(sp["music"]["segments"].items()):
        if idx >= len(segs):
            continue
        src = os.path.join(tmp, f"mus{idx}.asf")
        dst = os.path.join(tmp, f"mus{idx}.wav")
        with open(src, "wb") as f:
            f.write(segs[idx])
        if flaudio.vgm_decode(vgm, src, dst):
            rel = f"sound/music/fl_{level}_{name}.wav"
            with open(dst, "rb") as f:
                files[rel] = f.read()
            lines.append(f'\tlevel.fl_music["{name}"] = "{rel}"')
            lines.append(f'\tlevel.fl_music_len["{name}"] = {flaudio.wav_seconds(dst):.1f}')

    # ---- placements ----
    na = nl = nh = nm = 0
    for e in L.entities():
        names = [s for s in e["strs"] if not s.lower().startswith("start")]
        if not names:
            continue
        cls = names[0]
        p = X(e["pos"])
        o = f"( {p[0]:.0f} {p[1]:.0f} {p[2] + 24:.0f} )"
        if AXIS_RX.match(cls):
            na += 1
            lines.append(f'\tlevel.fl_axis[{na}] = {o}')
            lines.append(f'\tlevel.fl_axis_cls[{na}] = "{cls}"')
            lines.append(f'\tlevel.fl_axis_alert[{na}] = {int(any("alert" in s.lower() or "ambush" in s.lower() for s in e["strs"]))}')
        elif ALLY_RX.match(cls):
            nl += 1
            lines.append(f'\tlevel.fl_ally[{nl}] = {o}')
            lines.append(f'\tlevel.fl_ally_cls[{nl}] = "{cls}"')
        elif cls in HEALTH:
            nh += 1
            lines.append(f'\tlevel.fl_health[{nh}] = {o}')
            lines.append(f'\tlevel.fl_health_amt[{nh}] = {HEALTH[cls]}')
        elif cls in ("MObjective_1_1", "M1_1_ResistanceDrop", "M1_1_ClipBoard", "M1_1_WallExplosion",
                     "M1_1_Field_Phone", "Conversation", "InterrogationOfficer"):
            lines.append(f'\tlevel.fl_pos["{cls}"] = {o}')
        elif cls == "MountedMachineGun":
            nm += 1
            lines.append(f'\tlevel.fl_mg[{nm}] = {o}')
        elif cls in ("TankVehicle", "Player"):
            lines.append(f'\tlevel.fl_pos["{cls}"] = {o}')
            if cls == "Player":
                yaw = math.degrees(math.atan2(-p[1], -p[0])) % 360     # face the level centre
                lines.append(f'\tlevel.fl_start = {o}')
                lines.append(f'\tlevel.fl_start_yaw = {yaw:.0f}')
    navs = sorted(X(n["pos"]) for n in L.navpoints())
    if navs:
        w = navs[0]
        lines.append(f"\tlevel.fl_west = ( {w[0]:.0f} {w[1]:.0f} {w[2] + 24:.0f} )")
    lines += [f"\tlevel.fl_mg_n = {nm}", f"\tlevel.fl_axis_n = {na}", f"\tlevel.fl_ally_n = {nl}", f"\tlevel.fl_health_n = {nh}",
              "\tlevel.fl_data_ok = 1", "}end", ""]
    files[f"maps/mfl_{level}_data.scr"] = "\n".join(lines).encode("latin-1")
    return {"axis": na, "allies": nl, "health": nh, "cues": len(wavs), "music": len(segs)}
