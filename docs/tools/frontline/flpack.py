def _slots(e, k):
    """[flfix2 round 17] the messages a record's slot k sends (0 = player enters, 1 = player leaves, 2 = object
    enters, ...): word 22+k is the byte offset of the slot's list {u32 count, u32 msg...}, 0 = the slot is empty"""
    w = flscene.words(e)
    if 22 + k >= len(w) or not w[22 + k] or w[22 + k] % 4:
        return []
    o = w[22 + k] // 4
    if o >= len(w) or not (0 < w[o] < 16) or o + 1 + w[o] > len(w):
        return []
    return list(w[o + 1:o + 1 + w[o]])


def _ambience(disc, L, level, X, vgm, files, lines, ali, tmp, d, amb, log):
    """[flfix2 round 17] Frontline's ambience zones and fire loops -> sounds + level vars for the mission script.
    AmbienceTrigger (player enters, msg 236) starts streamed bed n = record word 14 from <l>STRBNK.AST and the bed
    plays until another zone starts another; PlayFireLoopParent plays its sound set's PLAYSOUND(57) at the record
    on enter (msg 66) and stops it on leave (msg 67) when its slot 1 sends 67, else never. Positions and radii go
    through the converter's own transform (X), radii in map units."""
    pre = f"fl{level.replace('_', '')}"
    sdir = f"sound/fl/{level}/"
    # beds: one per streamed ref of the .ABK, the loop body of each (the intro is the same audio on this disc)
    beds = {}
    ast = disc.read(d + amb["beds"] + ".ast")
    for n, (intro, loop) in enumerate(flaudio.ast_loops(disc.read(d + amb["beds"] + ".abk"))):
        sch = flaudio.schl_at(ast, loop or intro)
        if not sch:
            continue
        src, dst = os.path.join(tmp, f"amb{n}.asf"), os.path.join(tmp, f"amb{n}.wav")
        with open(src, "wb") as f:
            f.write(sch)
        if not flaudio.vgm_decode(vgm, src, dst):
            log("ambience bed decode failed", n)
            continue
        rel = f"{sdir}amb{n + 1}.wav"
        files[rel] = flaudio.wav_mono(dst)      # [discbot] stereo WAVs do not load as sound effects on the client
        alias = f"{pre}_amb{n + 1}"
        # played levelwide (loopsound min distance "levelwide"), so the distances here do not matter
        ali.append(f'aliascache {alias} {rel} soundparms 1.0 0.0 1.0 0.0 10000 10000 auto loaded maps "coop_fl"')
        beds[n] = alias
        lines.append(f'\tlevel.fl_amb_alias[{n + 1}] = "{alias}"')
        lines.append(f'\tlevel.fl_amb_len[{n + 1}] = {flaudio.wav_seconds(dst):.1f}')
    lines.append(f"\tlevel.fl_amb_n = {len(beds)}")
    # the fire loop: the sound set of a PlayFireLoopParent record (link category 11) -> SOMI row -> bank sample
    fire, row, sets_ = None, None, []
    som = L.files.get(amb["fire"]["som"], b"")
    fires = [e for e in L.entities() if amb["fire"]["cls"] in e["strs"]]
    for e in fires:
        sets_ = [x & 0xFFFF for x in flscene.words(e)[13:] if x >> 16 == 11]
        row = flaudio.som_sound(som, sets_[0], amb["fire"]["sound"]) if sets_ else None
        if row:
            break
    if row:
        abk = disc.read(d + amb["fire"]["bank"])
        stream = flaudio.bank_stream(abk, row["code"], row["first"])
        bnk_path = os.path.join(tmp, "fire.bnk")
        with open(bnk_path, "wb") as f:
            f.write(abk[abk.find(b"BNKl"):])
        dst = os.path.join(tmp, "fire.wav")
        if stream and flaudio.vgm_decode(vgm, bnk_path, dst, stream):
            rel = f"{sdir}fire.wav"
            with open(dst, "rb") as f:
                files[rel] = f.read()
            fire = f"{pre}_fire"
            ali.append(f'aliascache {fire} {rel} soundparms {row["volume"]:.2f} 0.0 1.0 0.0 256 2400 auto loaded maps "coop_fl"')
            lines.append(f'\tlevel.fl_fire_alias = "{fire}"')
            log("fire loop: set", sets_[0], "row", row, "stream", stream, f"{flaudio.wav_seconds(dst):.1f} s")
    nz = nf = 0
    for e in L.entities():
        w = flscene.words(e)
        q = X(e["pos"])
        r_ = flscene.radius_m(e) * X.s
        if amb["zone_cls"] in e["strs"] and len(w) > 14 and w[14] in beds:
            nz += 1
            lines.append(f'\tlevel.fl_ambz[{nz}] = ( {q[0]:.0f} {q[1]:.0f} {q[2]:.0f} )')
            lines.append(f'\tlevel.fl_ambz_r[{nz}] = {r_:.0f}')
            lines.append(f'\tlevel.fl_ambz_bed[{nz}] = {w[14] + 1}')
            lines.append(f'\tlevel.fl_ambz_rec[{nz}] = {e["i"]}')
        elif fire and amb["fire"]["cls"] in e["strs"]:
            nf += 1
            lines.append(f'\tlevel.fl_fire[{nf}] = ( {q[0]:.0f} {q[1]:.0f} {q[2]:.0f} )')
            lines.append(f'\tlevel.fl_fire_r[{nf}] = {r_:.0f}')
            lines.append(f'\tlevel.fl_fire_stop[{nf}] = {int(amb["fire"]["stop_msg"] in _slots(e, 1))}')
            lines.append(f'\tlevel.fl_fire_rec[{nf}] = {e["i"]}')
    lines.append(f"\tlevel.fl_ambz_n = {nz}")
    lines.append(f"\tlevel.fl_fire_n = {nf}")
    log("ambience: beds", len(beds), "zones", nz, "fire loops", nf)


def _fakedoors(disc, L, level, X, vgm, files, lines, ali, tmp, d, fd, log):
    """[decodeaudit 2026-11-22, gap 7] Frontline's locked doors. 62 class-less trigger volumes (upright cylinders,
    flscene.volume) stand in front of the doors that never open; their slot 4 (the player presses ACTION inside) sends
    msg 509. RemoteFakeDoorTrigger (rec 478 on 1_1) watches 509 from ANY sender (p2 0x010001fd, filter 0): HUD text 5
    (bi_70), PLAYSOUND 96 of the SENDER's sound set at the sender (bi_a8(sender, 96, -1); 11:685 -> SOMI row -> a
    0.31 s rattle in the script bank), an AI noise at the sender (bi_b0(sender, 0, 1.0) -> 0x29ae0, event 51 =
    "a sound"), then REGISTERTIMEREVENT(3, 77): back to listening 3 ticks later. No listener, nothing happens."""
    pre = f"fl{level.replace('_', '')}"
    sdir = f"sound/fl/{level}/"
    ents = L.entities()
    if not any(fd["cls"] in e["strs"] for e in ents):
        log("fake doors: no", fd["cls"], "record - the volumes are dead")
        return
    som = L.files.get(fd["som"], b"")
    abk = disc.read(d + fd["bank"])
    bnk_path = os.path.join(tmp, "fdoor.bnk")
    with open(bnk_path, "wb") as f:
        f.write(abk[abk.find(b"BNKl"):])
    snd, n = {}, 0
    for e in ents:
        if fd["msg"] not in _slots(e, 4):
            continue
        v = flscene.volume(e)
        if not v:
            continue
        sets_ = [x & 0xFFFF for x in flscene.words(e)[13:] if x >> 16 == 11]
        alias = ""
        row = flaudio.som_sound(som, sets_[0], fd["sound"]) if sets_ else None
        if row:
            key = (row["code"], row["first"])
            if key not in snd:
                stream = flaudio.bank_stream(abk, row["code"], row["first"])
                dst = os.path.join(tmp, f"fdoor{len(snd)}.wav")
                if stream and flaudio.vgm_decode(vgm, bnk_path, dst, stream):
                    rel = f"{sdir}fakedoor{len(snd) + 1}.wav"
                    files[rel] = flaudio.wav_mono(dst)
                    a_ = f"{pre}_fakedoor{len(snd) + 1}"
                    ali.append(f'aliascache {a_} {rel} soundparms {row["volume"]:.2f} 0.0 1.0 0.0 160 1600 auto loaded maps "coop_fl"')
                    snd[key] = a_
                else:
                    snd[key] = ""
            alias = snd[key]
        n += 1
        q = X(e["pos"])
        lines.append(f'\tlevel.fl_fdoor[{n}] = ( {q[0]:.0f} {q[1]:.0f} {q[2]:.0f} )')
        lines.append(f'\tlevel.fl_fdoor_r[{n}] = {v["r"] * X.s:.0f}')
        lines.append(f'\tlevel.fl_fdoor_zlo[{n}] = {v["zlo"] * X.s:.0f}')
        lines.append(f'\tlevel.fl_fdoor_zhi[{n}] = {v["zhi"] * X.s:.0f}')
        lines.append(f'\tlevel.fl_fdoor_snd[{n}] = "{alias}"')
        lines.append(f'\tlevel.fl_fdoor_rec[{n}] = {e["i"]}')
    lines.append(f"\tlevel.fl_fdoor_n = {n}")
    lines.append(f"\tlevel.fl_fdoor_rearm = {fd['rearm_ticks'] / 60.0:.3f}")
    log("fake doors:", n, "volumes,", len([a for a in snd.values() if a]), "sound(s)")


def _rv(lo, hi, s):
    """a decoded (lo, hi) range in metres -> a TIKI randomised value: crandom a | range base amplitude | a constant"""
    lo, hi = lo * s + 0.0, hi * s + 0.0
    if abs(lo) < 0.05:
        lo = 0.0
    if abs(hi) < 0.05:
        hi = 0.0
    if abs(lo - hi) < 0.05:
        return f"{lo:.1f}"
    if abs(lo + hi) < 0.05:
        return f"crandom {hi:.1f}"
    return f"range {lo:.1f} {hi - lo:.1f}"


def pfx_tik(p, typ, X, gen):
    """[flfix2 round 22] one placed particle system -> a TIKI emitter with the DECODED numbers, written in the syntax of
    the stock / mod emitters (models/emitters/tehao_fireSmoke_long.tik: dummy3 skeleton, effectentity, one
    originemitter, start / stop animations). Our sprite stands in for the disc's (its sprite is not on the level):
    gen["sprites"][type], gen["sprite_px"] pixels wide, drawn at pixels x scale units (tr_sprite.c), so scale =
    decoded size in metres x X.s / sprite_px. [51..52] = start size range, [53..54] = end size range (scalerate makes
    the end size at the end of the particle's life: scale(t) = s0 (1 + rate t), cg_tempmodels.cpp). Rate, life,
    colour (the average of the start colour range), spawn box, velocity and acceleration (metres -> units through the
    converter's transform, y mirrored with it) and spin (read as radians per second) are the record's."""
    s, m = X.s, (-1.0 if X.m < 0 else 1.0)
    px = float(gen.get("sprite_px", 256))
    life = p["life"] if p["life"] > 0 else 1.0
    # [look 2026-11-16] per-record look overrides (fl_levels.json particles.generate.rec): size_k scales the decoded size
    # (the disc's size is relative to ITS smoke sprite, not metres - record 8, the house smoke, drew as 48-72u blobs where
    # the original's plume is several metres wide, ref_xemu/trace/b41h_prepost.png), grow = end size / start size over
    # the particle's life, alpha / color_k replace our per-type alpha and lift the colour
    ov = dict(gen.get("look", {}).get(typ, {}), **gen.get("rec", {}).get(str(p.get("rec")), {}))     # per-type default, per-record override
    k_ = float(ov.get("size_k", 1.0))
    s0 = [p["size_raw"][0] * s / px * k_, p["size_raw"][1] * s / px * k_]
    s1 = [p["size_raw"][2] * s / px * k_ * float(ov.get("grow", 1.0)), p["size_raw"][3] * s / px * k_ * float(ov.get("grow", 1.0))]
    a0, a1 = sum(s0) / 2.0, sum(s1) / 2.0
    srate = (a1 / a0 - 1.0) / life if a0 > 0 else 0.0
    rate = p["rate"] if p["rate"] > 0 else float(gen.get("rate0", {}).get(typ, 4.0))
    # cfx_flame is additive and ignores the vertex colour; for the flames the start colour (orange) is kept, the
    # smokes take the average of the two colour words (round 20's reading: the start colour range)
    r, g, b = (tuple(c / 255.0 for c in p["rgb0"]) if typ == "flame" else p["rgb"])
    if ov.get("color_k"):
        r, g, b = (min(1.0, c * float(ov["color_k"])) for c in (r, g, b))

    def ax(rng, k):
        lo, hi = rng[k]
        if k == 1 and m < 0:
            lo, hi = -hi, -lo
        return _rv(lo, hi, s)
    spin = max(abs(p["spin"][0]), abs(p["spin"][1])) * 57.2958
    alpha = float(ov.get("alpha", gen.get("alpha", {}).get(typ, 0.8)))
    em = [f"\t\t\tspawnrate {rate:.2f}",
          f"\t\t\tmodel {gen['sprites'][typ]}",
          f"\t\t\tcolor {r:.2f} {g:.2f} {b:.2f}",
          f"\t\t\talpha {alpha:.2f}",
          f"\t\t\tlife {life:.2f}",
          f"\t\t\tscalemin {min(s0):.3f}",
          f"\t\t\tscalemax {max(s0):.3f}"]
    if abs(srate) > 0.0005:
        em.append(f"\t\t\tscalerate {srate:.4f}")
    em.append("\t\t\toffset " + " ".join(ax(p["box"], k) for k in range(3)))
    em.append("\t\t\trandvel " + " ".join(ax(p["vel"], k) for k in range(3)))
    acc = (p["acc"][0] * s, p["acc"][1] * s * m, p["acc"][2] * s)
    if any(abs(c) > 0.05 for c in acc):
        em.append(f"\t\t\taccel {acc[0]:.1f} {acc[1]:.1f} {acc[2]:.1f}")
    if spin > 0.5:
        em.append(f"\t\t\tavelocity 0 0 crandom {spin:.0f}")
    if typ != "flame":
        em.append(f"\t\t\tfadein {min(2.0, 0.08 * life):.2f}")
    em.append(f"\t\t\tfadedelay {0.6 * life:.2f}")
    return "\n".join([
        "TIKI", "// GENERATED on this PC by docs/tools/frontline/flpack.py (pfx_tik) from the numbers of a placed particle",
        "// system on the player's own disc; the sprite is the mod's stand-in. Regenerated by the converter.",
        "setup", "{", "\tscale 1.0", "\tpath models/fx/dummy", "\tskelmodel dummy3.skd", "}", "",
        "init", "{", "\tserver", "\t{", "\t\tclassname effectentity", "\t\tnotsolid", "\t\trendereffects +dontdraw", "\t}",
        "\tclient", "\t{", f"\t\tcache {gen['sprites'][typ]}",
        "\t\toriginemitter flpfx", "\t\t(", *em, "\t\t)", "\t}", "}", "",
        "animations", "{", "\tidle dummy3.skc", "\tstart dummy3.skc", "\t{", "\t\tclient", "\t\t{",
        "\t\t\tenter emitteron flpfx", "\t\t}", "\t}", "\tstop dummy3.skc", "\t{", "\t\tclient", "\t\t{",
        "\t\t\tenter emitteroff flpfx", "\t\t}", "\t}", "}", ""])


def _pfx_lifts(L, ents, log, below=2.0, above=2.0, clear=0.1):
    """[decodeaudit 2026-11-23, bug-11480] a placed system whose origin lies UNDER the walkable ground (a solid,
    up-facing collision triangle covers it 0..`below` m above, and none lies under it within `above` m) is never drawn
    here: the engine sends an entity only when its origin's cluster is in view, and an origin inside the world has no
    cluster (1_1 rec 4, the burning truck down the dock street: origin z -4.49 m, cobbles at -3.65 m). Frontline draws
    the system anyway (its sprites rise out of the street). -> {rec: z to use} = the ground + `clear` m."""
    tris = []
    for _cn, vs_, ts_ in L.collision():
        for a_, b_, c_, f_ in ts_:
            if f_ & (1 << 22):
                continue                                    # volumes are not ground
            A, B, C = vs_[a_], vs_[b_], vs_[c_]
            nz = (B[0] - A[0]) * (C[1] - A[1]) - (B[1] - A[1]) * (C[0] - A[0])
            if abs(nz) > 1e-9:
                tris.append((A, B, C, nz))
    out = {}
    for e in ents:
        x, y, z = e["pos"]
        zs = []
        for A, B, C, d in tris:
            if max(A[0], B[0], C[0]) < x or min(A[0], B[0], C[0]) > x or max(A[1], B[1], C[1]) < y or min(A[1], B[1], C[1]) > y:
                continue
            l1 = ((B[0] - x) * (C[1] - y) - (B[1] - y) * (C[0] - x)) / d
            l2 = ((C[0] - x) * (A[1] - y) - (C[1] - y) * (A[0] - x)) / d
            l3 = 1.0 - l1 - l2
            if min(l1, l2, l3) >= 0:
                zs.append(l1 * A[2] + l2 * B[2] + l3 * C[2])
        up = [g for g in zs if z < g <= z + below]
        down = [g for g in zs if z - above <= g <= z]
        if up and not down:
            out[e["i"]] = max(up) + clear
            log("particle", e["i"], "origin %.2f m under the ground at %.2f: lifted" % (max(up) - z, max(up)))
    return out


def _particles(L, X, lines, pfx, log, files=None, level=""):
    """[flfix2 round 20] Frontline's placed particle systems (.bpd section-3 kind 9, flscene.particle) -> level vars for
    the mission script: where, which STOCK MOHAA emitter stands in for it (fl_levels.json "particles": type -> model,
    chosen by the decoded colour, motion and size), when it starts and how long it stays. Nothing of the disc's
    sprites is carried; the type is ours, from the decoded numbers."""
    rows = []
    for e in L.entities():
        p = flscene.particle(e)
        if p is None:
            continue
        r, g, b = p["rgb"]
        if p["dur"] > 0 or p["cls"]:
            typ = "blast"           # a one-shot burst (emit duration set) or a scripted explosion class
        elif r > 1.3 * b and r > 0.4:
            typ = "flame"           # orange start colour
