"""Armory finish-chip UI pages for PER-GUN finishes (killchal-next; finishes2 v1.10.68). Called by gen_loadout.render_all, so
`gen_loadout.py check` byte-compares every file written here.

A finish chip's padlock used to be ONE account-wide state (coop_loLkF<fid>) plus an "all seven locked" override for an unmastered
gun (lkmast.cfg). Now every slot's gun has its own verdict per finish, pushed by loadoutpick.scr::loadout_slotLocksExport:

    coop_loMast<n>       = exec ui/loadout/lkfs<n>.cfg          lkfs<n>: vstr coop_loMast<n>_<f> per finish (run by s<n>sel via coop_loMastApply)
    coop_loMast<n>_<f>   = exec ui/loadout/lkc<f>_<0|1>.cfg     0 = chip open, 1 = chip locked (padlock + the deny click)
    coop_loFq<n>_<f>     = set coop_loFinNm "37 / 100 MP40 kills"  the gun's progress; fdeny<f>.cfg shows it under the finish name
    coop_loFqCur<f>      = vstr coop_loFq<n>_<f>                 s<n>sel.cfg points it at the active slot (a cfg cannot read a slot)

[v1.10.68 finishes2] The SECOND chip row (fids 40+, docs/tools/finishes2.tsv) uses the same per-chip machinery with FIXED positions
(no sort chain: chip q always shows fid level.coop_fs2Fid[q]). The row exists for slots 1-3 (guns); the grenade slot has no finishes2.
    coop_loF2On          the row's visibility: s1-3sel 1, s4sel 0, init.cfg 0 (menu open, no slot yet)
    coop_loFgo<F>        = exec ui/loadout/fin<F>_s<n>.cfg (s<n>sel retargets it, as for 0-8)
    fin<F>_s<n>.cfg      apply finish F to slot n (the fin<f>_s<n>.cfg format: archive + name bus + lp_f<n> + offline preview + name)
    coop_loLkFV<F> = 0   while the row is hidden (init / slot 4), so no padlock floats over an empty strip

Files written (all under ui/loadout/): lkfs1-4.cfg, lkc<f>_0|1.cfg, fdeny<f>.cfg, fin<F>_s<n>.cfg, s1..4sel.cfg and init.cfg (the old
text + marked blocks).
"""
import re

import finishes2 as F2

SLOTS = (1, 2, 3, 4)
FS2 = F2.table()
FS2_FIDS = [r["fid"] for r in FS2]
FIDS = list(range(1, 8)) + FS2_FIDS
GUN_SLOTS = (1, 2, 3)                      # the second row: guns only (slot 4 = grenades, no finishes2)
BLOCK_BEGIN = "// killchal: per-gun finish progress pointers (gen_finish_ui.py)"
BLOCK2_BEGIN = "// finishes2: the second finish chip row (gen_finish_ui.py)"
INIT_BEGIN = "// finishes2: second chip row hidden until a gun slot is clicked (gen_finish_ui.py)"
# exactly the lines the finishes2 blocks write (a looser "set coop_lo..." swallowed the hand-written lines that follow them)
B2_LINES = r"(?:(?:set coop_lo(?:F2On|Fgo[4-5]\d|FqCur[4-5]\d|LkFV[4-5]\d)|vstr coop_loMast\d_[4-5]\d)[^\n]*\n)+"


def fids_of(n):
    return FIDS if n in GUN_SLOTS else list(range(1, 8))


def lkfs(n):
    return ("// GENERATED by gen_finish_ui.py - apply slot %d's per-chip finish verdicts (pushed by loadout_slotLocksExport)\n" % n
            + "".join("vstr coop_loMast%d_%d\n" % (n, f) for f in fids_of(n)))


def lkc(f, locked):
    if locked:
        return ("// GENERATED by gen_finish_ui.py - finish chip %d LOCKED for the active slot's gun: padlock + the click shows what unlocks it\n" % f
                + "set coop_loLkFV%d 1\n" % f
                + 'set coop_loFcmt%d "exec ui/loadout/fdeny%d.cfg"\n' % (f, f))
    return ("// GENERATED by gen_finish_ui.py - finish chip %d OPEN for the active slot's gun\n" % f
            + "set coop_loLkFV%d 0\n" % f
            + 'set coop_loFcmt%d "vstr coop_loFgo%d"\n' % (f, f))


def fdeny(f):
    return ("// GENERATED by gen_finish_ui.py - locked finish chip click: the finish name, THIS gun's kill progress, beep, change nothing\n"
            "exec ui/loadout/reqf%d.cfg\n"
            "vstr coop_loFqCur%d\n"
            "vstr coop_loDeny\n" % (f, f))


def fin_slot(f, n, name):
    """fin<F>_s<n>.cfg - the fin<f>_s<n>.cfg format of the standard seven, for a finishes2 fid"""
    return ("// GENERATED by gen_finish_ui.py - apply finish %d to slot %d (0 = back to standard). seta persists the\n" % (f, n)
            + "// pick for the cold main menu; the server re-validates at apply AND at spawn.\n"
            + 'seta coop_loS%dF "%d"\n' % (n, f)
            + 'seta coop_loFA%d "append name ,f%d%d"\n' % (n, n, f)
            + "append name ,f%d%d\n" % (n, f)
            + "// show this finish in the viewer (the gun's page arms coop_loFinP%d at its finp<id>_%d.cfg)\n" % (f, f)
            + "vstr coop_loFinP%d\n" % f
            + "set lp_f%d %d\n" % (n, f)
            + 'seta coop_loFNmS%d "set coop_loFinNm %s"\n' % (n, name)
            + 'set coop_loFinNm "%s"\n' % name)


def sel_block(n):
    return (BLOCK_BEGIN + "\n"
            + "".join('set coop_loFqCur%d "vstr coop_loFq%d_%d"\n' % (f, n, f) for f in range(1, 8)))


def sel_block2(n):
    L = [BLOCK2_BEGIN]
    if n in GUN_SLOTS:
        L.append("set coop_loF2On 1")
        L += ['set coop_loFgo%d "exec ui/loadout/fin%d_s%d.cfg"' % (f, f, n) for f in FS2_FIDS]
        L += ['set coop_loFqCur%d "vstr coop_loFq%d_%d"' % (f, n, f) for f in FS2_FIDS]
        # the row's padlocks NOW, from the archived verdicts (the server's last push, else armory_defaults' fail-locked lkc<F>_1): the
        # slot's coop_loMast<n> chain only exists once a server has pushed it, and the cold main menu has none
        L += ["vstr coop_loMast%d_%d" % (n, f) for f in FS2_FIDS]
    else:
        L.append("set coop_loF2On 0")
        L += ["set coop_loLkFV%d 0" % f for f in FS2_FIDS]
    return "\n".join(L) + "\n"


def patch_sel(text, n):
    """s<n>sel.cfg with exactly one killchal block (right after the coop_loMastTCur line) and one finishes2 block after it
    (idempotent: older blocks are replaced)"""
    t = text.replace("\r\n", "\n")
    t = re.sub(re.escape(BLOCK_BEGIN) + r"\n(?:set coop_loFqCur\d+ \"[^\"\n]*\"\n)+", "", t)
    t = re.sub(re.escape(BLOCK2_BEGIN) + r"\n" + B2_LINES, "", t)
    anchor = 'set coop_loMastTCur "vstr coop_loMastT%d"\n' % n
    assert t.count(anchor) == 1, ("s%dsel.cfg anchor" % n, t.count(anchor))
    t = t.replace(anchor, anchor + sel_block(n) + (sel_block2(n) if FS2_FIDS else ""))
    return t


def patch_init(text):
    t = text.replace("\r\n", "\n")
    t = re.sub(re.escape(INIT_BEGIN) + r"\n" + B2_LINES, "", t)
    anchor = "set coop_loFinUIOn 0\n"
    assert t.count(anchor) == 1, ("init.cfg anchor", t.count(anchor))
    if FS2_FIDS:
        t = t.replace(anchor, anchor + INIT_BEGIN + "\nset coop_loF2On 0\n" + "".join("set coop_loLkFV%d 0\n" % f for f in FS2_FIDS))
    return t


def defaults():
    """armory_defaults.cfg lines (gen_armory): fail-LOCKED second-row verdicts for a never-connected client"""
    return ['seta coop_loMast%d_%d "exec ui/loadout/lkc%d_1.cfg"' % (n, f, f) for n in GUN_SLOTS for f in FS2_FIDS]


def build(out, read_sel, read_init=None):
    """add the finish-chip pages to `out` (name -> text); read_sel(n) returns the CURRENT text of s<n>sel.cfg, read_init() init.cfg's"""
    for n in SLOTS:
        out["lkfs%d.cfg" % n] = lkfs(n)
        out["s%dsel.cfg" % n] = patch_sel(read_sel(n), n)
    for f in FIDS:
        out["lkc%d_0.cfg" % f] = lkc(f, False)
        out["lkc%d_1.cfg" % f] = lkc(f, True)
        out["fdeny%d.cfg" % f] = fdeny(f)
    for r in FS2:
        for n in GUN_SLOTS:
            out["fin%d_s%d.cfg" % (r["fid"], n)] = fin_slot(r["fid"], n, r["name"])
    if read_init is not None:
        out["init.cfg"] = patch_init(read_init())
    return out
