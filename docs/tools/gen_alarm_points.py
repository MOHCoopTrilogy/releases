#!/usr/bin/env python
"""Generate coop_mod/alarmpoints.scr - the alarm switches + siren bells that coop_mod/alarm.scr arms on each alarm-ready map.

WHY THIS EXISTS
    The alarm state (docs/proposals/alarm_counterattack_2026-10-15) needs 2-4 switch points per map. They are DATA
    (docs/tools/alarm_points.json), and this turns the data into a script, the way gen_push_maps.py does for Push spawns.
    A map is "alarm-ready" when it has at least one switch here. Nothing else decides it.

    python docs/tools/gen_alarm_points.py check                  # regenerate in memory + byte-compare (exit 1 = drift)
    python docs/tools/gen_alarm_points.py build                  # write coop_mod/alarmpoints.scr
    python docs/tools/gen_alarm_points.py import-log MAP FILE    # add the '^~^~^ CN ALMPT <kind> x y z yaw' lines of a scout run
    python docs/tools/gen_alarm_points.py import-dat MAP [FILE]  # add the alarmswitch / alarmbell entries of coop_mod/save/build_<MAP>.dat
                                                                 # (stand at the wall, coop_build the model, then run this)

    ALARM_MOD=<mod checkout> overrides the checkout the file is written to / read from (default: hzm-mohaa-coop-mod).

OUTPUT RULES
    ASCII, LF, no BOM. Yaw is normalised to [0,360) so no bare negative scalar appears (vector literals may carry negatives).
    Spawns use `spawn animate` (class Animate): a ScriptModel never takes script/bullet damage in this engine build, an
    Animate does, and alarm.scr silences the alarm when a switch or bell is shot (probe 2026-10-15, BUILD.md step 5).
"""
import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MOD = os.environ.get("ALARM_MOD") or os.path.join(ROOT, "hzm-mohaa-coop-mod")
DATA = os.path.join(HERE, "alarm_points.json")
OUT = os.path.join(MOD, "coop_mod", "alarmpoints.scr")

SWITCH_MODEL = "models/animate/alarmswitch.tik"
BELL_MODEL = "models/static/alarmbell.tik"


def load():
    if not os.path.exists(DATA):
        return {}
    with io.open(DATA, "r", encoding="utf-8") as f:
        return json.load(f)


def save(d):
    with io.open(DATA, "w", encoding="utf-8", newline="\n") as f:
        json.dump(d, f, indent=1, sort_keys=True)
        f.write("\n")


def num(v):
    s = ("%.3f" % float(v)).rstrip("0").rstrip(".")
    return s if s not in ("", "-0") else "0"


def norm_yaw(a):
    a = float(a) % 360.0
    return a


def render(d):
    o = []
    o.append("//=========================================================================")
    o.append("// alarmpoints.scr - GENERATED by docs/tools/gen_alarm_points.py from docs/tools/alarm_points.json. Do not edit by hand.")
    o.append("// place <map> spawns that map's alarm switches + siren bells (registering them with alarm.scr::alm_add) and returns how many.")
    o.append("//=========================================================================")
    o.append("place local.map:{")
    o.append("\tlocal.n = 0")
    for m in sorted(d):
        if not d[m].get("points"):
            continue
        o.append("\tif( local.map == \"%s\" ){ local.n = waitthread pts_%s }" % (m, m))
    o.append("}end local.n")
    o.append("")
    for m in sorted(d):
        pts = d[m].get("points") or []
        if not pts:
            continue
        o.append("// %s: %d switch(es), %d bell(s)" % (m, sum(1 for p in pts if p["kind"] == "switch"), sum(1 for p in pts if p["kind"] == "bell")))
        o.append("pts_%s:{" % m)
        o.append("\tlocal.n = 0")
        for p in pts:
            kind = p["kind"]
            o.append("\t// %s %s" % (kind, p.get("area", "")) if p.get("area") else "\t// %s" % kind)
            o.append("\tlocal.e = spawn animate")
            o.append("\tlocal.e model \"%s\"" % (SWITCH_MODEL if kind == "switch" else BELL_MODEL))
            o.append("\tlocal.e.origin = ( %s %s %s )" % tuple(num(v) for v in p["pos"]))
            o.append("\tlocal.e.angles = ( 0 %s 0 )" % num(norm_yaw(p["yaw"])))
            o.append("\tlocal.e notsolid")
            o.append("\twaitthread coop_mod/alarm.scr::alm_add local.e \"%s\"" % kind)
            o.append("\tlocal.n++")
        o.append("}end local.n")
        o.append("")
    return "\n".join(o) + "\n"


def add_points(d, m, new):
    cur = d.setdefault(m, {"points": []})["points"]
    for n in new:
        dup = False
        for c in cur:
            if c["kind"] == n["kind"] and sum((a - b) ** 2 for a, b in zip(c["pos"], n["pos"])) < 64 ** 2:
                dup = True
        if not dup:
            cur.append(n)
    return d


def cmd_import_log(m, path):
    d = load()
    new = []
    rx = re.compile(r"CN ALMPT (switch|bell) (\S+) (\S+) (\S+) (\S+)")
    for line in io.open(path, "r", encoding="utf-8", errors="replace"):
        g = rx.search(line)
        if g:
            new.append({"kind": g.group(1), "pos": [float(g.group(2)), float(g.group(3)), float(g.group(4))], "yaw": norm_yaw(g.group(5))})
    add_points(d, m, new)
    save(d)
    print("%s: +%d (total %d)" % (m, len(new), len(d[m]["points"])))


def cmd_import_dat(m, path=None):
    path = path or os.path.join(MOD, "coop_mod", "save", "build_%s.dat" % m)
    txt = io.open(path, "r", encoding="utf-8", errors="replace").read()
    new = []
    for blk in re.split(r"(?=//\s*coop_build\s*#)", txt):
        g = re.match(r"//\s*coop_build\s*#\d+\s+(\S+)", blk)
        if not g:
            continue
        model = g.group(1).lower()
        if "alarmswitch" in model:
            kind = "switch"
        elif "alarmbell" in model:
            kind = "bell"
        else:
            continue
        po = re.search(r"\.origin\s*=\s*\(\s*(\S+)\s+(\S+)\s+(\S+)\s*\)", blk)
        an = re.search(r"\.angles\s*=\s*\(\s*(\S+)\s+(\S+)\s+(\S+)\s*\)", blk)
        if not po:
            continue
        yaw = float(an.group(2)) if an else 0.0
        new.append({"kind": kind, "pos": [float(po.group(i)) for i in (1, 2, 3)], "yaw": norm_yaw(yaw)})
    d = load()
    add_points(d, m, new)
    save(d)
    print("%s: +%d from %s (total %d)" % (m, len(new), path, len(d[m]["points"])))


def main():
    a = sys.argv[1:]
    if not a:
        print(__doc__)
        return 2
    if a[0] == "import-log" and len(a) == 3:
        cmd_import_log(a[1], a[2])
        return 0
    if a[0] == "import-dat" and len(a) >= 2:
        cmd_import_dat(a[1], a[2] if len(a) > 2 else None)
        return 0
    txt = render(load())
    if a[0] == "build":
        with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(txt)
        print("wrote %s (%d bytes)" % (OUT, len(txt)))
        return 0
    if a[0] == "check":
        cur = io.open(OUT, "r", encoding="utf-8", newline="").read() if os.path.exists(OUT) else ""
        if cur.replace("\r\n", "\n") != txt:
            print("DRIFT: %s differs from alarm_points.json" % OUT)
            return 1
        print("ok")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
