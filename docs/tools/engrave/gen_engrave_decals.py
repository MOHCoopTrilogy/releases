"""gen_engrave_decals.py - the Customize bench's emblems (decals) for the mod pak.

Writes, into the mod checkout:
  textures/hzm/decal/<name>.tga   the finishes agent's decal art (manifest.json + <name>_256.png), padded with transparent
                                  margins to the nearest emblem-quad aspect (HZE_ASPECTS), so nothing is ever stretched
  scripts/hzm_decal.shader        one shader per decal: straight alpha blend, lit like the gun (rgbGen lightingSpherical),
                                  polygonOffset, cull none (a mirrored decal is the quad seen from behind)
  scripts/hzm_decals.txt          decalinfo <name> <quad aspect> <long side units> <category> <need|-> <label>
                                  (read by qcommon/hzm_engrave_table.h in the cgame and the client)

MOH series emblems are NOT shipped: their shaders point at the retail images in the player's own main / mainta / maintt
paks ('need' = that image; the engine hides the emblem when it is missing). They are letterboxed into their quad with a
tcMod transform on a clampmap instead of padding.

    python docs/tools/engrave/gen_engrave_decals.py --mod <mod checkout> [--decals <finishes decals dir>] [--check]
"""
import io
import json
import os
import sys

from PIL import Image

ASPECTS = (0.5, 0.75, 1.0, 1.5, 2.0, 3.0, 4.0, 8.0)   # == HZE_ASPECTS in qcommon/hzm_engrave_table.h
DECALS = r"H:\hzm_work\finishes2-root\docs\proposals\finishes2_2026-11-09\decals"
RES = 256

# MOH series art read at runtime from the player's own retail paks: (name, image, w:h of the art, long side, label)
SERIES = [
    ("moh_aa_logo", "textures/mohmenu/moh_logo.tga", 2.0, 2.6, "Medal of Honor: Allied Assault"),
    ("moh_bt_logo", "textures/mohmenu/credits/mohaab_logo.tga", 1.0, 2.4, "Medal of Honor: Breakthrough"),
    ("moh_oss_seal", "textures/mohmenu/briefing/osseagle.tga", 1.0, 2.2, "OSS seal (Allied Assault briefing)"),
    ("moh_croix", "textures/mohmenu/croixdeguerre_med.tga", 0.5, 2.4, "Croix de Guerre (Spearhead)"),
    ("moh_berlin", "textures/mohmenu/captureofberlin_med.tga", 71 / 128.0, 2.4, "Capture of Berlin medal (Spearhead)"),
]


def opt(n, d=None):
    return sys.argv[sys.argv.index(n) + 1] if n in sys.argv else d


def nearest(a):
    return min(ASPECTS, key=lambda x: abs(x - a) / x)


def pad(im, qa):
    """centre the art in a transparent canvas of aspect qa (power-of-two friendly: long side RES)"""
    w, h = im.size
    if w / h > qa:
        cw, ch = w, int(round(w / qa))
    else:
        cw, ch = int(round(h * qa)), h
    c = Image.new("RGBA", (cw, ch), (0, 0, 0, 0))
    # bleed the colour under the transparent margin (no dark fringe when filtered)
    rgb = im.convert("RGB").resize((1, 1), Image.LANCZOS).getpixel((0, 0))
    c = Image.new("RGBA", (cw, ch), rgb + (0,))
    c.paste(im, ((cw - w) // 2, (ch - h) // 2), im)
    k = RES / float(max(cw, ch))
    return c.resize((max(4, int(round(cw * k))), max(4, int(round(ch * k)))), Image.LANCZOS)


def shader(name, image, extra="", clamp=False):
    return ("textures/hzm/decal/%s\n{\n\tqer_editorimage %s\n\tcull none\n\tpolygonOffset\n\tsort decal\n\t{\n\t\t%s %s\n"
            "\t\tblendFunc blend\n\t\trgbGen lightingSpherical\n%s\t}\n}\n\n") % (name, image, "clampmap" if clamp else "map", image, extra)


def build(mod, decals_dir):
    man = json.load(open(os.path.join(decals_dir, "manifest.json")))
    files = {}
    sh = ["// GENERATED by docs/tools/engrave/gen_engrave_decals.py - do not hand-edit. The Customize bench's emblems,\n"
          "// drawn on the gun by cgame/cg_engrave.c on the quads models/hzm/engrave_qa*.tik (cl_engrave.cpp in the Armory).\n\n",
          "textures/hzm/decal/none\n{\n\tsurfaceparm nodraw\n\t{\n\t\tmap $whiteimage\n\t\tblendFunc GL_ZERO GL_ONE\n\t}\n}\n\n"]
    info = ["// GENERATED by docs/tools/engrave/gen_engrave_decals.py - do not hand-edit.",
            "// decalinfo <name> <quad aspect w:h> <long side units> <category> <need image | -> <label>"]
    for d in man["decals"]:
        src = os.path.join(decals_dir, "%s_%d.png" % (d["name"], RES))
        if not os.path.exists(src):
            src = os.path.join(decals_dir, "%s_512.png" % d["name"])
        im = Image.open(src).convert("RGBA")
        qa = nearest(im.size[0] / float(im.size[1]))
        out = pad(im, qa)
        b = io.BytesIO()
        out.save(b, "TGA")
        rel = "textures/hzm/decal/%s.tga" % d["name"]
        files[rel] = b.getvalue()
        sh.append(shader(d["name"], rel))
        # the long side of the PADDED quad, so the art itself keeps the manifest's recommended size
        a_art = im.size[0] / float(im.size[1])
        L = float(d.get("recommended_long_side_units") or 2.0)
        art_w = L if a_art >= 1 else L * a_art
        quad_w = art_w * (qa / a_art if qa > a_art else 1.0)
        quad_L = quad_w if qa >= 1 else quad_w / qa
        label = d.get("label", d["name"]).split(" with ")[0].split(" (")[0].split(" - ")[0][:46]
        info.append("decalinfo %s %g %.2f %s - %s" % (d["name"], qa, quad_L, d.get("category", "emblem"), label))
    for name, img, a_art, L, label in SERIES:
        qa = nearest(a_art)
        if abs(qa - a_art) < 1e-3:
            extra = ""
        elif a_art > qa:   # wider than the quad: full width, letterboxed top and bottom
            k = a_art / qa
            extra = "\t\ttcMod transform 1 0 0 %.4f 0 %.4f\n" % (k, -(k - 1) / 2)
        else:
            k = qa / a_art
            extra = "\t\ttcMod transform %.4f 0 0 1 %.4f 0\n" % (k, -(k - 1) / 2)
        sh.append(shader(name, img, extra, clamp=True))
        info.append("decalinfo %s %g %.2f series %s %s" % (name, qa, L, img, label))
    files["scripts/hzm_decal.shader"] = "".join(sh).encode()
    files["scripts/hzm_decals.txt"] = ("\n".join(info) + "\n").encode()
    return files


def main():
    mod = opt("--mod", r"C:\mohaa-coop-dev\hzm-mod-engrave")
    files = build(mod, opt("--decals", DECALS))
    bad = 0
    for rel, data in sorted(files.items()):
        p = os.path.join(mod, rel)
        if "--check" in sys.argv:
            if not os.path.exists(p) or open(p, "rb").read() != data:
                print("STALE", rel)
                bad += 1
            continue
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "wb").write(data)
    print("%s %d files" % ("checked" if "--check" in sys.argv else "wrote", len(files)))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
