"""gen_custom_urc.py - ui/coop_custom.urc, the Armory's CUSTOMIZE bench (engrave PLAN, 2026-11-09).

Opened from the Armory hero ("CUSTOMIZE": hzmcust open; pushmenu coop_custom). It edits the gun the Armory is inspecting
(coop_loPrev). Every control is the client command `hzmcust` (client/cl_engrave.cpp); the command publishes the bench's
state as display cvars (cl_cust*Txt, cl_custItem<n>, cl_custState) and the unsaved choices as cl_custEdit, which the
preview here and the gun in hand both draw. SAVE writes the archived cvar cl_cust_<gun>; BACK without SAVE drops edits.
The words are one archived cvar for every gun (cl_engraveText), typed in the field.

Layout: the menu's 640x480 virtual grid; fonts verdana-12 and facfont-20 only (docs/ENGINE.md uilib); each resource field
on its own line (single-line resource blocks silently drop).

    python docs/tools/engrave/gen_custom_urc.py --mod <mod checkout> [--check]
"""
import os
import sys

TRACK = (0.075, 0.071, 0.067)
PANEL = (0.110, 0.106, 0.098)
PANEL2 = (0.149, 0.141, 0.129)
LINE = (0.239, 0.224, 0.204)
CREAM = (0.941, 0.910, 0.839)
DIM = (0.612, 0.584, 0.525)
FAINT = (0.384, 0.365, 0.329)
ORANGE = (1.000, 0.659, 0.200)
GREEN = (0.549, 0.780, 0.451)
CARD_BACK = (0.205, 0.196, 0.178)
FIT_ASPECT = "1.7778"            # as the Armory's model widgets (gen_armory_urc.py): the hero transforms were measured at 16:9
OUT = []


def c4(c, a=1.0):
    return "%.2f %.2f %.2f %.2f" % (c[0], c[1], c[2], a)


def res(typ, name, rect, fg=CREAM, bg=None, bga=1.0, title=None, font="verdana-12", align=None, link=None, enable=None,
        stuff=None, sound=None, border="NONE", extra=()):
    p = ["name \"%s\"" % name]
    if title is not None:
        p.append("title \"%s\"" % title)
    p.append("rect %d %d %d %d" % rect)
    p.append("fgcolor " + c4(fg))
    p.append("bgcolor " + (c4(bg, bga) if bg else "0.00 0.00 0.00 0.00"))
    p.append("borderstyle \"%s\"" % border)
    if font:
        p.append("font %s" % font)
    if align:
        p.append("textalign %s" % align)
    if enable:
        p.append("enabledcvar \"%s\"" % enable)
    if link:
        p.append("linkcvar \"%s\"" % link)
    if sound:
        p.append("clicksound \"%s\"" % sound)
    if stuff:
        p.append("stuffcommand \"%s\"" % stuff)
    p += list(extra)
    OUT.append("resource\n%s\n{\n%s\n}\n" % (typ, "\n".join(p)))


def text(name, x, y, w, s=None, link=None, col=CREAM, font="verdana-12", h=12, align="left", enable=None):
    res("Label", name, (x, y, w, h), fg=col, title=s if s is not None else "", font=font, align=align, link=link, enable=enable,
        extra=["dontlocalize"])


def box(name, x, y, w, h, fill=PANEL, enable=None):
    res("Label", name, (x, y, w, h), bg=fill, title="", enable=enable)


def button(name, x, y, w, h, label, cmd, col=CREAM, fill=PANEL2, sound="sound/menu/scroll.wav", enable=None):
    res("Button", name, (x, y, w, h), fg=col, bg=fill, title=label, stuff=cmd, sound=sound, enable=enable,
        extra=["hovershader \"textures/mohmenu/hzm_theme/mpui_glow\""])


def stepper(name, x, y, w, cap, link, minus, plus):
    """CAP   < value >"""
    text(name + "Cap", x, y, 60, cap, col=DIM)
    button(name + "M", x + 62, y - 1, 14, 14, "<", "hzmcust " + minus)
    text(name + "V", x + 80, y, w - 100, link=link, col=CREAM)
    button(name + "P", x + w - 16, y - 1, 14, 14, ">", "hzmcust " + plus)


def build():
    OUT.clear()
    head = ("// HZM coop - the Armory's CUSTOMIZE bench. GENERATED by docs/tools/engrave/gen_custom_urc.py: do not edit.\n"
            "// Controls are the client command hzmcust (client/cl_engrave.cpp); it edits the gun the Armory inspects (coop_loPrev).\n"
            "menu \"coop_custom\" 640 480 NONE 1\nborderstyle NONE\nbgcolor 0 0 0 0\nalign centerx centery\nvirtualres 1\nfullscreen 0\n"
            # [benchfix2] ESC keeps the work like BACK and SAVE (the Armory name screen's convention): hzmcust done saves and
            # leaves with popmenu 0 - popmenu 1 would restore the words field's cvar to its value from when the bench opened
            "escapecommand \"hzmcust done\"\n\n")
    res("Label", "bg", (0, 0, 640, 480), bg=(0.05, 0.06, 0.08), title="", extra=["ordernumber 1"])
    text("title", 20, 10, 220, "CUSTOMIZE BENCH", col=ORANGE, font="facfont-20", h=18)
    text("gun", 250, 12, 370, link="coop_loNm", col=CREAM, font="facfont-20", h=18, align="right", enable="cl_custHasGun")
    res("Label", "topRule", (20, 32, 600, 2), bg=ORANGE, title="")

    # ---------------------------------------------------------------- the preview: the hero render, bigger (same 2.6:1 box)
    box("pvBack", 20, 38, 600, 231, fill=CARD_BACK)
    res("Label", "pvGun", (20, 38, 600, 231), link="cl_custModel", enable="cl_custHasGun",
        extra=["ordernumber 20", "modelxformcvar \"cl_custXfm\"", "rendermodel 1", "rendermodelfit 1",
               "modelfitaspect " + FIT_ASPECT, "modeloffset \"0 0 0\"", "modelrotateoffset \"0 0 0\"", "modelangles \"0 90 180\"",
               "modelscale 1.00", "modelanim idle", "modelspincvar \"cl_custSpin\"",
               "modeltiltcvar \"cl_custTilt\""])   # [benchfix] the drag tilts too (+-60, engine-clamped)
    text("pvNone", 30, 140, 580, "THIS GUN HAS NO ENGRAVING SPOT YET.", col=DIM, align="center", enable="cl_custNoGun")
    text("pvHint", 26, 254, 400, "DRAG TO TURN AND TILT THE GUN.", col=FAINT)
    button("zoom", 426, 249, 92, 16, "ZOOM", "hzmcust zoom")
    button("turn", 524, 249, 92, 16, "TURN OVER", "hzmcust turn")

    # ---------------------------------------------------------------- left: the words
    box("wordsPanel", 20, 276, 290, 150)
    # [benchsize] per-gun words: this gun's own words (empty = it uses the default words), and the default words for every
    # gun without its own; both fields write their cvar as you type, hzmcust done keeps them (cl_words_<gun>, cl_engraveText)
    text("wordsCap", 28, 280, 160, "WORDS FOR THIS GUN", col=DIM)
    text("wordsState", 160, 280, 142, link="cl_custWordsTxt", col=ORANGE, align="right", enable="cl_custOwnWords")
    text("wordsStateD", 160, 280, 142, link="cl_custWordsTxt", col=FAINT, align="right", enable="cl_custOwnWordsNot")
    res("Field", "words", (28, 293, 274, 22), fg=(0.16, 0.09, 0.03), bg=(0.97, 0.95, 0.88), title="engraving",
        font="facfont-20", align="left", link="cl_custWords", sound="sound/menu/scroll.wav", border="INDENT_BORDER",
        extra=["SetMaxChars 20"])
    button("wordsDefault", 222, 317, 80, 14, "USE DEFAULT", "hzmcust words default")
    text("wordsHint1", 28, 318, 190, "EMPTY = THE DEFAULT WORDS BELOW", col=FAINT)
    text("defCap", 28, 334, 274, "DEFAULT WORDS (ALL GUNS)", col=DIM)
    res("Field", "wordsDef", (28, 347, 274, 20), fg=(0.16, 0.09, 0.03), bg=(0.90, 0.88, 0.80), title="default engraving",
        font="verdana-12", align="left", link="cl_engraveText", sound="sound/menu/scroll.wav", border="INDENT_BORDER",
        extra=["SetMaxChars 20"])
    text("wordsHint2", 28, 370, 274, "UP TO 20: A-Z 0-9 . - ! ? & # / : ( ) + * = % $", col=FAINT)
    button("textToggle", 28, 384, 160, 14, "SHOW / HIDE ON THIS GUN", "hzmcust item 0;hzmcust text")
    text("textState", 194, 385, 108, link="cl_custEmbTxt", col=CREAM, enable="cl_custItem0")
    text("finState", 28, 404, 160, link="cl_custFinTxt", col=DIM)
    button("finToggle", 222, 401, 80, 16, "TOGGLE", "hzmcust finish")

    # ---------------------------------------------------------------- right: what to place, where, how
    box("placePanel", 320, 276, 300, 150)
    for i, lab in enumerate(("ENGRAVING", "EMBLEM 1", "EMBLEM 2")):
        x = 326 + i * 98
        box("tabOn%d" % i, x, 281, 94, 16, fill=(0.40, 0.27, 0.08), enable="cl_custItem%d" % i)
        button("tab%d" % i, x, 281, 94, 16, lab, "hzmcust item %d" % i, fill=PANEL2)
        res("Label", "tabLine%d" % i, (x, 296, 94, 2), bg=ORANGE, title="", enable="cl_custItem%d" % i)
    text("embCapT", 328, 304, 60, "EMBLEM", col=DIM, enable="cl_custItem0")
    text("embNa", 410, 304, 200, "THE WORDS ABOVE", col=FAINT, enable="cl_custItem0")
    for i in (1, 2):
        stepper("emb%d" % i, 328, 304, 286, "EMBLEM", "cl_custEmbTxt", "emblem -1", "emblem 1")
        # the stepper widgets belong to the emblem tabs only
        for k in range(len(OUT) - 4, len(OUT)):
            OUT[k] = OUT[k].replace("\n}\n", "\nenabledcvar \"cl_custItem%d\"\n}\n" % i)
    stepper("spot", 328, 324, 286, "SPOT", "cl_custSpotTxt", "spot -1", "spot 1")
    text("moveCap", 328, 346, 34, "MOVE", col=DIM)
    # [benchfix] the face is the limit now, not a short range: a step of a quarter unit, a fast step of 1.5 to cross the gun,
    # up / down in tenths (faces are short that way); the engine keeps the whole piece on usable face
    for j, (lab, cmd) in enumerate((("<<", "move -1.5 0"), ("<", "move -0.25 0"), (">", "move 0.25 0"), (">>", "move 1.5 0"),
                                    ("^", "move 0 0.1"), ("v", "move 0 -0.1"))):
        button("mv%d" % j, 362 + j * 17, 344, 16, 14, lab, "hzmcust " + cmd)
    text("tiltCap", 470, 346, 30, "TILT", col=DIM)
    button("rotM", 502, 344, 16, 14, "-", "hzmcust rot -5")
    button("rotP", 520, 344, 16, 14, "+", "hzmcust rot 5")
    text("sizeCap", 546, 346, 30, "SIZE", col=DIM)
    button("scM", 580, 344, 16, 14, "-", "hzmcust scale -0.25")   # [benchsize] 25 % a press, 50..200 %, the face caps it
    button("scP", 598, 344, 16, 14, "+", "hzmcust scale 0.25")
    text("nudge", 328, 366, 196, link="cl_custNudgeTxt", col=CREAM)
    text("sizeNote", 516, 366, 98, link="cl_custSizeNote", col=ORANGE, align="right")   # MAX FOR THIS SPOT / MIN SIZE
    button("mirror", 328, 386, 90, 16, "MIRROR", "hzmcust mirror")
    button("center", 424, 386, 90, 16, "CENTRE", "hzmcust center")
    text("embHint", 328, 408, 286, "EMBLEMS: INSIGNIA, AWARDS, TRENCH ART, MOH SERIES.", col=FAINT)

    # ---------------------------------------------------------------- footer
    res("Label", "ftrLine", (20, 436, 600, 1), bg=LINE, title="")
    button("reset", 20, 446, 110, 20, "RESET GUN", "hzmcust reset", col=DIM)
    text("state", 300, 450, 180, link="cl_custState", col=ORANGE, align="right", enable="cl_custDirty")
    text("stateOk", 300, 450, 180, link="cl_custState", col=GREEN, align="right", enable="cl_custSaved")
    text("keepHint", 140, 452, 150, "LEAVING KEEPS YOUR WORK", col=FAINT)
    button("save", 490, 446, 60, 20, "SAVE", "hzmcust done", col=ORANGE, sound="sound/menu/apply.wav")   # [benchfix2] save + back to the Armory
    button("back", 560, 446, 60, 20, "BACK", "hzmcust done", sound="sound/menu/back.wav")
    return head + "\n".join(OUT) + "end.\n"


def main():
    mod = sys.argv[sys.argv.index("--mod") + 1] if "--mod" in sys.argv else r"C:\mohaa-coop-dev\hzm-mod-engrave"
    out = os.path.join(mod, "ui", "coop_custom.urc")
    data = build()
    if "--check" in sys.argv:
        ok = os.path.exists(out) and open(out, encoding="utf-8").read() == data
        print("coop_custom.urc", "ok" if ok else "STALE")
        sys.exit(0 if ok else 1)
    open(out, "w", encoding="utf-8", newline="\n").write(data)
    print("wrote", out)


if __name__ == "__main__":
    main()
