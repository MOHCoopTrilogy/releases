"""gen_engrave_slots.py - scripts/hzm_engrave_slots.shader: the per-gun words' shaders (benchsize, 2026-11-10).

Each gun may have its own words (cl_words_<gun>); the client carves every distinct text into a slot of its own images,
textures/hzm/engrave_dyn{,2,3}_s<k>.tga (client/cl_engrave.cpp: slot 1 = the gun in hand, 2..7 = the Armory / bench
previews; slot 0 = the default words, the original images and shaders in scripts/hzm_engrave.shader). This copies the six
text shaders of hzm_engrave.shader (wood / metal x one line / two lines / short words) for slots 1..7, so a change to
the carving's look is made once, in hzm_engrave.shader, and regenerated here.

    python docs/tools/engrave/gen_engrave_slots.py --mod <mod checkout> [--check]
"""
import os
import re
import sys

SLOTS = range(1, 8)
NAMES = ("engrave_wood", "engrave_metal", "engrave_wood2", "engrave_metal2", "engrave_wood3", "engrave_metal3")


def build(mod):
    src = open(os.path.join(mod, "scripts", "hzm_engrave.shader"), encoding="utf-8").read()
    out = ["// GENERATED by docs/tools/engrave/gen_engrave_slots.py from scripts/hzm_engrave.shader - do not hand-edit.\n"
           "// The per-gun words' shaders: slot k samples textures/hzm/engrave_dyn{,2,3}_s<k>.tga (client/cl_engrave.cpp).\n\n"]
    for k in SLOTS:
        for nm in NAMES:
            m = re.search(r"(?ms)^textures/hzm/%s\s*\n\{.*?^\}\s*$" % re.escape(nm), src)
            if not m:
                raise SystemExit("no shader %s in hzm_engrave.shader" % nm)
            blk = m.group(0)
            blk = blk.replace("textures/hzm/%s" % nm, "textures/hzm/%s_s%d" % (nm, k), 1)
            blk = re.sub(r"textures/hzm/(engrave_dyn[23]?)\.tga", r"textures/hzm/\1_s%d.tga" % k, blk)
            out.append(blk.rstrip() + "\n\n")
    return "".join(out)


def main():
    mod = sys.argv[sys.argv.index("--mod") + 1] if "--mod" in sys.argv else r"C:\mohaa-coop-dev\hzm-mohaa-coop-mod"
    p = os.path.join(mod, "scripts", "hzm_engrave_slots.shader")
    data = build(mod)
    if "--check" in sys.argv:
        ok = os.path.exists(p) and open(p, encoding="utf-8").read() == data
        print("hzm_engrave_slots.shader", "ok" if ok else "STALE")
        sys.exit(0 if ok else 1)
    open(p, "w", encoding="utf-8", newline="\n").write(data)
    print("wrote", p)


if __name__ == "__main__":
    main()
