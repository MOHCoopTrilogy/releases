def c4(c, a=1.0):
    return "%.2f %.2f %.2f %.2f" % (c[0], c[1], c[2], a)


# ------------------------------------------------------------------ the frozen baseline
def read_base():
    t = open(BASE, encoding="latin-1").read().replace("\r\n", "\n")
    head = ("// HZM coop - ARMORY Showroom loadout screen. GENERATED by docs/tools/gen_armory_urc.py (called from gen_loadout.py): do not edit.\n"
            "// Picker = 18 card positions fed by the cfg chains of gen_armory.py (unlocked first); hero + compare read the inspected gun.\n"
            + t[t.index("menu \"coop_loadout\""):t.index("resource")])
    ws = {}
    order = []
    for m in re.finditer(r"resource\s*\n(\w+)\s*\n\{\n(.*?)\n\}", t, re.S):
        typ, body = m.group(1), m.group(2)
        props = []
        for ln in body.split("\n"):
            if not ln.strip():
                continue
            k, _, v = ln.partition(" ")
            props.append((k, v))
        nm = dict(props).get("name", "").strip('"')
        ws[nm] = (typ, props)
        order.append(nm)
    return head, ws, order


class Out:
    def __init__(self, base):
        self.base = base
        self.parts = []
        self.names = set()

    def raw(self, typ, props):
        self.parts.append("resource\n%s\n{\n%s\n}\n" % (typ, "\n".join("%s %s" % (k, v) if v != "" else k for k, v in props)))
        for k, v in props:
            if k == "name":
                self.names.add(v.strip('"'))

    def new(self, typ, name, rect, **kw):
        """a fresh widget. kw: fg, bg (colour tuples or ('a', tuple, alpha)), title, font, link, enable, shader, stuff, hover, away,
        sound, border, align, dontloc, order, extra=[(k, v)...]"""
        p = []
        if kw.get("order") is not None:
            p.append(("ordernumber", str(kw["order"])))
        p.append(("name", '"%s"' % name))
        if kw.get("title") is not None:
            p.append(("title", '"%s"' % kw["title"]))
        p.append(("rect", " ".join(str(v) for v in rect)))
        fg = kw.get("fg", CREAM)
        p.append(("fgcolor", c4(fg[0], fg[1]) if isinstance(fg, tuple) and len(fg) == 2 and isinstance(fg[0], tuple) else c4(fg)))
        bg = kw.get("bg")
        if bg is None:
            p.append(("bgcolor", "0.00 0.00 0.00 0.00"))
        elif isinstance(bg[0], tuple):
            p.append(("bgcolor", c4(bg[0], bg[1])))
        else:
            p.append(("bgcolor", c4(bg)))
        p.append(("borderstyle", '"%s"' % kw.get("border", "NONE")))
        if kw.get("font"):
            p.append(("font", '"%s"' % kw["font"]))
        if kw.get("dontloc"):
            p.append(("dontlocalize", ""))
        if kw.get("align"):
            p.append(("textalign", kw["align"]))
        if kw.get("sound"):
            p.append(("clicksound", '"%s"' % kw["sound"]))
        if kw.get("enable"):
            p.append(("enabledcvar", '"%s"' % kw["enable"]))
        if kw.get("link"):
            p.append(("linkcvar", '"%s"' % kw["link"]))
        if kw.get("shader"):
            p.append(("shader", '"%s"' % kw["shader"]))
        if kw.get("stuff"):
            p.append(("stuffcommand", '"%s"' % kw["stuff"]))
        if kw.get("hover"):
            p.append(("hovercommand", '"%s"' % kw["hover"]))
        if kw.get("away"):
            p.append(("mouseawaycommand", '"%s"' % kw["away"]))
        for k, v in kw.get("extra", []):
            p.append((k, v))
        self.raw(typ, p)

    def carry(self, name, rect=None, **over):
        """a baseline widget, behaviour verbatim; rect / fgcolor / bgcolor / borderstyle / font / title / textalign may be replaced"""
        typ, props = self.base[name]
        res = []
        seen = set()
        for k, v in props:
            if k in over:
                v = over[k]
            if k == "rect" and rect is not None:
                v = " ".join(str(x) for x in rect)
            seen.add(k)
            res.append((k, v))
        for k, v in over.items():
            if k not in seen:
                res.append((k, v))
        self.raw(typ, res)

    # --- composites
    def box(self, name, x, y, w, h, fill=PANEL, line=LINE, enable=None, a=1.0):
        self.new("Label", name + "_l", (x, y, w, h), bg=line, enable=enable)
        self.new("Label", name, (x + 1, y + 1, w - 2, h - 2), bg=(fill, a) if a != 1.0 else fill, enable=enable)

    def rule(self, name, x, y, w, h=1, col=LINE, enable=None):
        self.new("Label", name, (x, y, w, h), bg=col, enable=enable)

    def text(self, name, x, y, w, s=None, link=None, col=CREAM, font="verdana-12", h=None, align="left", enable=None):
        self.new("Label", name, (x, y, w, h or (12 if font == "verdana-12" else 14)), fg=col, title=s, link=link, font=font,
                 dontloc=True, align=align, enable=enable)

    def render(self, head):
        return head + "".join(p + "\n" for p in self.parts) + "end.\n"


