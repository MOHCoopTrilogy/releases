#!/usr/bin/env python3
"""gen_rkeep_lists.py - generate the cvar lists the keep-renderer registration check needs
(docs/proposals/renderer_reinit_2026-09-26/plan.md 2.1/2.4), from the SAME classifier the live-graphics-settings audit
uses (docs/tools/gfx_live_audit.py - one classifier, live_graphics_settings plan K3). Never hand-edit the output.

Output: <engine>/renderergl2/tr_hzm_keeplists.h with two NULL-terminated string arrays:
  hzmKeepWindowCvars    cvars that take effect only when the window/context is created (class WINDOW, or registered
                        by sdl/*). A pending latch on one of them does NOT force the full re-init: today's per-map
                        R_Init keeps the window too (InitOpenGL skips GLimp_Init once glConfig.vidWidth != 0), so the
                        map load never applied them either.
  hzmKeepInitReadCvars  NON-latched gl2 cvars with a read in the INIT phase (R_Init and what it calls, stopping at
                        image/shader/world roots). Their modificationCount is snapshotted at the end of R_Init; a
                        change forces the full re-init at the next registration, which is what a map load does today.
                        ASSET-phase readers (images, shaders) are not listed: the fast path rebuilds shaders and
                        re-loads images every map, so they apply at the next map anyway.

  python gen_rkeep_lists.py [--engine DIR]      write (DIR defaults to openmohaa-hzm-keep/code)
  python gen_rkeep_lists.py --check [--engine DIR]   exit 1 if the header is stale
"""
import io, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
sys.path.insert(0, TOOLS)

DEV = os.path.dirname(os.path.dirname(TOOLS))
eng = os.path.join(DEV, "openmohaa-hzm-keep", "code")
if "--engine" in sys.argv:
    eng = os.path.abspath(sys.argv[sys.argv.index("--engine") + 1])

import gfx_live_audit as A  # noqa: E402

A.ENG = eng

# Functions the keep fast path re-runs on every registration (tr_hzm_keep_fast.h). A cvar whose EVERY init-phase read
# sits in one of them is re-applied per map on both paths, so a change must not force the full re-init (vet E2-13,
# P1 review R3-7: r_offsetfactor/r_offsetunits, read only in GL_SetDefaultState). Keep this set in step with the
# fast path. r_maxtermarks stays listed: E2-13 called it dead, but tr_scene.c RE_AddTerrainMarkToScene reads
# max_termarks, which only R_Init assigns.
FASTPATH_RERUNS = {"GL_SetDefaultState", "R_SetupShaders", "CreateInternalShaders", "CreateExternalShaders",
                   "R_InitSkins", "R_ModelInit", "R_Sky_Init", "R_InitNextFrame"}


def main():
    idx = {k: A.CvarIndex(A.Module(k)) for k in A.MODULES}
    gl2 = idx["gl2"]
    window, initread, rerun = [], [], []
    for lname in sorted(gl2.regs):
        regs = gl2.regs[lname]
        c = A.classify(lname, "gl2", idx)
        flags = c["flags"]
        in_sdl = any(r["file"].replace("\\", "/").startswith("code/sdl/") or "/sdl/" in r["file"].replace("\\", "/")
                     for r in regs)
        if c["cls"].startswith("WINDOW") or in_sdl:
            window.append(lname)
            continue
        if "LATCH" in flags or "ROM" in flags:
            continue
        if c["cls"].startswith("LIVE"):
            continue   # re-applied per frame (e.g. r_textureMode on ->modified): nothing to re-init
        if "INIT" in c["phases"]:
            init_reads = [r for r in c.get("reads", []) if "INIT" in (r.get("phases") or [])]
            if init_reads and all((r.get("func") or "").split("::")[-1] in FASTPATH_RERUNS for r in init_reads):
                rerun.append(lname)
                continue
            initread.append(lname)
    out = io.StringIO()
    out.write("// GENERATED by docs/tools/rkeep/gen_rkeep_lists.py from docs/tools/gfx_live_audit.py - DO NOT EDIT.\n")
    out.write("// renderer_reinit plan 2.1/2.4: window-only cvars (never force the full re-init) and non-latched\n")
    out.write("// R_Init-read cvars (a changed modificationCount forces it). Lower-case names; Q_stricmp compares.\n")
    out.write("#pragma once\n\n")
    out.write("static const char *const hzmKeepWindowCvars[] = {\n")
    for n in window:
        out.write('\t"%s",\n' % n)
    out.write("\tNULL\n};\n\n")
    if rerun:
        out.write("// re-applied by the fast path itself (FASTPATH_RERUNS), so not listed: %s\n" % ", ".join(rerun))
    out.write("static const char *const hzmKeepInitReadCvars[] = {\n")
    for n in initread:
        out.write('\t"%s",\n' % n)
    out.write("\tNULL\n};\n")
    text = out.getvalue()
    dst = os.path.join(eng, "renderergl2", "tr_hzm_keeplists.h")
    if "--check" in sys.argv:
        cur = open(dst, encoding="utf-8").read() if os.path.exists(dst) else ""
        if cur != text:
            print("STALE:", dst)
            return 1
        print("current:", dst)
        return 0
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s: %d window, %d init-read" % (dst, len(window), len(initread)))
    print("window:", ", ".join(window))
    print("init-read:", ", ".join(initread))
    return 0


if __name__ == "__main__":
    sys.exit(main())
