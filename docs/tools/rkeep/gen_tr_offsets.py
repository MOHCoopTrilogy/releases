#!/usr/bin/env python3
"""gen_tr_offsets.py - generate, from renderergl2/tr_local.h, the tables the keep-renderer audits need
(renderer_reinit plan 2.7 / 9.2, vet E2-11, H2-2b). The compiler validates every entry, so a stale or wrong table
fails the build instead of lying. Never hand-edit the output.

  hzmKeepFields_<struct>[]   {name, offset, size} of every TOP-LEVEL field of trGlobals_t, backEndState_t, glstate_t
                             (drift audit), plus compile-time gap assertions so a field added later cannot hide
                             between two listed ones
  hzmKeepImageFields[]       every image_t* (or image_t* array) field of trGlobals_t: the "permanent holders" whose
                             images the per-map sweep must never delete (role audit)

  python gen_tr_offsets.py [--engine DIR]          write DIR/renderergl2/tr_hzm_troffsets.h (DIR: openmohaa-hzm-keep/code)
  python gen_tr_offsets.py --check [--engine DIR]  exit 1 if stale
"""
import io, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEV = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
eng = os.path.join(DEV, "openmohaa-hzm-keep", "code")
if "--engine" in sys.argv:
    eng = os.path.abspath(sys.argv[sys.argv.index("--engine") + 1])
STRUCTS = ["trGlobals_t", "backEndState_t", "glstate_t"]
MAX_GAP = 8   # bytes of padding tolerated between two consecutive listed fields


def strip_comments(t):
    t = re.sub(r"/\*.*?\*/", " ", t, flags=re.S)
    return re.sub(r"//[^\n]*", " ", t)


def fields_of(text, tname):
    """[(name, declaration text of that declarator)] for the top-level fields of the struct typedef'd as tname."""
    m = re.search(r"\n\}\s*" + re.escape(tname) + r"\s*;", text)
    if not m:
        raise SystemExit("struct %s not found" % tname)
    end = m.start() + 1            # index of the closing brace
    depth, i = 0, end
    while i >= 0:                  # walk back to the matching opening brace
        if text[i] == "}":
            depth += 1
        elif text[i] == "{":
            depth -= 1
            if depth == 0:
                break
        i -= 1
    body = text[i + 1:end]
    depth, flat = 0, []
    for ch in body:
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        elif depth == 0:
            flat.append(ch)
    body = "".join(flat)
    body = re.sub(r"#\s*(if|ifdef|ifndef|else|elif|endif)[^\n]*", " ", body)
    out = []
    for decl in body.split(";"):
        decl = " ".join(decl.split())
        if not decl:
            continue
        if "(" in decl:
            m2 = re.search(r"\(\s*\*\s*(\w+)\s*\)", decl)
            if m2:
                out.append((m2.group(1), decl))
                continue
            raise SystemExit("cannot parse member of %s: %s" % (tname, decl))
        # split "type a, *b, c[4]" into declarators sharing the base type
        first = re.match(r"^(.*?)([\*\s]*)([A-Za-z_]\w*)(\s*\[[^\]]*\])*\s*(,.*)?$", decl)
        if not first:
            raise SystemExit("cannot parse member of %s: %s" % (tname, decl))
        base = first.group(1).strip()
        declarators = [d.strip() for d in decl[len(base):].split(",")]
        for d in declarators:
            nm = re.findall(r"[A-Za-z_]\w*", re.sub(r"\[[^\]]*\]", "", d))
            if nm:
                out.append((nm[-1], base + " " + d))
    return out


def main():
    text = strip_comments(open(os.path.join(eng, "renderergl2", "tr_local.h"), encoding="utf-8", errors="replace").read())
    o = io.StringIO()
    o.write("// GENERATED by docs/tools/rkeep/gen_tr_offsets.py from renderergl2/tr_local.h - DO NOT EDIT.\n")
    o.write("// Top-level fields of the renderer's global state (drift audit) and trGlobals_t's image_t* fields (role\n")
    o.write("// audit). Include only from tr_hzm_keep.c.\n#pragma once\n#include <stddef.h>\n\n")
    o.write("typedef struct { const char *name; size_t off, size; } hzmKeepField_t;\n\n")
    counts = {}
    for t in STRUCTS:
        fl = fields_of(text, t)
        counts[t] = len(fl)
        o.write("static const hzmKeepField_t hzmKeepFields_%s[] = {\n" % t)
        for n, _ in fl:
            o.write('\t{ "%s", offsetof(%s, %s), sizeof(((%s *)0)->%s) },\n' % (n, t, n, t, n))
        o.write("\t{ NULL, 0, 0 }\n};\n")
        # completeness: consecutive listed fields leave at most MAX_GAP bytes; the last one reaches the end
        for k in range(len(fl) - 1):
            a, b = fl[k][0], fl[k + 1][0]
            o.write("typedef char hzmKeepGap_%s_%d[(offsetof(%s, %s) - (offsetof(%s, %s) + sizeof(((%s *)0)->%s))) "
                    "<= %d ? 1 : -1];\n" % (t, k, t, b, t, a, t, a, MAX_GAP))
        last = fl[-1][0]
        o.write("typedef char hzmKeepGap_%s_end[(sizeof(%s) - (offsetof(%s, %s) + sizeof(((%s *)0)->%s))) <= %d ? 1 : -1];\n\n"
                % (t, t, t, last, t, last, MAX_GAP))
    imgs = [(n, d) for n, d in fields_of(text, "trGlobals_t")
            if re.match(r"^(struct\s+image_s|image_t)\s*\*\s*[A-Za-z_]", d.replace(" *", "*").replace("* ", "*").replace("*", " *", 1))
            and "**" not in d.replace(" ", "") and n != "images"]  # tr.images is the registry, not a holder
    o.write("typedef struct { const char *name; size_t off; int count; } hzmKeepImageField_t;\n")
    o.write("static const hzmKeepImageField_t hzmKeepImageFields[] = {\n")
    for n, _ in imgs:
        o.write('\t{ "%s", offsetof(trGlobals_t, %s), (int)(sizeof(((trGlobals_t *)0)->%s) / sizeof(image_t *)) },\n'
                % (n, n, n))
    o.write("\t{ NULL, 0, 0 }\n};\n")
    out = o.getvalue()
    dst = os.path.join(eng, "renderergl2", "tr_hzm_troffsets.h")
    if "--check" in sys.argv:
        cur = open(dst, encoding="utf-8").read() if os.path.exists(dst) else ""
        print("current" if cur == out else "STALE", dst)
        return 0 if cur == out else 1
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print("wrote %s %s image fields=%d" % (dst, counts, len(imgs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
