#!/usr/bin/env python3
"""Generate ui/hzm_pushmaps.urc - the PUSH campaign-map picker (reached from the Push team board's
"Campaign Maps" button). Lists every campaign map Push supports, titled with its thematic mission name.

SINGLE SOURCE OF TRUTH for the titles is coop_mod/mp_maptitles.scr (the same names the rotation announce
and the Push HUD use); this parses them out so the picker can never drift from the in-game display. The
map ORDER/roster lives here. Each button arms the one-shot engine arena gate sv_mpForceArena and sets
ui_dmmap, exactly like the sibling pickers; isolation-clean (sets only ui_dmmap + sv_mpForceArena).

Run:  python docs/tools/gen_pushmaps_menu.py         (write)
      python docs/tools/gen_pushmaps_menu.py check   (exit 1 if the .urc is stale)
"""
import sys, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "hzm-mohaa-coop-mod", "ui", "hzm_pushmaps.urc")
TITLES_SCR = os.path.join(ROOT, "hzm-mohaa-coop-mod", "coop_mod", "mp_maptitles.scr")

# Roster + order for the picker: 7 live Push maps, then 6 BSP-derived Tier-1, then 10 BSP-derived Tier-2.
MAPS = ["m1l2b", "m2l1", "m3l3", "m4l1", "m4l2", "m5l1a", "m5l1b",
        "t3l1", "t2l1", "t2l3", "t2l4", "m5l2a", "m3l1b",
        "m2l3", "m1l3a", "m1l3b", "e1l1", "e3l1", "e3l2", "e3l3", "t1l1", "t1l2", "t1l3"]
        # m5l2b PULLED (bug-2747): SP King Tiger tank-drive map, on-foot players fall through the world.
        # m5l3 PULLED (bug-2832, user 2026-09-23): Rocket Facility - allies spawn inside a building and jam in a
        #   stairwell corner, axis spawn OFF the playable map. "Just NOT a good map for this" - removed from Push.

COLS = 4
COL_X = [92, 206, 320, 434]
BTN_W = 108
ROW_Y0 = 122
ROW_DY = 30
BTN_H = 26


def load_titles():
    """Parse map -> title from mp_maptitles.scr (the in-game display source of truth)."""
    txt = open(TITLES_SCR, encoding="latin-1").read()
    t = {}
    for m, title in re.findall(r'local\.m\s*==\s*"(\w+)"\s*\)\s*\{\s*end\s+"([^"]+)"', txt):
        t[m] = title
    return t


def build():
    titles = load_titles()
    missing = [m for m in MAPS if m not in titles]
    if missing:
        raise SystemExit("mp_maptitles.scr has no title for: " + ", ".join(missing))
    L = []
    L.append("// GENERATED by docs/tools/gen_pushmaps_menu.py. Do NOT hand-edit (regenerate instead).")
    L.append("// PUSH campaign-map picker. Titles come from coop_mod/mp_maptitles.scr (same names the rotation")
    L.append("// announce + Push HUD use). Reached from the PUSH-only 'Campaign Maps' button on the team board.")
    L.append("// Each button arms sv_mpForceArena and sets ui_dmmap; isolation-clean.")
    L.append('menu "hzm_pushmaps" 640 480 NONE 0')
    L.append("bgcolor 1 1 1 1")
    L.append("borderstyle NONE")
    L.append("bgfill 0 0 0 1")
    L.append("fullscreen 1")
    L.append("virtualres 1")
    L.append('include "ui/multiplayerback.inc"')
    L += ["resource", "Label", "{", 'name "bg_panel"', "rect 84 56 472 372",
          "fgcolor 0.84 0.82 0.76 1.00", "bgcolor 0.05 0.06 0.08 1.00", 'borderstyle "RAISED"', "}"]
    L += ["resource", "Label", "{", 'name "caption"', 'title "PUSH CAMPAIGN MAPS"',
          "rect 84 66 472 22", "fgcolor 0.86 0.74 0.44 1.00", "bgcolor 0.00 0.00 0.00 0.00",
          'borderstyle "NONE"', 'font "facfont-20"', "textalign xcenter", "}"]
    L += ["resource", "Label", "{", 'name "sub"',
          'title "Trilogy missions - single front, push to the enemy spawn"',
          "rect 84 92 472 16", "fgcolor 0.55 0.60 0.66 1.00", "bgcolor 0.00 0.00 0.00 0.00",
          'borderstyle "NONE"', 'font "verdana-12"', "textalign xcenter", "}"]
    for i, m in enumerate(MAPS):
        col = i % COLS
        row = i // COLS
        x = COL_X[col]
        y = ROW_Y0 + row * ROW_DY
        L += ["resource", "Button", "{",
              'name "map_%s"' % m,
              'title "%s"' % titles[m],
              "rect %d %d %d %d" % (x, y, BTN_W, BTN_H),
              "fgcolor 1.00 1.00 1.00 1.00", "bgcolor 0.09 0.10 0.13 0.90",
              'borderstyle "3D_BORDER"', 'font "verdana-12"',
              'clicksound "sound/menu/apply.wav"',
              'stuffcommand "set sv_mpForceArena 1 ; set ui_dmmap %s ; popmenu 0"' % m,
              "}"]
    L += ["resource", "Label", "{", 'name "hint"',
          'title "Pick a campaign map, then Start Game."',
          "rect 84 344 472 16", "fgcolor 0.55 0.60 0.66 1.00", "bgcolor 0.00 0.00 0.00 0.00",
          'borderstyle "NONE"', 'font "verdana-12"', "textalign xcenter", "}"]
    L += ["resource", "Button", "{", 'name "back"', "rect 8 448 96 24",
          "fgcolor 1.00 1.00 1.00 1.00", "bgcolor 0.50 0.50 0.50 0.00", 'borderstyle "3D_BORDER"',
          'shader "textures/mohmenu/back"', 'hovershader "textures/mohmenu/back_h"',
          'clicksound "sound/menu/back.wav"', 'stuffcommand "Popmenu 0"', "}"]
    L.append("end.")
    return "\n".join(L) + "\n"


def main():
    text = build()
    if len(sys.argv) > 1 and sys.argv[1] == "check":
        cur = open(OUT, encoding="latin-1").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("STALE: hzm_pushmaps.urc differs from generator output"); sys.exit(1)
        print("OK: hzm_pushmaps.urc matches generator"); return
    open(OUT, "w", encoding="latin-1", newline="\n").write(text)
    print("wrote %s (%d maps)" % (os.path.relpath(OUT, ROOT), len(MAPS)))


if __name__ == "__main__":
    main()
