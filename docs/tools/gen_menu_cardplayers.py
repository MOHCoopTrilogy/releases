"""gen_menu_cardplayers.py - the MP room's card player in the player's own coop uniform (user 2026-11-16: "Can we have the
soldier playing cards in the join game menu be your coop character?").

    python -I docs/tools/gen_menu_cardplayers.py build    # write hzm-mohaa-coop-mod/models/human/hzm_menu/cards/<uniform>.tik
    python -I docs/tools/gen_menu_cardplayers.py check    # exit 1 when the folder does not match what build would write

One TIKI per armory uniform (every ui/loadout/skin/sNN.cfg page): the uniform's HATLESS body (the setup block of
models/player/<uniform>_nohat.tik, its glove skins included) with the card player's animations (hub_gi_menu.tik, written by
docs/proposals/attic_polish_2026-11-02/tools/gen_mproom69.py: `idle` and `cardA` = actor_m1l1_cardidle02, scale 0.52).
The MP room scenes name the card player with `scenemodellook` (engine cl_uiscene.cpp [joincards]), which draws
cards/<coop_loSkin>.tik in his place, seats the worn helmet on Bip01 Head and sets the glove skin; a uniform without a file
here falls back to the stock card player.

WHY NOT THE PLAYER TIKI ITSELF: it has no card animation, and adding an alias to models/player/base/anims_shared.txt would
renumber every player animation (an alias's number is its Q_stricmp rank): demos and a client/server pair on different paks
would play the wrong animations (TRAPS: "A demo stores anim NUMBERS", bug-10330). These files are menu-only.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MOD = os.path.join(ROOT, "hzm-mohaa-coop-mod")
SKIN = os.path.join(MOD, "ui", "loadout", "skin")
OUT = os.path.join(MOD, "models", "human", "hzm_menu", "cards")

TAIL = """	radius 20
}

init
{
	server
	{
		classname Actor
	}
}

animations
{
	$path models/human/animation
	idle scripted/table/actor_m1l1_cardidle02.skc
	cardA scripted/table/actor_m1l1_cardidle02.skc
}
"""


def uniforms():
    out = []
    for f in sorted(os.listdir(SKIN)):
        if not re.match(r"s\d+\.cfg$", f):
            continue
        t = open(os.path.join(SKIN, f), "rb").read().decode("latin-1")
        m = re.search(r'set coop_loChar "models/player/(\w+)_nohat\.tik"', t)
        if not m:
            raise SystemExit("%s: no coop_loChar body" % f)
        out.append(m.group(1))
    return sorted(set(out))


def setup_body(tik):
    t = open(tik, "rb").read().decode("latin-1").replace("\r\n", "\n")
    m = re.search(r"(?m)^setup\s*\n?\{\n", t)
    if not m:
        raise SystemExit("%s: no setup block" % tik)
    depth, i = 1, m.end()
    lines, cur = [], i
    while depth:
        j = t.find("\n", cur)
        if j < 0:
            raise SystemExit("%s: setup block runs to the end of the file" % tik)
        line = t[cur:j]
        code = line.split("//", 1)[0]
        if depth == 1 and re.match(r"\s*(init|animations|\$define|\$include)\b", code):
            break                         # american_omaha_ranger(_nohat): setup never closes its brace; the engine ends it here
        if re.match(r"\s*\$define\b", code):
            cur = j + 1
            continue
        depth += code.count("{") - code.count("}")
        if depth:
            lines.append(line)
        cur = j + 1
    keep = []
    for line in lines:
        code = line.split("//", 1)[0].strip()
        if re.match(r"(?i)(scale|radius)\b", code):
            continue                      # the menu scale and radius are set once below
        if code.startswith("$include"):
            raise SystemExit("%s: an $include inside setup is not supported" % tik)
        keep.append(line.rstrip())
    while keep and not keep[-1].strip():
        keep.pop()
    return keep


def render(u):
    body = setup_body(os.path.join(MOD, "models", "player", u + "_nohat.tik"))
    head = ("TIKI\n// GENERATED by docs/tools/gen_menu_cardplayers.py - do not hand-edit. The MP room's card player wearing the %s\n"
            "// uniform (hatless body: the worn helmet is attached by the menu scene, scenemodellook).\nsetup\n{\n\tscale 0.52\n" % u)
    return (head + "\n".join(body) + "\n" + TAIL).encode("latin-1")


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "check"
    want = {u + ".tik": render(u) for u in uniforms()}
    have = set(os.listdir(OUT)) if os.path.isdir(OUT) else set()
    # the mod repo checks out with core.autocrlf true (a stash / checkout turns these LF files CRLF): compare without line ends
    same = lambda n: open(os.path.join(OUT, n), "rb").read().replace(b"\r\n", b"\n") == want[n]  # noqa: E731
    bad = sorted(n for n in want if n not in have or not same(n)) + sorted(have - set(want))
    if mode == "build":
        os.makedirs(OUT, exist_ok=True)
        for n in have - set(want):
            os.remove(os.path.join(OUT, n))
        for n, b in want.items():
            p = os.path.join(OUT, n)
            if not os.path.exists(p) or not same(n):
                open(p, "wb").write(b)
        print("cardplayers: %d uniforms, %d written" % (len(want), len(bad)))
        return 0
    print("cardplayers: %d uniforms, %s" % (len(want), "ok" if not bad else "STALE %s" % bad[:8]))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
