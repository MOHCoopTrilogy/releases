#!/usr/bin/env python3
"""Generate ui/coopAdmin.urc - the coop/MP admin panel.

Eight player-slot rows (name from admin_p<N>, published by admin.scr::adm_refreshNames), each with the
admin action buttons. Every button uses `append name ,6<NN>` where NN = ACTION*10 + SLOT (see admin.scr:
1 kick, 2 ban, 3 slay, 4 god, 5 pull-to-me, 6 go-to-them); server actions and login/exit at the bottom.

Run:  python docs/tools/gen_admin_menu.py         (write)
      python docs/tools/gen_admin_menu.py check   (exit 1 if the .urc is stale)
"""
import sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "hzm-mohaa-coop-mod", "ui", "coopAdmin.urc")

# (label, action-code). Token appended is ,6 + (action*10 + slot).
ACTIONS = [("Kick", 1), ("Ban", 2), ("Slay", 3), ("God", 4), ("Pull", 5), ("Goto", 6)]
COLX = [206, 268, 330, 392, 454, 516]   # x of each action button
BTNW = 58
ROW_Y0 = 132
ROW_DY = 30
NROWS = 8


def button(title, name, rect, cmd, fg="0.99 0.80 0.20 1.00", bg="0.00 0.00 0.00 0.50", font="courier-16"):
    return ["resource", "Button", "{",
            'title "%s"' % title, 'name "%s"' % name, "rect %s" % rect,
            'borderstyle "NONE"', "font %s" % font,
            'clicksound sound/menu/TypeKey.wav',
            "fgcolor %s" % fg, "bgcolor %s" % bg,
            'stuffcommand "%s"' % cmd, "}"]


def build():
    L = []
    L.append("// GENERATED by docs/tools/gen_admin_menu.py. Do NOT hand-edit (regenerate instead).")
    L.append("// The coop/MP admin panel. Buttons use `append name ,6<NN>` (NN = action*10 + slot); admin.scr")
    L.append("// routes the token. Names come from admin_p1..8 (admin.scr::adm_refreshNames). Auth is enforced")
    L.append("// server-side in admin.scr (host auto-trusted; others must log in), never in this menu.")
    L.append('menu "coopadmin" 640 480 NONE 1')
    L.append("borderstyle NONE")
    L.append("bgcolor 0 0 0 0")
    L.append("align centerx centery")
    L.append("virtualres 0")
    L.append("fullscreen 0")
    L.append("direction from_top 0")
    # backdrop
    L += ["resource", "Widget", "{", 'name "background"', "rect 40 96 560 388",
          "bgcolor 0 0 0 0.6", "}"]
    # title
    L += ["resource", "Label", "{", 'name "coopAdminTitle"', 'title "HZM Admin Panel"',
          "rect 42 100 556 20", "fgcolor 1.00 1.00 1.00 1.00", "bgcolor 0.00 0.00 0.00 1.00",
          "font courier-16", "}"]
    # column header
    L += ["resource", "Label", "{", 'name "hdrPlayer"', 'title "Player"',
          "rect 46 118 150 12", "fgcolor 0.70 0.70 0.70 1.00", "bgcolor 0.00 0.00 0.00 0.00",
          "font courier-16", "}"]
    # rows
    for slot in range(1, NROWS + 1):
        y = ROW_Y0 + (slot - 1) * ROW_DY
        # name readout (from admin_p<slot>)
        L += ["resource", "Label", "{", 'name "admName%d"' % slot,
              "rect 46 %d 150 20" % y, "fgcolor 0.85 0.90 1.00 1.00", "bgcolor 0.00 0.00 0.00 0.40",
              "font courier-16", 'linkcvar "admin_p%d"' % slot, "}"]
        for (label, act), x in zip(ACTIONS, COLX):
            token = act * 10 + slot
            L += button(label, "adm_%s%d" % (label.lower(), slot),
                        "%d %d %d 20" % (x, y, BTNW),
                        "append name ,6%d" % token)
    # server actions row + login + exit
    yb = ROW_Y0 + NROWS * ROW_DY + 6
    L += button("Restart Map", "admRestart", "46 %d 200 20" % yb, "append name ,690",
                fg="1.00 1.00 1.00 1.00", bg="0.20 0.10 0.00 0.70")
    L += button("LOGIN", "admLogin", "260 %d 150 20" % yb, "append name ,3lgn",
                fg="0.99 0.80 0.20 1.00", bg="1.00 0.00 0.00 0.50")
    L += button("EXIT", "admExit", "424 %d 150 20" % yb, "popmenu 0;cg_3rd_Person 0",
                fg="0.99 0.80 0.20 1.00", bg="1.00 1.00 1.00 0.70")
    L.append("end.")
    return "\n".join(L) + "\n"


def main():
    text = build()
    if len(sys.argv) > 1 and sys.argv[1] == "check":
        cur = open(OUT, encoding="latin-1").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("STALE: coopAdmin.urc differs from generator output")
            sys.exit(1)
        print("OK: coopAdmin.urc matches generator")
        return
    open(OUT, "w", encoding="latin-1", newline="\n").write(text)
    print("wrote %s (%d player slots)" % (os.path.relpath(OUT, ROOT), NROWS))


if __name__ == "__main__":
    main()
