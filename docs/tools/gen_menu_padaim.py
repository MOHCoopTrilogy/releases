"""gen_menu_padaim.py - generates ui/coop_padaim.urc (Options > Controls > AIM / SENSITIVITY) in the mod tree.

    python docs/tools/gen_menu_padaim.py [mod_root]     (default: hzm-mohaa-coop-mod)

Sliders bind the archived joy_* cvars of the engine (cl_main.cpp / cl_input.cpp CL_JoystickMove, sdl_input.c). Every widget
is a normal Slider / Button / CheckBox, so the pad reaches it by itself: D-pad focus, A, left/right on a slider.
DEFAULTS mirrors the engine defaults in cl_main.cpp (keep both in step)."""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MOD = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "hzm-mohaa-coop-mod")

# (label, cvar, min, max, step, default, value-label cvar). The value labels read the in_padV_* mirrors that the engine keeps
# (sdl_input.c IN_PadMirrors): percent for sensitivities / deadzones, "1.5x" / "0.6 s" for the rest.
SLIDERS = [
    ("Horizontal look speed", "joy_lookX", 0.2, 3.0, 0.1, 1.0, "in_padV_lookX"),
    ("Vertical look speed", "joy_lookY", 0.2, 3.0, 0.1, 0.8, "in_padV_lookY"),
    ("Aim-down-sights sensitivity", "joy_adsScale", 0.2, 1.5, 0.05, 0.6, "in_padV_adsScale"),
    ("Inner deadzone (ignore small stick)", "joy_threshold", 0.0, 0.4, 0.01, 0.15, "in_padV_inner"),
    ("Outer deadzone (rim margin)", "joy_outerThreshold", 0.0, 0.3, 0.01, 0.05, "in_padV_outer"),
    ("Curve strength (Exponential)", "joy_response", 1.0, 3.0, 0.1, 1.5, "in_padV_response"),
    ("Acceleration ramp time", "joy_accelTime", 0.1, 2.0, 0.1, 0.6, "in_padV_accelTime"),
    ("Acceleration top speed", "joy_accelMax", 1.0, 3.0, 0.1, 1.5, "in_padV_accelMax"),
]
TOGGLES = [("Invert Y (push up = look down)", "joy_invertY", 0), ("Look acceleration", "joy_accel", 1)]
CURVES = [("LINEAR", 0), ("EXPONENTIAL", 1), ("DYNAMIC", 2)]

out = []
w = out.append
w('// HZM coop - CONTROLLER AIM / SENSITIVITY. GENERATED by docs/tools/gen_menu_padaim.py - do not hand-edit.')
w('// Opened from Options > Controls > AIM / SENSITIVITY (ui/coop_controls.urc). Everything is a plain Slider / Button / CheckBox:')
w('// the pad reaches it with the D-pad and changes sliders with left / right (engine UIWindowManager::PadNavigate).')
w('menu "coop_padaim" 640 480 NONE 1')
w('borderstyle NONE\nbgcolor 0 0 0 0\nalign centerx centery\nvirtualres 1\nfullscreen 0\n\ndirection from_top 0\n')


def label(name, title, x, y, wd, h=14, fg="0.84 0.82 0.76 1.00", extra=""):
    w('resource\nLabel\n{\n\tname "%s"\n\ttitle "%s"\n\trect %d %d %d %d\n\tfgcolor %s\n\tbgcolor 0.00 0.00 0.00 0.00\n\tborderstyle "NONE"\n\tfont "verdana-12"\n%s}'
      % (name, title, x, y, wd, h, fg, extra))


def button(name, title, x, y, wd, cmd, snd="apply"):
    w('resource\nButton\n{\n\tname "%s"\n\ttitle "%s"\n\trect %d %d %d 18\n\tfgcolor 0.84 0.82 0.76 1.00\n\tbgcolor 0.09 0.10 0.13 0.90\n\tborderstyle "3D_BORDER"\n\tfont "verdana-12"\n\tclicksound "sound/menu/%s.wav"\n\tstuffcommand "%s"\n}'
      % (name, title, x, y, wd, snd, cmd))


w('resource\nLabel\n{\n\tordernumber 50\n\tname "bg"\n\trect 0 0 640 480\n\tfgcolor 0.84 0.82 0.76 1.00\n\tbgcolor 0.05 0.06 0.08 1.00\n\tborderstyle "NONE"\n}')
label("title", "CONTROLLER AIM / SENSITIVITY", 200, 12, 300, fg="0.88 0.83 0.66 1.00")
label("hint", "D-pad to a slider, left / right to change it. Saved per player.", 40, 30, 560, fg="0.60 0.58 0.52 1.00")

y = 54
for i, (lab, cv, lo, hi, step, df, vcv) in enumerate(SLIDERS):
    label("lab%d" % i, lab, 40, y, 190)
    w('resource\nSlider\n{\n\ttitle "%s"\n\tname "sl_%s"\n\trect 232 %d 192 16\n\tfgcolor 1.00 1.00 1.00 1.00\n\tbgcolor 0.00 0.00 0.00 0.00\n\tborderstyle "NONE"\n\tshader "textures/menu/slider"\n\tlinkcvar "%s"\n\tslidertype float\n\tsetrange %s %s\n\tstepsize %s\n}'
      % (lab, cv, y - 1, cv, lo, hi, step))
    label("val%d" % i, "", 436, y, 70, fg="0.45 0.80 0.45 1.00", extra='\tlinkcvar "%s"\n' % vcv)
    y += 26

y += 4
label("capCurve", "RESPONSE CURVE", 40, y, 190)
label("curveNow", "", 232, y, 150, fg="0.45 0.80 0.45 1.00", extra='\tlinkcvar "in_padCurveLabel"\n')
y += 20
x = 40
for nm, v in CURVES:
    button("btnCurve%d" % v, nm, x, y, 130, "seta joy_curve %d" % v)
    x += 140
y += 30
for lab, cv, df in TOGGLES:
    label("lab_" + cv, lab, 80, y, 300)
    w('resource\nCheckBox\n{\n\tname "cb_%s"\n\trect 40 %d 192 34\n\tfgcolor 1.00 1.00 1.00 1.00\n\tbgcolor 0.50 0.50 0.50 0.00\n\tborderstyle "NONE"\n\tlinkcvar "%s"\n\tchecked_shader "textures/menu/checkbox_checked"\n\tunchecked_shader "textures/menu/checkbox_unchecked"\n}'
      % (cv, y - 8, cv))
    y += 26

PEEKS = [("OFF", 0), ("HOLD PEEK BUTTON", 1), ("WHILE AIMING", 2)]
label("capPeek", "STICK PEEK (lean / rise / duck)", 40, y, 250)
label("peekNow", "", 300, y, 240, fg="0.45 0.80 0.45 1.00", extra='\tlinkcvar "in_padPeekLabel"\n')
y += 20
x = 40
for nm, v in PEEKS:
    button("btnPeek%d" % v, nm, x, y, 170, "seta joy_stickPeek %d" % v)
    x += 180
y += 22
label("peekHint", "WHILE AIMING: hold ADS, left stick peeks. HOLD PEEK BUTTON: hold the button bound to Peek.", 40, y, 580)
y += 14
label("peekHelp1", "Handhelds: map a back button (e.g. ROG Ally M1) to a key or button in your device software,", 40, y, 580)
y += 14
label("peekHelp2", "bind it to Peek, and choose Hold peek button.", 40, y, 580)

defaults = " ; ".join("seta %s %s" % (s_[1], s_[5]) for s_ in SLIDERS)
defaults += " ; seta joy_curve 1 ; seta joy_invertY 0 ; seta joy_accel 1 ; seta joy_stickPeek 2"
button("btnDefaults", "RESET TO DEFAULTS", 40, 458, 200, defaults)
button("btnLayout", "CONTROLLER LAYOUT", 250, 458, 200, "ui_padbinds ; pushmenu coop_padlayout")   # [v1.10.46] the rebind page (gen_menu_padlayout.py)
button("btnBack", "BACK", 470, 458, 120, "popmenu 0", "back")
w("end.")

os.makedirs(os.path.join(MOD, "ui"), exist_ok=True)
p = os.path.join(MOD, "ui", "coop_padaim.urc")
open(p, "w", newline="\r\n").write("\n".join(out) + "\n")
print("wrote", p, "(%d sliders)" % len(SLIDERS))
