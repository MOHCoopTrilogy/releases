#!/usr/bin/env python3
"""gen_lktab.py - ui/loadout/lktab<t>.cfg, the client-side per-tab padlock + equipped-marker recompute (recreated 2026-10-15).

The original generator was lost; this one was reconstructed from the outputs and reproduces the six committed files BYTE-IDENTICALLY
before any change (run `check` on a tree that still has the old files). It is driven by docs/tools/loadout_weapons.tsv (the `tab` column).

    python gen_lktab.py check|build        HZM_MOD=<dir> points it at another copy of hzm-mohaa-coop-mod (as gen_loadout.py does)

Layout of a tab file (the quirks are the old generator's, kept so the diff against the old output is empty):
  header; `set coop_loLkV<id> 0` for ids 1..69; then for every member of the tab with id < 70 the pair `set coop_loLkV<id> <1|0>` /
  `vstr coop_loLkA<id>` (starters 01/24/48/64 default 0) - EXCEPT the last such member, whose vstr is deferred to the tail; then
  `set coop_loLkV<id> 0` for the late ids (70..75, 78, 80); `set coop_loP3d 0`; the tail vstrs (deferred member, then members >= 70);
  heavy tab only: `vstr coop_loDbT`.
LEGACY: id 73 is still listed in the heavy tab (a removed weapon, harmless: nothing defines coop_loLkA73); kept for byte-identity.
Equipped markers (added after the reproduction check): see MARKERS below.
"""
import io, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MOD = os.environ.get("HZM_MOD") or os.path.join(ROOT, "hzm-mohaa-coop-mod")
UI = os.path.join(MOD, "ui", "loadout")
TSV = os.path.join(os.path.dirname(os.path.abspath(__file__)), "loadout_weapons.tsv")
TABNAMES = ["RIFLE", "SNIPER", "SMG", "HEAVY", "PISTOL", "NADES"]
STARTERS = ("01", "24", "48", "64")
LATE = ["70", "71", "72", "73", "74", "75", "78", "80"]
LEGACY = {"3": ["73"]}
MARKERS = True   # equipped markers (2026-10-15): lktab<t> ends by replaying eqre<t>.cfg


def rows():
    out = []
    hdr = None
    for l in io.open(TSV, encoding="latin-1"):
        if l.startswith("#") or not l.strip():
            continue
        f = l.rstrip("\r\n").split("\t")
        if hdr is None:
            hdr = f
            continue
        out.append(dict(zip(hdr, f)))
    return out


def members(rs, t):
    m = [r["id"] for r in rs if r["tab"] == str(t)]
    m += LEGACY.get(str(t), [])
    return sorted(m)


def render(rs, t):
    mem = members(rs, t)
    early = [i for i in mem if int(i) < 70]
    late = [i for i in mem if int(i) >= 70]
    L = ["// GENERATED - client-side padlock recompute for tab %d (%s). Fail-LOCKED default." % (t, TABNAMES[t])]
    for i in range(1, 70):
        L.append("set coop_loLkV%02d 0" % i)
    for n, i in enumerate(early):
        L.append("set coop_loLkV%s %d" % (i, 0 if i in STARTERS else 1))
        if n < len(early) - 1:
            L.append("vstr coop_loLkA%s" % i)
    for i in LATE:
        L.append("set coop_loLkV%s 0" % i)
    L.append("set coop_loP3d 0")
    if early:
        L.append("vstr coop_loLkA%s" % early[-1])
    for i in late:
        L.append("vstr coop_loLkA%s" % i)
    if t == 3:
        L.append("vstr coop_loDbT")
    # [armory B 2026-10-18] active-tab flags (the tab buttons underline on them) and the card grid of this tab (gen_armory.py: unlocked
    # first); the equipped markers replay AFTER the fill because they are card (position) flags now.
    L += ["set coop_loTA%d %d" % (i, 1 if i == t else 0) for i in range(6)]
    L.append("exec ui/loadout/fill%d.cfg" % t)
    if MARKERS:
        L.append('set coop_loEqRe "exec ui/loadout/eqre%d.cfg"' % t)
        L.append("vstr coop_loEqRe")
    return L


def all_ids():
    return ["%02d" % i for i in range(1, 70)] + LATE


def render_eqre(t):
    """eqre<t>.cfg - recompute the EQUIPPED tile markers for tab t: zero every marker, then replay the slots' archived commands."""
    L = ["// GENERATED by gen_lktab.py - equipped-marker recompute for tab %d (%s): zero all, replay the four slot archives" % (t, TABNAMES[t])]
    for c in range(18):          # [armory B] card positions (gen_armory.NC), not per-gun tile flags
        L.append("set coop_loEqP%d 0" % c)
    for n in range(1, 5):
        L.append("vstr coop_loEqR%d_%d" % (t, n))
    return L


def eol_of(p):
    try:
        return "\r\n" if "\r\n" in io.open(p, encoding="latin-1", newline="").read() else "\n"
    except IOError:
        return "\n"


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "check"
    rs = rows()
    bad = []
    for t in range(6):
        p = os.path.join(UI, "lktab%d.cfg" % t)
        e = eol_of(p)
        text = e.join(render(rs, t)) + e
        pe = os.path.join(UI, "eqre%d.cfg" % t)
        if mode == "build":
            io.open(p, "w", encoding="latin-1", newline="").write(text)
            if MARKERS:
                io.open(pe, "w", encoding="latin-1", newline="").write(e.join(render_eqre(t)) + e)
        elif io.open(p, encoding="latin-1", newline="").read() != text:
            bad.append(t)
        elif MARKERS and (not os.path.isfile(pe) or io.open(pe, encoding="latin-1", newline="").read() != e.join(render_eqre(t)) + e):
            bad.append(t)
    if mode == "check":
        print("lktab: %s" % ("EXACT REPRODUCTION" if not bad else "DIFFERENT tabs %s" % bad))
        return 1 if bad else 0
    print("lktab: wrote 6 files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
