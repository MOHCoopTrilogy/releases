#!/usr/bin/env python3
"""patch_armory_locks.py - one-shot, idempotent patch of the hand-maintained armory outputs for the 2026-10-15 follow-up:
  (c) EQUIPPED markers on weapon tiles (urc labels + slot-clear cfgs; the per-tab recompute comes from gen_lktab.py, the weapon
      commit lines from gen_loadout.py)
  (a) per-gun "master it first" lock on the finish chips (lkmast / fdenym + the s<N>sel hook)
  (b) a lock + padlock on the VARIANT button (lkmv / fdenymv + finlk8)
The files patched here (urc, s<N>sel, clr*, lkfin) have no generator in the repo, so this script is the record.
    python patch_armory_locks.py <mod_tree>
"""
import io, os, re, sys

CR, LF = chr(13), chr(10)


def rd(p):
    return io.open(p, encoding="latin-1", newline="").read()


def wr(p, s):
    io.open(p, "w", encoding="latin-1", newline="").write(s)


def main(tree):
    ui = os.path.join(tree, "ui")
    d = os.path.join(ui, "loadout")
    urc = os.path.join(ui, "coop_loadout.urc")
    s = rd(urc)
    eol = CR + LF if CR + LF in s else LF
    # ---- (c) tile markers
    if '"tileeq' not in s:
        out, pos, n = [], 0, 0
        for m in re.finditer(r'name "tile(\d+)"', s):
            wid = m.group(1)
            blk_end = s.index(eol + "}", m.end()) + len(eol) + 1
            rect = re.search(r"rect (\d+) (\d+) (\d+) (\d+)", s[m.start():blk_end])
            x, y, w, h = [int(v) for v in rect.groups()]
            lbl = eol.join(["", "resource", "Label", "{", "ordernumber 9", 'name "tileeq%s"' % wid,
                            "rect %d %d 5 %d" % (x + 2, y + 2, h - 4), "fgcolor 1.00 1.00 1.00 1.00",
                            "bgcolor 0.40 0.85 0.35 0.95", 'borderstyle "NONE"', 'enabledcvar "coop_loEqV%s"' % wid, "}", ""])
            out.append(s[pos:blk_end])
            out.append(lbl)
            pos = blk_end
            n += 1
        out.append(s[pos:])
        s = "".join(out)
        print("tile markers:", n)
    # ---- (b) padlock on the VARIANT button
    if '"finlk8"' not in s:
        i = s.index('name "finbtn8"')
        blk_end = s.index(eol + "}", i) + len(eol) + 1
        lbl = eol.join(["", "resource", "Label", "{", "ordernumber 8", 'name "finlk8"', "rect 583 436 11 11",
                        "fgcolor 1.00 1.00 1.00 1.00", "bgcolor 0.00 0.00 0.00 0.00", 'borderstyle "NONE"',
                        'enabledcvar "coop_loLkFV8"', 'shader "textures/mohmenu/coop_lo_lock.tga"', "}", ""])
        s = s[:blk_end] + lbl + s[blk_end:]
        print("finlk8 added")
    wr(urc, s)
    # ---- lkfin: variant defaults, reset on every replay
    p = os.path.join(d, "lkfin.cfg")
    s = rd(p)
    if "coop_loLkFV8" not in s:
        e = CR + LF if CR + LF in s else LF
        s = s.replace('set coop_loFcmt0 "vstr coop_loFgo0"' + e,
                      'set coop_loFcmt0 "vstr coop_loFgo0"' + e + "set coop_loLkFV8 0" + e + 'set coop_loFcmt8 "vstr coop_loFgo8"' + e, 1)
        wr(p, s)
    # ---- new cfgs
    files = {
        "lkmast.cfg": ["// GENERATED by patch_armory_locks.py - the gun in the active slot is not mastered: every finish chip locks"]
        + ["set coop_loLkFV%d 1" % f for f in range(1, 8)]
        + ['set coop_loFcmt%d "exec ui/loadout/fdenym.cfg"' % f for f in range(1, 8)],
        "fdenym.cfg": ['// GENERATED by patch_armory_locks.py - locked chip click (gun not mastered): say so, beep, change nothing',
                       'set coop_loReq "MASTER THIS GUN FIRST"', "vstr coop_loMastTCur", "vstr coop_loDeny"],
        "lkmv.cfg": ["// GENERATED by patch_armory_locks.py - the VARIANT button is locked for the gun in the active slot",
                     "set coop_loLkFV8 1", 'set coop_loFcmt8 "exec ui/loadout/fdenymv.cfg"'],
        "fdenymv.cfg": ["// GENERATED by patch_armory_locks.py - locked VARIANT click: the variant's requirement, beep, change nothing",
                        "vstr coop_loMvReqCur", "vstr coop_loDeny"],
    }
    for n in range(1, 5):
        files["eqclr%d.cfg" % n] = (["// GENERATED by patch_armory_locks.py - slot %d no longer holds a gun: clear its EQUIPPED marker archives" % n]
                                    + ['seta coop_loEqR%d_%d ""' % (t, n) for t in range(6)] + ["vstr coop_loEqRe"])
    for name, lines in files.items():
        wr(os.path.join(d, name), LF.join(lines) + LF)
    # ---- slot clears call eqclr<N>
    for name, n in (("clrP1", 1), ("clrP2", 2), ("clr3", 3), ("clr4", 4), ("clrk1", 1), ("clrk2", 2), ("clrk3", 3), ("clrk4", 4)):
        p = os.path.join(d, name + ".cfg")
        if not os.path.isfile(p):
            print("missing", name)
            continue
        s = rd(p)
        if "eqclr" not in s:
            e = CR + LF if CR + LF in s else LF
            if not s.endswith(e):
                s += e
            s += "exec ui/loadout/eqclr%d.cfg" % n + e
            wr(p, s)
    # ---- s<N>sel: mastery + variant lock hook after the lkfin replay
    for n in range(1, 5):
        p = os.path.join(d, "s%dsel.cfg" % n)
        s = rd(p)
        if "coop_loMast" in s:
            continue
        e = CR + LF if CR + LF in s else LF
        a = "exec ui/loadout/lkfin.cfg" + e
        assert a in s, p
        add = e.join(['set coop_loMastTCur "vstr coop_loMastT%d"' % n,
                      'set coop_loMastApply "exec ui/loadout/lkfin.cfg ; vstr coop_loMast%d ; vstr coop_loMvLk%d"' % (n, n),
                      "vstr coop_loMast%d" % n, "vstr coop_loMvLk%d" % n, ""])
        s = s.replace(a, a + add, 1)
        wr(p, s)
    print("patch_armory_locks done")


if __name__ == "__main__":
    main(sys.argv[1])
