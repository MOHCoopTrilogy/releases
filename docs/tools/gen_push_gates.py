#!/usr/bin/env python3
"""Generate coop_mod/mp_push_blockers.scr from docs/tools/push_blockers.json (the blocker-probe sweep,
bug-2827/2828): for each push map, notsolid every harvested scripted path-blocker so it is carved out of the
bot navmesh, letting BOTH teams traverse.

PROPER fix, not just a collision hack (user 2026-09-22) - class-aware, matching push_openGates' own intent
("open it with $name open / trigger it / remove a func_static"):
  * DOORS/GATES (class contains 'Door')  -> `open` (animates open, looks right) + `notsolid` (nav-carve safety
    in case it is locked / does not fully clear the corridor).
  * DESTRUCTIBLES (exploder/chunk/smashed/barrel/crate/fencepost) -> `remove` - the SP explosion leaves them
    GONE, so removing them is the correct cleared state (and it carves the navmesh too).
  * everything else -> `notsolid` (safe default).

Lessons baked in (from the e3l2 hand-fix):
  * a broadcast `$name notsolid` did NOT clear a large same-name ARRAY - ITERATE $name[i] instead.
  * some blockers (destructible debris/gibs) spawn LATE - RETRY the whole pass for ~15s.
  * a `.size`/event throw on a single-entity target is survivable: per TRAPS T17 it skips just that for-loop and
    control falls through, so one odd blocker never kills the pass.

Runs ADDITIVELY alongside the hand-authored push_gates_<map> handlers (notsolid is idempotent). Hooked from
mp_push.scr::push_openGates.

  python docs/tools/gen_push_gates.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
JSON = os.path.join(ROOT, 'docs', 'tools', 'push_blockers.json')
OUT = os.path.join(ROOT, 'hzm-mohaa-coop-mod', 'coop_mod', 'mp_push_blockers.scr')
RETRY = 15  # seconds of re-notsolid to catch late-spawning debris


def action_for(cls, tn):
    c, t = cls.lower(), tn.lower()
    if 'door' in c:
        return 'door'      # open + notsolid
    if 'fencepost' in c or 'crate' in c:
        return 'remove'
    if any(k in t for k in ('exploder', 'chunk', 'smashed', 'barrel', 'debris', 'rubble', 'gib')):
        return 'remove'
    return 'notsolid'


def emit_blocker(L, b):
    """Emit the iterated, class-appropriate action for one blocker."""
    tn = b['tn']
    act = action_for(b['class'], tn)
    itr = 'for( local.i = 1; local.i <= $%s.size; local.i++ ){ if( $%s[local.i] != NULL ){ $%s[local.i] %%s } }' % (tn, tn, tn)
    if act == 'door':
        L.append('\t\t\t' + itr % 'open $world')  # animate open; Door::Open wants an 'other' entity or it Script-Errors (bug-2859)
        L.append('\t\t\t' + itr % 'notsolid')   # + nav-carve safety
    elif act == 'remove':
        L.append('\t\t\t' + itr % 'remove')     # gone / cleared (what the SP explosion leaves)
    else:
        L.append('\t\t\t' + itr % 'notsolid')


def build():
    data = json.load(open(JSON))
    L = []
    L.append('// GENERATED by docs/tools/gen_push_gates.py from docs/tools/push_blockers.json - DO NOT EDIT.')
    L.append('// Auto-harvested scripted PATH BLOCKERS per push map (blocker-probe sweep, bug-2827/2828).')
    L.append('// notsolid carves each out of the bot navmesh so both teams traverse. Additive to the hand-')
    L.append('// authored push_gates_<map> handlers. Iterates arrays + retries ~%ds for late-spawning debris.' % RETRY)
    L.append('// MP-isolated: names only $targetnames + coop_mpRun; no coop cvar / coop_lo / loadout token.')
    L.append('')
    L.append('applyPushBlockers:{')
    L.append('\tif( level.coop_mpRun != 1 ){ end }')
    L.append('\tthread applyPushBlockers_loop')
    L.append('}end')
    L.append('')
    L.append('applyPushBlockers_loop:{')
    L.append('\tlocal.map = getcvar( "mapname" )')
    L.append('\tlocal.k = 0')
    L.append('\twhile( local.k < %d ){' % RETRY)
    any_map = False
    for m in sorted(data):
        blockers = data[m]
        if not blockers:
            continue
        any_map = True
        L.append('\t\tif( local.map == "%s" ){' % m)
        for b in blockers:
            if b.get('keep_solid'):
                # [bug-2835] deliberately left CLOSED (user) - the harvester MERGES, so this flag survives re-harvests
                L.append('			//%s kept SOLID: %s' % (b['tn'], b['keep_solid'][:90]))
                continue
            emit_blocker(L, b)
        L.append('\t\t}')
    if not any_map:
        L.append('\t\t//(no named blockers harvested yet - run the blocker-probe sweep + bot_soak_blockers.py)')
    L.append('\t\tlocal.k++')
    L.append('\t\twait 1')
    L.append('\t}')
    L.append('\tprintln( "^~^~^ MPPUSHBLK notsolid pass complete for " + local.map )')
    L.append('}end')
    L.append('')
    with open(OUT, 'w', newline='\n') as fh:
        fh.write('\n'.join(L))
    nmaps = sum(1 for v in data.values() if v)
    print('wrote %s (%d maps with blockers)' % (os.path.relpath(OUT, ROOT), nmaps))


if __name__ == '__main__':
    build()
