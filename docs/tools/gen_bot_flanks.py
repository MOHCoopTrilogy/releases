#!/usr/bin/env python3
"""Generate coop_mod/mp_botflanks.scr from docs/tools/axis_chokes.json (the soak-derived per-map axis
congestion chokes + reachable flank waypoints, bug-2826).

For each ENABLED axis-lag map it emits secondary AXIS attract-nodes at the map's flank waypoints (slots 22-25,
priority 7 = same as the axis goal). MoveToBestAttractivePoint draws each axis bot to the NEAREST eligible
node, so with the far goal PLUS the lateral flanks the axis team SPLITS around the bottleneck instead of all
funnelling through it - which is what makes axis so much slower than allies on these maps. The nodes are static
(the choke is a fixed map location) and applied ONCE per map load, so no per-frame entity churn.

Only maps in ENABLED are populated - the soak's 'fine' maps (m4l1, m5l2a, t2l4 ...) get nothing, and the
'nav-broken for both teams' maps (m4l2, m5l1a, m5l3, e3l2) are a SEPARATE job (flank nodes won't fix them).

  python docs/tools/gen_bot_flanks.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
JSON = os.path.join(ROOT, 'docs', 'tools', 'axis_chokes.json')
OUT = os.path.join(ROOT, 'hzm-mohaa-coop-mod', 'coop_mod', 'mp_botflanks.scr')

# Maps validated for flank routing. Start with m1l2b (the proof); expand after the re-soak confirms the
# mechanism closes the axis gap. NOT the nav-broken maps and NOT the already-fine maps.
ENABLED = []  # attract-node routing PARKS bots (bug-2826 re-soak) - disabled; see buglog

MAX_FLANKS = 4  # slots 22..25


def flanks_for(data, m):
    d = data.get(m) or {}
    out = []
    seen = set()
    for ch in d.get('chokes', []):
        for f in ch.get('flanks', []):
            key = (f[0] // 128, f[1] // 128)   # dedupe near-duplicate flanks across the map's chokes
            if key in seen:
                continue
            seen.add(key)
            out.append(f)
            if len(out) >= MAX_FLANKS:
                return out
    return out


def build():
    data = json.load(open(JSON))
    L = []
    L.append('// GENERATED by docs/tools/gen_bot_flanks.py from docs/tools/axis_chokes.json - DO NOT EDIT.')
    L.append('// Per-map AXIS flank waypoints (soak bug-2826): secondary axis attract-nodes that split axis bots')
    L.append('// off the map congestion bottleneck so axis stops lagging allies. Applied once per map load.')
    L.append('// Only validated axis-lag maps are populated; every other map is a no-op.')
    L.append('')
    L.append('applyAxisFlanks:{')
    L.append('\tif( level.coop_mpFlanksApplied == 1 ){ end }   //static nodes: apply once, never churn')
    L.append('\tlevel.coop_mpFlanksApplied = 1')
    L.append('\tlocal.map = getcvar( "mapname" )')
    for m in ENABLED:
        fl = flanks_for(data, m)
        if not fl:
            continue
        L.append('\tif( local.map == "%s" ){' % m)
        for i, f in enumerate(fl):
            slot = 22 + i
            # negative VECTOR COMPONENTS are legal in a vector literal (TRAPS T1); assign to a local first,
            # matching the botobj_set call convention (it takes a vector variable, floor-snaps it - bug-2781).
            L.append('\t\tlocal.f%d = ( %d %d %d )' % (i, f[0], f[1], f[2]))
            L.append('\t\twaitthread coop_mod/mp_botobj.scr::botobj_set %d local.f%d 7 "axis"' % (slot, i))
        L.append('\t\tend')
        L.append('\t}')
    L.append('}end')
    L.append('')
    txt = '\n'.join(L)
    with open(OUT, 'w', newline='\n') as fh:
        fh.write(txt)
    print('wrote %s (%d enabled map(s): %s)' % (os.path.relpath(OUT, ROOT), len(ENABLED), ', '.join(ENABLED)))


if __name__ == '__main__':
    build()
