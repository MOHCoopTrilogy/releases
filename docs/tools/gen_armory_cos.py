#!/usr/bin/env python3
"""gen_armory_cos.py - the data side of the sorted uniform / helmet / glove steppers (see patch_armory_cos.py for the page side).

  * defaults  : ui/loadout/armory_defaults.cfg lines  seta coop_loSkNx<NN> exec ui/loadout/skin/s<MM>.cfg ... = the natural ring, so a profile that has
                never connected steps exactly as before;
  * ring data : coop_mod/cosring_gen.scr  = the natural ring per kind (page numbers) + the flag / cvar / file names the server needs;
  * server    : coop_mod/cosorder.scr     = cos_exportOrder: orders a kind's pages unlocked first (natural order inside each group, locked last),
                and pushes, diff-only, the NEXT / PREVIOUS page pointer of every page whose neighbours changed.
Lock state is read from the flags the existing lock exports keep (coop_loSkLkL<i> / coop_loHmLkL<i> = 1 locked, 0 open, NIL free; the glove
export gained the same flag).  Everything is derived from docs/tools/assets/armory_cos_ring.json (patch_armory_cos.py extract).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RING = os.path.join(HERE, "assets", "armory_cos_ring.json")
FAM = {
    "skin": ("skin", "s", "coop_loSkNx", "coop_loSkPv", "coop_loSkLkL"),
    "helm": ("helm", "h", "coop_loHmNx", "coop_loHmPv", "coop_loHmLkL"),
    "glove": ("glove", "g", "coop_loGlNx", "coop_loGlPv", "coop_loGlLkL"),
}


def ring():
    return json.load(open(RING))


def pad(n):
    return "%02d" % n if n < 10 else str(n)


def defaults():
    """armory_defaults.cfg lines: the natural ring"""
    R = ring()
    out = ["// natural order of the uniform / helmet / glove pages (patch_armory_cos.py); the server re-points them unlocked first"]
    for kind, (d, ltr, nx, pv, _fl) in FAM.items():
        order = R[kind]
        n = len(order)
        for j, pg in enumerate(order):
            nxt, prv = order[(j + 1) % n], order[(j - 1) % n]
            out.append('seta %s%s "exec ui/loadout/%s/%s%s.cfg"' % (nx, pad(pg), d, ltr, pad(nxt)))
            out.append('seta %s%s "exec ui/loadout/%s/%s%s.cfg"' % (pv, pad(pg), d, ltr, pad(prv)))
    return out


def ring_scr():
    R = ring()
    L = ["//=========================================================================",
         "// GENERATED by docs/tools/gen_armory_cos.py - DO NOT EDIT BY HAND",
         "// The natural page ring of the armory's uniform / helmet / glove steppers (data for cosorder.scr::cos_exportOrder).",
         "//=========================================================================",
         "",
         "main:{",
         "\tif( level.coop_cosRingBuilt == 1 ){ end }",
         "\tlevel.coop_cosRingBuilt = 1"]
    for kind, (d, ltr, nx, pv, fl) in FAM.items():
        order = R[kind]
        L.append('\tlevel.coop_cosRingN["%s"] = %d' % (kind, len(order)))
        L.append('\tlevel.coop_cosDir["%s"] = "%s"' % (kind, d))
        L.append('\tlevel.coop_cosLtr["%s"] = "%s"' % (kind, ltr))
        L.append('\tlevel.coop_cosNx["%s"] = "%s"' % (kind, nx))
        L.append('\tlevel.coop_cosPv["%s"] = "%s"' % (kind, pv))
        L.append('\tlevel.coop_cosFl["%s"] = "%s"' % (kind, fl))
        for j, pg in enumerate(order):
            L.append('\tlevel.coop_cosRing["%s"][%d] = %d' % (kind, j, pg))
    L += ["}end", ""]
    return "\n".join(L)


COSORDER = r'''//=========================================================================
// GENERATED by docs/tools/gen_armory_cos.py - DO NOT EDIT BY HAND
// [armory B 2026-10-18] UNLOCKED FIRST for the uniform / helmet / glove steppers. The pages (ui/loadout/skin|helm|glove) step through pointer
// cvars (patch_armory_cos.py): `set coop_loCharN "vstr coop_loSkNx<NN>"`.  This orders one kind's pages for ONE player - open (or free) pages in
// their natural order, then the locked ones in theirs - and pushes the pointers that changed:
//   seta coop_loSkNx<NN> exec ui/loadout/skin/s<MM>.cfg      (HmNx / GlNx for helmets / gloves; ...Pv<NN> = the previous page)
// Same wire rules as the lock exports: archived seta, ONE statement per stufftext, unquoted (bug-758), diff-only (flags coop_loCosOrd<kind><NN>),
// paced to stay under the reliable-command ring.  Lock state = the flags those exports keep (1 locked, 0 open, NIL free).
// Called at the end of armory_skin_exportLocks / armory_helmet_exportLocks / armory_glove_exportLocks (helmet.scr, gloves.scr).
//=========================================================================
cos_exportOrder local.player local.kind:{
	if( local.player == NULL ){ end }
	waitthread coop_mod/cosring_gen.scr::main
	local.n = level.coop_cosRingN[local.kind]
	if( local.n == NIL ){ end }
	if( local.n < 2 ){ end }
	local.fl = level.coop_cosFl[local.kind]
	local.m = 0
	local.j = 0
	while( local.j < local.n ){
		local.pg = level.coop_cosRing[local.kind][local.j]
		if( local.player.flags[local.fl + local.pg] != 1 ){
			local.ord[local.m] = local.pg
			local.m++
		}
		local.j++
	}
	local.j = 0
	while( local.j < local.n ){
		local.pg = level.coop_cosRing[local.kind][local.j]
		if( local.player.flags[local.fl + local.pg] == 1 ){
			local.ord[local.m] = local.pg
			local.m++
		}
		local.j++
	}
	local.w = 0
	local.j = 0
	while( local.j < local.n ){
		local.cur = local.ord[local.j]
		local.jn = local.j + 1
		if( local.jn >= local.n ){ local.jn = 0 }
		local.jp = local.j - 1
		if( local.jp < 0 ){ local.jp = local.n - 1 }
		local.nxt = local.ord[local.jn]
		local.prv = local.ord[local.jp]
		local.sig = "" + local.nxt + "," + local.prv
		if( local.player.flags["coop_loCosOrd" + local.kind + local.cur] != local.sig ){
			local.player.flags["coop_loCosOrd" + local.kind + local.cur] = local.sig
			local.cs = "" + local.cur
			if( local.cur < 10 ){ local.cs = "0" + local.cur }
			local.ns = "" + local.nxt
			if( local.nxt < 10 ){ local.ns = "0" + local.nxt }
			local.ps = "" + local.prv
			if( local.prv < 10 ){ local.ps = "0" + local.prv }
			local.player stufftext ( "seta " + level.coop_cosNx[local.kind] + local.cs + " exec ui/loadout/" + level.coop_cosDir[local.kind] + "/" + level.coop_cosLtr[local.kind] + local.ns + ".cfg" )
			local.player stufftext ( "seta " + level.coop_cosPv[local.kind] + local.cs + " exec ui/loadout/" + level.coop_cosDir[local.kind] + "/" + level.coop_cosLtr[local.kind] + local.ps + ".cfg" )
			local.w++
			local.w++
			if( local.w >= 8 ){
				local.w = 0
				waitframe
				if( local.player == NULL ){ end }
			}
		}
		local.j++
	}
}end
'''
