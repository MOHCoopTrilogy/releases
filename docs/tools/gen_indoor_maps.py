#!/usr/bin/env python3
"""Generate coop_mod/indoor_maps.scr - the per-map INDOOR flag used by officer.scr::coop_officer_death_drops.

A map is INDOOR (no airstrike / paradrop reward is usable, so the officer drops the ammo+health cache instead) when:
  (a) it is flight class D in aircraft_envelope: fewer than 40 outdoor pathnodes, i.e. no usable sky anywhere.
  Only (a) counts: an officer standing under a roof on an otherwise open map is NOT indoor (the call-ins retarget to
  the nearest open sky, officer.scr::coop_binoc_opensky). Omaha (m3l1a/b) is never touched.
Source: retail BSPs via aircraft_bsp.py (read only). Never hand-edit the output.

Usage: python gen_indoor_maps.py build | check | list
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import aircraft_bsp as E  # noqa: E402

MOD = os.environ.get("GEN_MOD") or os.path.join(HERE, "..", "..", "hzm-mohaa-coop-mod", "coop_mod")
POS = os.path.join(MOD, "officer_positions.scr")
OUT = os.path.join(MOD, "indoor_maps.scr")


def anchors():
    t = open(POS, encoding="utf-8", errors="replace").read()
    res = {}
    parts = re.split(r'local\.m == "(\w+)"\s*\)\s*\{', t)
    for i in range(1, len(parts), 2):
        m = re.search(r'level\.coop_officer_anchor\s*=\s*\(\s*(-?\d+)\s+(-?\d+)\s+(-?\d+)\s*\)', parts[i + 1].split("} else if")[0])
        if m:
            res[parts[i].lower()] = tuple(float(v) for v in m.groups())
    return res


def open_sky_above(s, x, y, z):
    zz = z + 48
    if not s.valid(x, y, zz):
        return None
    top = s.world[5] + 64
    while zz < top and s.valid(x, y, zz):
        zz += 64
    lo, hi = zz - 64, zz
    for _ in range(5):
        mid = (lo + hi) / 2
        if s.valid(x, y, mid):
            lo = mid
        else:
            hi = mid
    return bool(s.is_sky_leaf(s.leaf(x, y, hi + 1)))


def compute():
    fogs = E.fog_rows()
    anc = anchors()
    rows = []
    for m in E.MAPS:
        r = E.analyse(m, fogs)
        why = None
        if "g50" not in r or r.get("outdoor", 0) < 40:
            why = "no usable sky (%s outdoor nodes)" % r.get("outdoor", 0)
        if why:
            rows.append((m, why))
    return rows


def render(rows):
    L = ["// GENERATED by docs/tools/gen_indoor_maps.py from the retail BSPs + officer_positions.scr.",
         "// DO NOT EDIT - edit the generator and run `python docs/tools/gen_indoor_maps.py build`.",
         "// INDOOR maps: no usable sky for an airstrike / paradrop, so the officer's death reward is the ammo+health cache",
         "// (officer.scr::indoorReward). Flagged: " + " ".join(m for m, _ in rows)]
    for m, w in rows:
        L.append("//   %s: %s" % (m, w))
    L.append("")
    L.append("// returns 1 if local.m is an indoor map")
    L.append("isIndoor local.m:{")
    for m, _ in rows:
        L.append('\tif( local.m == "%s" ){ end 1 }' % m)
    L.append("}end 0")
    return ("\r\n".join(L) + "\r\n").encode("ascii")


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "build"
    rows = compute()
    data = render(rows)
    if mode == "list":
        for m, w in rows:
            print(m, w)
        return 0
    if mode == "check":
        cur = open(OUT, "rb").read() if os.path.exists(OUT) else b""
        if cur != data:
            print("indoor_maps.scr is STALE - run build")
            return 1
        print("indoor_maps.scr up to date (%d maps)" % len(rows))
        return 0
    open(OUT, "wb").write(data)
    print("wrote", os.path.normpath(OUT), len(rows), "maps")
    return 0


if __name__ == "__main__":
    sys.exit(main())
