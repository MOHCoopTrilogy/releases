"""Generate hzm-mohaa-coop-mod/ui/coop_version.cfg - the mod version the main menu shows beside WHAT'S NEW.

[user 2026-09-25] "we need to put somewhere in the main menu a way to see the current version and what's new
so you can visit that card yourself whenever you want". The version is DERIVED, never typed: its one source is
the What's New card title (ui/coop_whatsnew.urc, `title "UPDATE vX.Y.Z ..."`), which publish_release.ps1
already refuses to publish unless it equals the release version. autoexec.cfg execs the cfg at launch (a menu showcommand is not a URC keyword), and
its version Label links the cvar.

Usage:  python docs/tools/gen_version_cfg.py build   (build.ps1 runs this before packing)
        python docs/tools/gen_version_cfg.py check   (exit 1 on drift)
Writes only when the content changes, so the deterministic packer sees a stable mtime.
"""
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MOD = os.path.join(ROOT, "hzm-mohaa-coop-mod")
CARD = os.path.join(MOD, "ui", "coop_whatsnew.urc")
OUT = os.path.join(MOD, "ui", "coop_version.cfg")


def render():
    text = io.open(CARD, "r", encoding="latin-1").read()
    m = re.search(r'title\s+"UPDATE v(\d+\.\d+\.\d+)', text)
    if not m:
        raise SystemExit("no 'UPDATE vX.Y.Z' title in %s" % os.path.relpath(CARD, ROOT))
    return ("// GENERATED by docs/tools/gen_version_cfg.py from ui/coop_whatsnew.urc - do not edit.\n"
            "// Exec'd by autoexec.cfg at launch; the main menu's version label links coop_modVersion.\n"
            'set coop_modVersion "v%s"\n' % m.group(1))


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "check"
    want = render()
    have = io.open(OUT, "r", encoding="latin-1", newline="").read() if os.path.exists(OUT) else None
    if mode == "build":
        if have != want:
            io.open(OUT, "wb").write(want.encode("ascii"))
            print("wrote %s" % os.path.relpath(OUT, ROOT))
        else:
            print("unchanged %s" % os.path.relpath(OUT, ROOT))
        return 0
    if have != want:
        print("DRIFT - run: python docs/tools/gen_version_cfg.py build")
        return 1
    print("EXACT REPRODUCTION (%s)" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
