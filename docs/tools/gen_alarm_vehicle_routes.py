#!/usr/bin/env python
"""Generate coop_mod/alarmveh_routes.scr - the vehicle routes coop_mod/alarmveh.scr drives on an alarm.

    python docs/tools/gen_alarm_vehicle_routes.py check     # regenerate in memory + byte-compare (exit 1 = drift)
    python docs/tools/gen_alarm_vehicle_routes.py build     # write coop_mod/alarmveh_routes.scr

DATA: docs/tools/alarm_vehicle_routes.json  { "<map>": [ {name, kind: truck|halftrack, model, nodes:[[x,y,z],..], crate:[x,y,z],
      crateyaw, src} ] }.  A map with no entry (or no JSON row) is vehicle-OFF: alarmveh.scr does nothing there. Vanilla chains were
      read out of the stock BSPs by extract_alarm_vehicle_routes.py; hand-authored routes are added by hand (ROUTES_HOWTO.md).
      A halftrack route REQUIRES a crate (no crate, no halftrack: the squad must always have a rocket).

ALARM_MOD=<mod checkout> overrides the checkout written to (default: hzm-mohaa-coop-mod).
OUTPUT RULES: ASCII, LF, no BOM, no bare negative scalar (vectors may carry negatives).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MOD = os.environ.get("ALARM_MOD") or os.path.join(ROOT, "hzm-mohaa-coop-mod")
SRC = os.path.join(HERE, "alarm_vehicle_routes.json")
OUT = os.path.join(MOD, "coop_mod", "alarmveh_routes.scr")


def v(p):
    return "( %s %s %s )" % tuple(("%g" % float(x)) for x in p)


def render():
    data = json.load(open(SRC))
    o = []
    o.append("//=========================================================================")
    o.append("// alarmveh_routes.scr - GENERATED by docs/tools/gen_alarm_vehicle_routes.py from docs/tools/alarm_vehicle_routes.json. Do not edit.")
    o.append("// av_data <map> fills level.av_rn (route count) and, per route r (1..av_rn): av_kind[r] av_name[r] av_model[r] av_n[r] av_crate[r]")
    o.append("// av_cyaw[r] and the nodes av_p[r*100+k], k = 1..av_n[r] (k = 1 is the ENTRY, the last node is the STOP). A map with no label is vehicle-off.")
    o.append("//=========================================================================")
    o.append("")
    o.append("av_data local.m:{")
    o.append("\tlevel.av_rn = 0")
    for m in sorted(data):
        o.append("\tif( local.m == \"%s\" ){ waitthread av_data_%s }" % (m, m))
    o.append("}end")
    for m in sorted(data):
        o.append("")
        o.append("av_data_%s:{" % m)
        rs = data[m]
        o.append("\tlevel.av_rn = %d" % len(rs))
        for i, r in enumerate(rs, 1):
            if r["kind"] == "halftrack" and not r.get("crate"):
                raise SystemExit("%s/%s: a halftrack route needs a crate" % (m, r["name"]))
            if len(r["nodes"]) < 3 or len(r["nodes"]) > 99:
                raise SystemExit("%s/%s: 3..99 nodes" % (m, r["name"]))
            o.append("\tlevel.av_kind[%d] = \"%s\"" % (i, r["kind"]))
            o.append("\tlevel.av_name[%d] = \"%s\"" % (i, r["name"]))
            o.append("\tlevel.av_model[%d] = \"%s\"" % (i, r["model"]))
            o.append("\tlevel.av_n[%d] = %d" % (i, len(r["nodes"])))
            o.append("\tlevel.av_crate[%d] = %s" % (i, v(r["crate"])))
            o.append("\tlevel.av_cyaw[%d] = %g" % (i, float(r.get("crateyaw", 0)) % 360))
            for k, p in enumerate(r["nodes"], 1):
                o.append("\tlevel.av_p[%d] = %s" % (i * 100 + k, v(p)))
        o.append("}end")
    return "\n".join(o) + "\n"


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    txt = render()
    if cmd == "build":
        open(OUT, "w", newline="\n", encoding="ascii").write(txt)
        print("wrote", OUT, len(txt), "bytes")
    elif cmd == "check":
        cur = open(OUT, encoding="ascii", newline="").read() if os.path.exists(OUT) else None
        if cur != txt:
            print("STALE:", OUT)
            sys.exit(1)
        print("ok", OUT)
    else:
        sys.exit("usage: build|check")


if __name__ == "__main__":
    main()
