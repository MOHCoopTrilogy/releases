"""gen_remap.py - the sprite remap of the smoke & fire Phase 1 layer: scripts/coop_sprremap.txt (read by the cgame when
cg_hzmSprRemap is 1) and scripts/coop_fx_p1_remap.shader (size-matched copies of our billow / soot flipbooks).

Each retail / fx_1025 smoke sprite is replaced by a copy of our own art drawn at the SAME world size (sprite size =
image width x spritescale, tr_sprite.c) and played at a pace that fits how long those particles live, so a tik's
scale / scalerate / life / alpha keep meaning what they meant. Excluded maps keep the retail look: Omaha (user) and the
disc missions (their own converter path). Our own art only."""
import glob, os

HERE = os.path.dirname(os.path.abspath(__file__))
LAYER = os.path.normpath(os.path.join(HERE, "..", "..", "..", "tools", "assets", "fx", "pak_p1"))
TEX = os.path.join(LAYER, "textures", "coop_fx", "fx")
# new shader: (frames set, world size u, play fps, replaces)
R = [
    ("cfx2_billow_m", "billow", 32, 20, ["vsssource.spr", "vsssource2.spr"]),      # muzzle smoke + every VSS plume
    ("cfx2_soot_g", "soot", 256, 10, ["cfx_smoke_fb.spr"]),                      # fx_1025 grenade / shell smoke
    ("cfx2_soot_g2", "soot", 256, 6, ["cfx_smoke_tk.spr"]),                      # fx_1025 big-blast smoke
    ("cfx2_soot_c", "soot", 128, 6, ["tehaosmoke_dark.spr"]),                    # dark stacks / burning-building smoke
    ("cfx2_billow_c", "billow", 128, 6, ["tehaosmoke_light.spr"]),               # light stacks / chimneys / steam-ish
]
EXCLUDE = ["m3l1a", "m3l1b", "coop_fl_", "coop_ea_"]

sh = ["// [smoke&fire Phase 1] generated by docs/proposals/smokefire_2026-11-24/tools/gen_remap.py - do not edit.",
      "// Size-matched copies of our own billow / soot flipbooks for the cgame sprite remap (cg_hzmSprRemap).", ""]
tab = ["// [smoke&fire Phase 1] cgame sprite remap (cg_hzmSprRemap 1). Generated by gen_remap.py - do not edit.",
       "// 'exclude <map prefix>' keeps those maps on the retail sprites; '<from.spr> <to.spr>' remaps everywhere else."]
tab += ["exclude %s" % e for e in EXCLUDE]
for name, fset, world, fps, froms in R:
    # skip the first 10 frames: the simulation starts as a small, crisp-edged sphere, which read as a hard dark
    # ball inside the grenade fireball (remap capture 2026-11-24); a remapped puff starts already billowed
    frames = sorted(glob.glob(os.path.join(TEX, fset + "[0-9][0-9][0-9].png")))[10:]
    if not frames:
        raise SystemExit("no frames for " + fset)
    px = 512
    paths = " ".join("textures/coop_fx/fx/" + os.path.basename(f) for f in frames)
    sh += [name, "{", "\tqer_hzmSoftEdge %d" % max(16, min(128, int(0.4 * world))), "\tcull none",
           "\tspriteGen parallel_oriented", "\tspritescale %g" % (float(world) / px), "\t{",
           "\t\tanimMapOnce %g %s" % (fps, paths), "\t\tblendfunc blend", "\t\trgbGen vertex", "\t\talphaGen vertex",
           "\t}", "}", ""]
    tab += ["%s %s.spr" % (f, name) for f in froms]
open(os.path.join(LAYER, "scripts", "coop_fx_p1_remap.shader"), "w", encoding="latin-1", newline="\n").write("\n".join(sh))
open(os.path.join(LAYER, "scripts", "coop_sprremap.txt"), "w", encoding="latin-1", newline="\n").write("\n".join(tab) + "\n")
print("remap:", ", ".join("%s<-%s" % (r[0], "+".join(r[4])) for r in R))
