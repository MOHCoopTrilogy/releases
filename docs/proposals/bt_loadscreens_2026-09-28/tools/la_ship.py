"""la_ship.py - build the STAGED mod files for the loading-art pool (nothing is written into hzm-mohaa-coop-mod).

    python la_ship.py <picks.json> <stage_dir>

stage_dir mirrors the mod tree:
  textures/mohmenu/hzmload/<id>.jpg   2048x1024 RGB JPEG (q90). The torn card is baked onto black: the widget's
                                      backdrop is black, so no alpha is needed and JPEG (not 24/32-bit TGA) keeps
                                      the pak small. New file names: no retail/mod .dds or .tga shares them, so the
                                      engine's .dds-first lookup (TRAPS) cannot pick up anything else. Not a TGA,
                                      so the bottom-up rule (bug-3019) does not apply.
                                      The card is 608:327 on screen; the texture is stored 2:1 and the widget rect
                                      restores the aspect (a plain resample, no crop).
  scripts/coop_loadart.shader         one hzmLoadArt_<id> shader per image (nopicmip, force32bit, clampMap)
  ui/loadart.txt                      the pool: art lines from picks.json tags + the map rules below
The loadingbar.txt widgets are inserted by apply_mod.py (the file is shared with other features).
"""
import json, os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import la_treat as T  # noqa: E402

TEX_DIR = "textures/mohmenu/hzmload"
W, H = 2048, 1024

# First matching rule wins (engine: UI_LoadArt_Begin). Themes checked against each BSP's worldspawn title and its
# snow/sand shader counts (README, "Map rules"). '-' = the map keeps its own loading screen.
MAP_RULES = """// maps that keep their OWN loading screen
map m1l1 -                               // the mod's own m1l1 screen (ui/loading_m1l1.urc) stays
map m3l1a -                              // Omaha Beach: its own screen, by rule (sensitive area)
map m3l1b -
map e3l4_arena -                         // the mod's own arena screen
// Allied Assault
map m1l* desert !snow                    // Algeria / Operation Torch: any desert image
map m2l* aa !desert                      // Norway: Trondheim, the U-529 pens (snow on m2l1 / m2l3)
map m3l* aa green !desert !snow          // Normandy: bocage, Nebelwerfer hunt
map m4l* aa green !desert !snow          // occupied France
map m5l* aa green !desert !snow          // Brest, the King Tiger, the bridge
map m6l* snow !desert                    // Siegfried Forest and Fort Schmerzen: any winter image
// Spearhead
map t1l* green !desert !snow             // Normandy (night drop): the Normandy images
map t2l* snow !desert                    // Bastogne: any winter image
map t3l* -                               // Berlin: its own screen until a Berlin image passes QA (2 attempts failed)
// Breakthrough
map e1l* desert !snow                    // Tunisia: any desert image
map e2l* bt italy !snow !desert          // Sicily
map e3l* bt italy !snow !desert          // Italy
// Mission briefings (maps/briefing/*): same theatre as the mission they brief
map briefing/briefing1 desert !snow
map briefing/briefing2 aa !desert
map briefing/briefing3 aa green !desert !snow
map briefing/briefing4 aa green !desert !snow
map briefing/briefing5 aa green !desert !snow
map briefing/briefing6 snow !desert
map briefing/briefinge1 desert !snow
map briefing/briefinge2 bt italy !snow !desert
map briefing/briefinge3 bt italy !snow !desert
map briefing/briefingt1 green !desert !snow
map briefing/briefingt2 snow !desert
map briefing/briefingt3 -                // Berlin: same as t3l*
// Everything else (co_lobby1-8, dm/*, obj/*, training, any other map): the WHOLE pool at random, so the stock
// loading_default / retail Breakthrough card never shows. MUST stay the last rule (first match wins).
map *
"""


def build(picks, stage):
    tex = os.path.join(stage, *TEX_DIR.split("/"))
    os.makedirs(tex, exist_ok=True)
    os.makedirs(os.path.join(stage, "scripts"), exist_ok=True)
    os.makedirs(os.path.join(stage, "ui"), exist_ok=True)
    sh = ["// HZM coop [user 2026-09-28] LOADING-SCREEN ART POOL - generated by",
          "// docs/proposals/bt_loadscreens_2026-09-28/tools/la_ship.py. One shader per image; ui/loadart.txt picks one per",
          "// load (the exe's UI_LoadArt_Begin) and ui/loadingbar.txt's hzm_loadart widget draws it (linkcvartoshader).",
          "// Art: real in-engine captures of staged Allied-vs-Axis scenes, finished offline (aged-photo card). No text.",
          ""]
    art = ["// HZM coop [user 2026-09-28] LOADING-SCREEN ART POOL (read by the exe at every load: UI_LoadArt_Begin).",
           "// Generated by docs/proposals/bt_loadscreens_2026-09-28/tools/la_ship.py - edit picks.json / MAP_RULES there.",
           "//   art <shader> <tags...>          map <name>[*] <tag | !tag | -> ...   (first matching map rule wins)",
           "// A map rule's pool = images carrying ANY plain tag and NONE of the !tags. '-' = the map's own screen.",
           ""]
    total = 0
    for p in picks:
        card, _menu = T.treat(p["src"], os.path.join(stage, "_tmp_" + p["id"]), p.get("look", "photo"),
                              tuple(p["crop"]) if p.get("crop") else None, p.get("seed", 1), p.get("exp", 0.0))
        bg = Image.new("RGB", card.size, (0, 0, 0))
        bg.paste(card, (0, 0), card)
        img = bg.resize((W, H), Image.LANCZOS)
        out = os.path.join(tex, p["id"] + ".jpg")
        img.save(out, quality=90, optimize=True, subsampling=0)
        total += os.path.getsize(out)
        for f in ("_card.png", "_menu1280.png"):
            try:
                os.remove(os.path.join(stage, "_tmp_" + p["id"] + f))
            except OSError:
                pass
        name = "hzmLoadArt_" + p["id"]
        sh += ["// %s" % p.get("title", ""), name, "{", "\tnopicmip", "\tcull none", "\tforce32bit",
               "\tsurfaceparm nolightmap", "\t{", "\t\tclampMap %s/%s.jpg" % (TEX_DIR, p["id"]), "\t}", "}", ""]
        art.append("art %-28s %s" % (name, " ".join(p["tags"])))
    art += ["", MAP_RULES]
    open(os.path.join(stage, "scripts", "coop_loadart.shader"), "w", newline="\r\n").write("\n".join(sh))
    open(os.path.join(stage, "ui", "loadart.txt"), "w", newline="\r\n").write("\n".join(art))
    for fn in (os.path.join(stage, "scripts", "coop_loadart.shader"), os.path.join(stage, "ui", "loadart.txt")):
        assert all(b < 128 for b in open(fn, "rb").read()), fn
    print("images %d, %.1f MB of JPEG" % (len(picks), total / 1048576.0))


if __name__ == "__main__":
    build(json.load(open(sys.argv[1])), sys.argv[2])
