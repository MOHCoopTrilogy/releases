"""make_grease_tik.py - models/weapons/coop_greasegun_ai.tik: the M3 grease gun for an AI paratrooper.
Source: models/weapons/greasegun.tik of zzzzz_xw_weapons.pk3 (the players' M3: mesh greaser.skd, sound greasegun_fire).
That file is a PLAYER weapon: its weapongroup is xw_greasegun, for which an actor has no animation set (anim/*.scr
switch on the weapon group / the stripped name and fall to the default). Two fields change:
    name         "Thompson (M3 Grease Gun)"   every consumer strips ' (' and gets "thompson" (TRAPS, weapon variant suffixes)
    weapongroup  thompson                      the actor aims, fires and reloads it with the Thompson's clips
A NEW file name: nothing retail or imported is overridden. Given to the trooper AFTER `gun "thompson"` has built his
body, with aihandler.scr::coop_actorArm (bug-3306: never `gun <tik>`). Paratroopers `dontdropweapons`, so it never
lies on the ground as a pickup.   --check = compare with the file in the mod tree, write nothing."""
import io, os, re, sys, zipfile
PAK = r"G:\GOG\Medal of Honor - Allied Assault War Chest\maintt\zzzzz_xw_weapons.pk3"
OUT = "C:/mohaa-coop-dev/hzm-mohaa-coop-mod/models/weapons/coop_greasegun_ai.tik"
src = zipfile.ZipFile(PAK).read("models/weapons/greasegun.tik").decode("latin-1").replace("\r\n", "\n")
assert src.startswith("TIKI")
n1 = len(re.findall(r'(?m)^(\s*name\s+)"M3 Grease Gun"', src))
n2 = len(re.findall(r"(?m)^(\s*weapongroup\s+)xw_greasegun", src))
assert n1 == 1 and n2 == 1, (n1, n2)
out = re.sub(r'(?m)^(\s*name\s+)"M3 Grease Gun"', r'\1"Thompson (M3 Grease Gun)"', src)
out = re.sub(r"(?m)^(\s*weapongroup\s+)xw_greasegun", r"\1thompson", out)
head = ("TIKI\n"
        "// HZM coop: the M3 grease gun in the hands of an AI paratrooper (coop_mod/paradrop.scr, coop_paraGreaseChance).\n"
        "// GENERATED by docs/proposals/para_30cal_2026-10-12/tools/pass3/make_grease_tik.py from the players' own\n"
        "// models/weapons/greasegun.tik (zzzzz_xw_weapons.pk3): the name strips to \"thompson\" and the weapon group is\n"
        "// thompson, so an actor holds, fires and reloads it with the Thompson's animations. A new name on purpose:\n"
        "// nothing is overridden. Do not give this to a player.\n")
out = head + out[len("TIKI\n"):]
assert all(ord(c) < 128 for c in out)
if "--check" in sys.argv:
    cur = io.open(OUT, encoding="latin-1", newline="").read().replace("\r\n", "\n")
    print("check:", "same" if cur == out else "DIFFERENT")
    sys.exit(0 if cur == out else 1)
io.open(OUT, "w", encoding="latin-1", newline="\n").write(out)
print("wrote", OUT, len(out.splitlines()), "lines")
