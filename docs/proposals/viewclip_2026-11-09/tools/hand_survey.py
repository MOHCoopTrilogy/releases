"""viewclip - the HAND-INTO-CAMERA survey (class C): clips that pose a hand (or sleeve) so close to the eye that it fills the view
as a big, crumpled, low-poly shape. Not a near-plane cut - identical before and after the projection fix - so it is ranked
separately, to re-pose the worst clips first.

Per clip (clip_survey's rows and camera rules: hip = the eye bone looking along model +x; aim rows = the held ADS correction),
every sampled frame rasterises the ARM triangles (hands, sleeves) that are nearer than NEAR u into a 16:9 view (cg_fov 80, Hor+)
and measures:
  near_cover   share of the whole view covered by arm triangles nearer than NEAR u
  centre_cover the same inside the centre box (the middle 40 % x 40 %) - where it hides the target
  arm_min      closest arm vertex, u
Score = max over frames of centre_cover * 2 + near_cover.

    python hand_survey.py [row ...]     -> ../assets/hand_survey.tsv (GENERATED), worst first
"""
import os, sys, json, math, time
import numpy as np
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import clip_survey as CS   # noqa: E402
V, H, IS, R = CS.V, CS.H, CS.IS, CS.R

NEAR = 6.0
W, HT = 192, 108
TV = CS.TV
TH = TV * 16 / 9.0


def frame_cover(surfs, E):
    im = Image.new('L', (W, HT), 0)
    d = ImageDraw.Draw(im)
    amin = 1e9
    for s in surfs:
        if s.get('gun'):
            continue
        c = s['P'] - E
        if np.abs(c).max() > 5000:
            continue
        dist = np.linalg.norm(c, axis=1)
        amin = min(amin, float(dist.min()))
        x = c[:, 0]
        ok = (x > 0.2) & (dist < NEAR)
        if not ok.any():
            continue
        sx = W / 2 + (-c[:, 1] / np.maximum(x, 0.2)) / TH * (W / 2)
        sy = HT / 2 - (c[:, 2] / np.maximum(x, 0.2)) / TV * (HT / 2)
        for tri in s['tri']:
            if ok[tri].all():
                d.polygon([(float(sx[i]), float(sy[i])) for i in tri], fill=255)
    a = np.asarray(im) > 0
    cw, ch = int(W * 0.3), int(HT * 0.3)
    return float(a.mean()), float(a[ch:HT - ch, cw:W - cw].mean()), amin


def measure(row, clip_path, key, ctl, corr):
    tik = V.SIGHTS[key]['tik']
    clip = R.load(R.ANIM + clip_path)
    anim = CS.gun_anim(row)
    best = dict(score=0.0, near=0.0, centre=0.0, f=-1, amin=1e9)
    frames = sorted(set(list(range(0, clip.numFrames, max(1, clip.numFrames // CS.SAMPLES))) + [clip.numFrames - 1]))
    for f in frames:
        t = f * clip.frameTime
        try:
            surfs, E, Wb = V.scene2(R.pose_dict(clip, f), key, tik, anim, t, ctl, corr, None, None)
        except Exception:
            surfs, E, Wb = V.scene2(R.pose_dict(clip, f), key, tik, 'idle', t, ctl, corr, None, None)
        nc, cc, amin = frame_cover(surfs, E)
        best['amin'] = min(best['amin'], amin)
        sc = 2 * cc + nc
        if sc > best['score']:
            best.update(score=sc, near=nc, centre=cc, f=f)
    return best


def main():
    rows = H.fps_rows()
    want = sys.argv[1:] or [k for k in rows if '_' in k and not k.endswith('_disabled') and not k.startswith('$')]
    ctl = json.load(open(os.path.join(CS.BOLT, '..', 'assets', 'ctl_stand.json')))
    corrs, out = {}, []
    t0 = time.time()
    for row in want:
        pre = row.split('_')[0]
        key = IS.PREFIX.get(pre)
        if pre in ('cv', 'coopr'):
            rest = row.split('_', 1)[1]
            hits = [k for k in V.SIGHTS if rest == k or rest.startswith(k + '_')]
            key = max(hits, key=len) if hits else None
            pre = '%s_%s' % (pre, key) if key else pre
        if key is None or key not in V.SIGHTS:
            continue
        corr = None
        if CS.is_ads(row):
            if pre not in corrs:
                try:
                    corrs[pre] = CS.aim_corr(pre, rows, key, ctl)
                except Exception:
                    corrs[pre] = None
            corr = corrs[pre]
            if corr is None:
                continue
        try:
            b = measure(row, rows[row], key, ctl, corr)
        except Exception as e:
            print('ERR', row, repr(e)[:80])
            continue
        out.append((b['score'], row, rows[row], key, 'ADS' if corr is not None else 'hip', b))
    out.sort(key=lambda o: -o[0])
    p = os.path.join(HERE, '..', 'assets', 'hand_survey.tsv')
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# GENERATED by tools/hand_survey.py - do not edit. cover = share of the 16:9 view under arm triangles nearer than '
                '%.0f u (centre = the middle 40%% box); score = 2*centre + near, worst frame\n' % NEAR)
        f.write('score\trow\tclip\tgun\tcamera\tnear_cover\tcentre_cover\tarm_min\tworst_frame\n')
        for sc, row, clip, key, cam, b in out:
            f.write('%.3f\t%s\t%s\t%s\t%s\t%.3f\t%.3f\t%.1f\t%d\n' % (sc, row, clip, key, cam, b['near'], b['centre'], b['amin'], b['f']))
    print('wrote %s: %d rows, %.0f s' % (p, len(out), time.time() - t0))
    for o in out[:25]:
        print('%.3f %-36s %-4s near %.2f centre %.2f arm %.1f f%d' % (o[0], o[1], o[4], o[5]['near'], o[5]['centre'], o[5]['amin'], o[5]['f']))


if __name__ == '__main__':
    main()
