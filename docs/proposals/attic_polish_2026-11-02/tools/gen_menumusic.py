"""gen_menumusic.py <mod dir> - the main-menu theme playlist (ui/coop_menumusic/*.cfg), rebuilt with a persisted pick.

The original gen_menumusic.py (bug-2570) is lost; this rebuilds the same files from the THEMES table below and adds the
gramophone's pick (user 2026-11-02: "switching picks that theme now; offer a Random record/position in the cycle so they can
return to randomized (persist the choice) - random stays the default for new players").

  t<n>.cfg   the ENGINE's per-launch roll (S_TriggeredMusic_PlayIntroMusic counts t0.. up to the first missing file and execs one
             at random). It only records the rolled theme and hands over to the player's pick:  ui_mmBoot = "vstr ui_mmRoll" (random,
             the default seeded in coop_defaults.cfg) or "exec ui/coop_menumusic/p<k>.cfg" (a record the player put on).
  p<n>.cfg   play theme n now (title / game cvars, Prev / Next = p<n-1> / p<n+1> for the engine's auto-advance at the end of a track,
             seta ui_menuMusicLast, menumusic_play).  Never changes the pick.
  u<n>.cfg   the PLAYER picks theme n (gramophone / flat-menu arrows): persists ui_mmBoot / ui_mmSelPrev / ui_mmSelNext / ui_mmShuffle, plays it.
  ur.cfg     the PLAYER picks shuffle: ui_mmBoot back to the roll, and the next theme starts so the click is heard.
Cycle (ui_mmSelNext / ui_mmSelPrev): SHUFFLE -> record 1 .. record N -> SHUFFLE."""
import os, sys

THEMES = [  # (mp3, title, game) - the six themes as shipped by bug-2570, + two stock AA songs (v1.10.63)
    ("sound/music/coop_menu/moh1999_main_theme.mp3", "Main Theme", "Medal of Honor", "Main Theme|Medal of Honor"),
    ("sound/music/coop_menu/mohu_may_10th_1940.mp3", "May 10th, 1940", "Medal of Honor: Underground", "May 10th, 1940|Underground"),
    (None, "Main Theme", "Medal of Honor: Allied Assault", "Main Theme|Allied Assault"),
    (None, "Main Theme", "Medal of Honor: Frontline", "Main Theme|Frontline"),
    (None, "Dogs of War: Main Title", "Medal of Honor: European Assault", "Dogs of War|European Assault"),
    ("sound/music/coop_menu/mohab_main_theme.mp3", "Main Theme", "Medal of Honor: Airborne", "Main Theme|Airborne"),
    # v1.10.63 (user): two stock Allied Assault songs. The radio swing (main/sound/mechanics/Mec_RadioMusic_01.wav, the m2l1 / m6l2a
    # radios) has no published title, so a plain descriptive one; the menu player takes only sound/music/*.mp3 (snd_openal_new.cpp
    # S_MenuMusic_Start), so gen_gram_art.py converts the stock WAV to this mp3 in the menus3d pak.  The m5l1b medic dance is a stock
    # mp3 already (main/sound/music/medicdance.mp3): played from main as is.
    ("sound/music/coop_menu/mohaa_radio_music.mp3", "On the Wireless", "Medal of Honor: Allied Assault", "On the Wireless|Allied Assault"),
    ("sound/music/medicdance.mp3", "Medic Dance", "Medal of Honor: Allied Assault", "Medic Dance|Allied Assault"),
]   # (mp3, title, game, the record sleeve's short "title|game" (gen_gram_art.py prints it on hzm_gram_sleeve<n>))
SHUFFLE = "SHUFFLE"
D = "ui/coop_menumusic/"


def main(mod):
    out = os.path.join(mod, "ui", "coop_menumusic")
    n = len(THEMES)
    themes = []
    for i, (mp3, title, game, short) in enumerate(THEMES):
        if mp3 is None:     # read the track from the shipped t<i>.cfg (first build) or p<i>.cfg (rebuilds)
            for src in ("p%d.cfg" % i, "t%d.cfg" % i):
                p = os.path.join(out, src)
                if os.path.exists(p):
                    for l in open(p, encoding="latin-1"):
                        if l.startswith("set ui_menuMusic "):
                            mp3 = l.split(None, 2)[2].strip()
                    if mp3:
                        break
        assert mp3, "no track for theme %d" % i
        themes.append((mp3, title, game, short))
    hdr = "// HZM coop [bug-2570, gramophone 2026-11-02] main-menu theme %s - GENERATED by docs/proposals/attic_polish_2026-11-02/tools/gen_menumusic.py, do not hand-edit\n"
    for i, (mp3, title, game, short) in enumerate(themes):
        w = lambda name, body: open(os.path.join(out, name), "w", newline="\n").write(body)  # noqa: E731
        w("t%d.cfg" % i, hdr % ("%d of %d: the engine's launch roll" % (i + 1, n)) +
          'set ui_mmRoll "exec %sp%d.cfg"\nvstr ui_mmBoot\n' % (D, i))
        w("p%d.cfg" % i, hdr % ("%d of %d: play it" % (i + 1, n)) +
          'set ui_menuMusic %s\nset ui_menuMusicTitle "%s"\nset ui_menuMusicGame "%s"\n' % (mp3, title, game) +
          'set ui_mmSleeve "textures/menu/hzm_gram_sleeve%d"\nset ui_mmLabel "textures/menu/hzm_gram_label%d"\n' % (i, i) +
          'set ui_menuMusicPrev "exec %sp%d.cfg"\nset ui_menuMusicNext "exec %sp%d.cfg"\nseta ui_menuMusicLast %d\nmenumusic_play\n'
          % (D, (i - 1) % n, D, (i + 1) % n, i))
        nxt = "u%d" % (i + 1) if i + 1 < n else "ur"
        prv = "u%d" % (i - 1) if i > 0 else "ur"
        w("u%d.cfg" % i, hdr % ("%d of %d: the player's pick" % (i + 1, n)) +
          'seta ui_mmBoot "exec %sp%d.cfg"\nseta ui_mmSelNext "exec %s%s.cfg"\nseta ui_mmSelPrev "exec %s%s.cfg"\nseta ui_mmShuffle 0\nexec %sp%d.cfg\n'
          % (D, i, D, nxt, D, prv, D, i))
    open(os.path.join(out, "ur.cfg"), "w", newline="\n").write(
        hdr % "shuffle: the player's pick" +
        'seta ui_mmBoot "vstr ui_mmRoll"\nseta ui_mmSelNext "exec %su0.cfg"\nseta ui_mmSelPrev "exec %su%d.cfg"\nseta ui_mmShuffle 1\nvstr ui_menuMusicNext\n'
        % (D, D, n - 1))
    print("wrote", sorted(os.listdir(out)))
    return n


DEFAULTS = ('// MAIN-MENU THEME PICK (attic gramophone, flat-menu arrows; ui/coop_menumusic/*.cfg, gen_menumusic.py). Shuffle = a random theme\n'
            '// every launch (the default); a record the player puts on is kept: ui_mmBoot = "exec ui/coop_menumusic/p<n>.cfg".\n'
            'seta ui_mmBoot "vstr ui_mmRoll"\n'
            'seta ui_mmSelNext "exec ui/coop_menumusic/u0.cfg"\n'
            'seta ui_mmSelPrev "exec ui/coop_menumusic/u%d.cfg"\n'
            'seta ui_mmShuffle 1\n')


def seed_defaults(mod, n):
    p = os.path.join(mod, "coop_defaults.cfg")
    t = open(p, encoding="latin-1", newline="").read()
    nl = "\r\n" if "\r\n" in t else "\n"
    block = (DEFAULTS % (n - 1)).replace("\n", nl)
    import re
    t = re.sub(r"// MAIN-MENU THEME PICK .*?seta ui_mm(?:Slot \"[^\"]*\"|Shuffle \d)" + re.escape(nl), "", t, flags=re.S)
    anchor = "seta ui_atticMain 1" + nl
    assert anchor in t
    t = t.replace(anchor, anchor + block, 1)
    open(p, "w", encoding="latin-1", newline="").write(t)
    print("coop_defaults.cfg seeded")


if __name__ == "__main__":
    mod = sys.argv[1]
    seed_defaults(mod, main(mod))
