"""gen_ng_tags.py <out dir> - re-draw the New Game wall-map campaign tags + their shader WITHOUT re-running the whole
make_newgame3d.py chain: tag() and CAMPAIGNS are taken from make_newgame3d.py's own source (one definition, no copy), and the
shader text is the same as that generator writes (now mip-mapped, D-N4)."""
import ast, os, sys
from PIL import Image, ImageDraw, ImageFilter, ImageFont  # noqa: F401  (used by the exec'd tag())

SRC = r"C:\mohaa-coop-dev\docs\proposals\mphub3d_2026-11-02\newgame\make_newgame3d.py"
out = sys.argv[1]
tree = ast.parse(open(SRC, encoding="utf-8").read())
ns = {"Image": Image, "ImageDraw": ImageDraw, "ImageFilter": ImageFilter, "ImageFont": ImageFont, "os": os, "FONTS": r"C:\Windows\Fonts"}
for node in tree.body:
    if isinstance(node, ast.FunctionDef) and node.name == "tag" or isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "CAMPAIGNS" for t in node.targets):
        exec(compile(ast.Module([node], []), SRC, "exec"), ns)
tdir, sdir = os.path.join(out, "textures", "menu"), os.path.join(out, "scripts")
os.makedirs(tdir, exist_ok=True)
os.makedirs(sdir, exist_ok=True)
shader = ["// [newgame3d] campaign tags on the attic wall map (generated by make_newgame3d.py)"]
for key, name, sub, _m, cv in ns["CAMPAIGNS"]:
    for lk in ((False, True) if cv else (False,)):
        nm = "hzm_ng_tag_%s%s" % (key, "_lk" if lk else "")
        ns["tag"](name, sub, lk).save(os.path.join(tdir, nm + ".tga"))
        shader.append("textures/menu/%s\n{\n\tnopicmip\n\tcull none\n\t{\n\t\tclampmap textures/menu/%s.tga\n\t\tblendFunc blend\n\t\trgbGen identity\n\t}\n}" % (nm, nm))
open(os.path.join(sdir, "hzm_newgame3d.shader"), "w", newline="\n").write("\n".join(shader) + "\n")
print("ng tags ->", out)
