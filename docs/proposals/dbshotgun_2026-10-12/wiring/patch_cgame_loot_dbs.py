"""ENGINE (cgame only) - the double barrel's own use-to-loot picture. Applied on branch dbshotgun-next by this lane.

    python wiring/patch_cgame_loot_dbs.py <engine worktree>        (idempotent)

1. code/cgame/cg_coopfeed.c: the icon lookup cut the name at " (" BEFORE looking it up ("<Base Gun> (<Finish>)" is
   the same gun), so "Shotgun (Double Barrel)" could only ever show the trench gun. Now the FULL name is tried first
   and the cut name second - a finish still falls through to its base gun, and no existing row has a " (" name.
2. code/cgame/cg_coopfeed_loot.h: one row. The header is generated by
   docs/proposals/use_pickup_2026-10-05/tools/build_icons.py, whose input (sil/meta.json) is not in the repository,
   so the generator could not be re-run: the row is inserted here and must be added to that tool's weapon list when
   its inputs are back (keyed by weapon NAME; texture textures/hud/loot/w_dbshotgun.tga, 512 x 256 RLE, made by
   tools/dbs_icon.py from our mesh in the existing icons' measured colours).
"""
import os, sys

ROW = '    {"Shotgun (Double Barrel)", "w_dbshotgun", "Double Barrel", 0.801f, 0.469f}, // HZM coop [dbshotgun]: full-name row (cg_coopfeed.c tries the full name first)\n'
OLD = '''            Q_strncpyz(artName, cs ? cs : "", sizeof(artName));
            p = strstr(artName, " (");
            if (p) {
                *p = 0; // "<Base Gun> (<Finish>)" is the same gun
            }
            for (i = 0; i < LOOT_ART_N; i++) {
                if (!Q_stricmp(artName, s_lootArt[i].name)) {
                    artIdx = i;
                    break;
                }
            }
'''
NEW = '''            Q_strncpyz(artName, cs ? cs : "", sizeof(artName));
            // HZM coop [dbshotgun 2026-10-13] the FULL name first: a gun that is its own weapon although its name
            // carries a " (..)" part ("Shotgun (Double Barrel)") has its own picture row
            for (i = 0; i < LOOT_ART_N; i++) {
                if (!Q_stricmp(artName, s_lootArt[i].name)) {
                    artIdx = i;
                    break;
                }
            }
            p = (artIdx < 0) ? strstr(artName, " (") : NULL;
            if (p) {
                *p = 0; // "<Base Gun> (<Finish>)" is the same gun
            }
            for (i = 0; i < LOOT_ART_N && artIdx < 0; i++) {
                if (!Q_stricmp(artName, s_lootArt[i].name)) {
                    artIdx = i;
                    break;
                }
            }
'''


def edit(path, fn):
    raw = open(path, 'rb').read()
    nl = '\r\n' if b'\r\n' in raw else '\n'
    s = raw.decode('latin-1').replace('\r\n', '\n')
    t = fn(s)
    if t != s:
        open(path, 'wb').write(t.replace('\n', nl).encode('latin-1'))
    return t != s


def c_file(s):
    if 'the FULL name first' in s:
        return s
    assert s.count(OLD) == 1
    return s.replace(OLD, NEW)


def h_file(s):
    if 'w_dbshotgun' in s:
        return s
    a = '    {"Shotgun", "w_shotgun", "Shotgun", '
    k = s.index(a)
    e = s.index('\n', k) + 1
    return s[:e] + ROW + s[e:]


def main():
    root = sys.argv[1]
    print('cg_coopfeed.c', edit(os.path.join(root, 'code', 'cgame', 'cg_coopfeed.c'), c_file))
    print('cg_coopfeed_loot.h', edit(os.path.join(root, 'code', 'cgame', 'cg_coopfeed_loot.h'), h_file))


if __name__ == '__main__':
    main()
