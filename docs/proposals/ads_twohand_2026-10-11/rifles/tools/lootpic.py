"""Loot-feed / use-prompt picture for the iron-sight G43, made the way every other gun's is: the side silhouette of
its OWN mesh (use_pickup lane: meshsil.py + build_icons.py, used as libraries - neither is edited, nothing is written
into that lane's folder). The staged mesh / tik are read from rifles/assets first.

    python lootpic.py
-> ../assets/textures/hud/loot/w_g43irons.tga   (+ ../evidence/g43irons/loot_w_g43irons.png, beside the scoped G43's)
   ../wire/cg_coopfeed_loot_g43irons.txt        the table row for code/cgame/cg_coopfeed_loot.h (a GENERATED file of
                                                the use_pickup lane: the row belongs in its weapons.json / SHORT list)
"""
import os, sys, json
import numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
UP = r"C:\mohaa-coop-dev\docs\proposals\use_pickup_2026-10-05\tools"
ASSETS = os.path.normpath(os.path.join(HERE, '..', 'assets'))
SP = os.path.join(os.environ.get('TEMP', r'C:\Temp'), 'claude', 'C--mohaa-coop-dev', '7ee3b4ee-deea-4563-b7bc-c7746a82f4e9', 'scratchpad', 'lootpic')
sys.path.insert(0, UP)
os.chdir(UP)
import meshsil                      # noqa: E402  (imports docs/tools/weapon_hd/vfs.py)
import vfs                          # noqa: E402
_read = vfs.read


def read(vpath, which=-1):
    f = os.path.join(ASSETS, vpath.replace('/', os.sep))
    if os.path.isfile(f):
        return open(f, 'rb').read()
    return _read(vpath, which)


vfs.read = read
meshsil.vfs.read = read
import build_icons as BI            # noqa: E402
from overrides import OVR           # noqa: E402

BASE, TIK, SHORT = "G 43 Irons", "coop_g43_irons", "G43 Irons"


def sil(base, tik, o):
    r = meshsil.silhouette("models/weapons/%s.tik" % tik, skip=o.get("skip", ()), keep_all=o.get("keep_all", False), axes=o.get("axes"),
                           mainbone=o.get("mainbone", False), turn=o.get("turn", (0.0, 0.0)), only=o.get("only", ()))
    assert r is not None, base
    im, sc, d = r
    a = meshsil.orient(np.array(im) > 127)
    if o.get("flipx"):
        a = a[:, ::-1]
    if o.get("flipy"):
        a = a[::-1, :]
    stem = "".join(c for c in base.lower() if c.isalnum())
    os.makedirs(os.path.join(SP, 'sil'), exist_ok=True)
    Image.fromarray((a * 255).astype(np.uint8)).save(os.path.join(SP, 'sil', stem + '.png'))
    print("%-12s len=%5.1f u  anim=%s bones %s/%s" % (base, a.shape[1] / sc, d["anim"], d["covered"], d["need"]))
    return stem, a.shape[1] / sc


def main():
    o = OVR.get("G 43", {})          # the scoped G43's overrides (same body)
    BI.HERE = SP
    out = {}
    for base, tik in ((BASE, TIK), ("G 43", "g43")):
        stem, units = sil(base, tik, o)
        im = BI.weapon_icon(stem, units, close=o.get("close", 0), slit=o.get("slit", 0.0))
        out[base] = (stem, im, BI.vis(im))
    stem, im, (vw, vh) = out[BASE]
    d = os.path.join(ASSETS, 'textures', 'hud', 'loot')
    os.makedirs(d, exist_ok=True)
    im.save(os.path.join(d, 'w_%s.tga' % stem), compression='tga_rle')
    ev = os.path.normpath(os.path.join(HERE, '..', 'evidence', 'g43irons'))
    sheet = Image.new('RGB', (512, 2 * 256 + 12), (52, 60, 52))
    for k, b in enumerate((BASE, "G 43")):
        sheet.paste(out[b][1], (0, k * 268), out[b][1])
    sheet.save(os.path.join(ev, 'loot_w_g43irons.png'))
    row = '    {"%s", "w_%s", "%s", %.3ff, %.3ff},' % (BASE, stem, SHORT, vw, vh)
    open(os.path.normpath(os.path.join(HERE, '..', 'wire', 'cg_coopfeed_loot_g43irons.txt')), 'w', newline='\n').write(
        '// row for code/cgame/cg_coopfeed_loot.h, after the "G 43" row (the file is GENERATED by the use_pickup lane\'s\n'
        '// build_icons.py: add "G 43 Irons" -> tik coop_g43_irons to its weapons.json and "G 43 Irons": "G43 Irons" to SHORT,\n'
        '// or paste this row; the texture is rifles/assets/textures/hud/loot/w_%s.tga)\n' % stem + row + '\n')
    print(row)
    print('scoped G43 for comparison: vis %.3f x %.3f' % out["G 43"][2])


if __name__ == '__main__':
    main()
